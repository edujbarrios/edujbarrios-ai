args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(args)==0L) stop("run with Rscript")
source(file.path(dirname(normalizePath(sub("^--file=","",args[[1L]]))),"cross_modal_attention.R"))
bad <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e) TRUE))
q <- c(1,0); k <- c(1,0,0,1); v <- c(10,0,0,20)
a <- exp(1/sqrt(2))/(1+exp(1/sqrt(2)))
result <- cross_modal_attention(q,k,v,2,2)
stopifnot(abs(result$weights[[1]]-a)<1e-12)
stopifnot(abs(result$weights[[2]]-(1-a))<1e-12)
stopifnot(abs(result$context[[1]]-10*a)<1e-12)
stopifnot(abs(result$context[[2]]-20*(1-a))<1e-12)
uniform <- cross_modal_attention(c(0,0),k,v,2,2)
stopifnot(identical(uniform$weights,c(0.5,0.5)))
stopifnot(identical(uniform$context,c(5,10)))
stopifnot(identical(cross_modal_attention(q,k[1:2],v[1:2],1,2)$weights,1))
bad(cross_modal_attention(q,k,v,0,2))
bad(cross_modal_attention(q,k,v,65,2))
bad(cross_modal_attention(q,k,v,2,0))
bad(cross_modal_attention(c(NaN,0),k,v,2,2))
bad(cross_modal_attention(q,c(1,1001,0,1),v,2,2))
bad(cross_modal_attention(q,k,v[-4],2,2))
cat("R cross-modal attention tests passed\n")
