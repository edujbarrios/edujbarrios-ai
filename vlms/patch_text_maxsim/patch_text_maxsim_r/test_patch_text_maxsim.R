args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(args)==0L) stop("run with Rscript")
source(file.path(dirname(normalizePath(sub("^--file=","",args[[1L]]))),
                 "patch_text_maxsim.R"))
bad <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e) TRUE))
p <- c(1,0,0,1)
t <- c(1,0,0.6,0.8)
result <- patch_text_maxsim(p,2,t,2,2)
stopifnot(identical(result$matches,c(0L,1L)))
stopifnot(abs(result$score-0.9)<1e-12)
result <- patch_text_maxsim(c(1,0,1,0),2,c(1,0),1,2)
stopifnot(identical(result$matches,0L))
stopifnot(abs(result$score-1)<1e-12)
result <- patch_text_maxsim(c(0,1),1,c(0,-1),1,2)
stopifnot(identical(result$matches,0L))
stopifnot(abs(result$score+1)<1e-12)
bad(patch_text_maxsim(p,0,t,2,2))
bad(patch_text_maxsim(p,33,t,2,2))
bad(patch_text_maxsim(p,2,t,0,2))
bad(patch_text_maxsim(p,2,t,2,65))
bad(patch_text_maxsim(c(0,0,0,1),2,t,2,2))
bad(patch_text_maxsim(c(NaN,0,0,1),2,t,2,2))
bad(patch_text_maxsim(c(1001,0,0,1),2,t,2,2))
bad(patch_text_maxsim(p,2,t[-4],2,2))
cat("R patch-text MaxSim tests passed\n")
