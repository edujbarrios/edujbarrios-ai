file_arg <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(file_arg)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",file_arg[[1L]])))
source(file.path(folder,"image_text_recall_at_k.R"))
expect_error <- function(expr) {
  failed <- tryCatch({force(expr);FALSE},error=function(e) TRUE)
  stopifnot(failed)
}
aligned <- c(1,0,0,1)
swapped <- c(0,1,1,0)
duplicates <- c(1,0,1,0)
stopifnot(identical(image_text_recall_at_k(aligned,aligned,2,2,1),c(1,1)))
stopifnot(identical(image_text_recall_at_k(aligned,swapped,2,2,1),c(0,0)))
stopifnot(identical(image_text_recall_at_k(aligned,swapped,2,2,2),c(1,1)))
stopifnot(identical(image_text_recall_at_k(duplicates,duplicates,2,2,1),c(.5,.5)))
stopifnot(identical(image_text_recall_at_k(c(2,0,0,3),aligned,2,2,1),c(1,1)))
expect_error(image_text_recall_at_k(aligned,aligned,1,2,1))
expect_error(image_text_recall_at_k(aligned,aligned,2,0,1))
expect_error(image_text_recall_at_k(aligned,aligned,2,129,1))
expect_error(image_text_recall_at_k(aligned,aligned,2,2,0))
expect_error(image_text_recall_at_k(aligned,aligned,2,2,3))
expect_error(image_text_recall_at_k(aligned,c(0,0,0,1),2,2,1))
expect_error(image_text_recall_at_k(aligned,c(1,0,Inf,1),2,2,1))
expect_error(image_text_recall_at_k(aligned,c(1,0,1001,1),2,2,1))
expect_error(image_text_recall_at_k(aligned,c(1,0,1),2,2,1))
cat("R image-text retrieval recall tests passed\n")
