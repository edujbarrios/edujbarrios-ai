file_arg <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(file_arg)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",file_arg[[1L]])))
source(file.path(folder,"image_text_mrr.R"))
expect_error <- function(expr) {
  failed <- tryCatch({force(expr);FALSE},error=function(e) TRUE)
  stopifnot(failed)
}
id <- c(1,0,0,1)
stopifnot(identical(image_text_mrr(id,id,2,2),c(1,1)))
stopifnot(identical(image_text_mrr(id,c(0,1,1,0),2,2),c(0.5,0.5)))
stopifnot(identical(image_text_mrr(c(1,0,1,0),c(1,0,1,0),2,2),c(0.75,0.75)))
stopifnot(identical(image_text_mrr(c(2,0,0,3),id,2,2),c(1,1)))
expect_error(image_text_mrr(id,id,1,2))
expect_error(image_text_mrr(id,id,65,2))
expect_error(image_text_mrr(id,id,2,0))
expect_error(image_text_mrr(id,id,2,129))
expect_error(image_text_mrr(id,c(0,0,0,1),2,2))
expect_error(image_text_mrr(id,c(1,NaN,0,1),2,2))
expect_error(image_text_mrr(id,c(1,1001,0,1),2,2))
expect_error(image_text_mrr(id,c(1,0,1),2,2))
cat("R image-text MRR tests passed\n")
