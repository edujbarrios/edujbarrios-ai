file_arg <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(file_arg)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",file_arg[[1L]])))
source(file.path(folder,"siglip_pairwise_loss.R"))
expect_error <- function(expr) {
  failed <- tryCatch({force(expr);FALSE},error=function(e) TRUE)
  stopifnot(failed)
}
id <- c(1,0,0,1)
swapped <- c(0,1,1,0)
expected <- (log1p(exp(-1))+log(2))/2
stopifnot(abs(siglip_pairwise_loss(id,id,2,2,1,0)-expected)<1e-12)
stopifnot(abs(siglip_pairwise_loss(c(3,0,0,2),id,2,2,1,0)-expected)<1e-12)
stopifnot(siglip_pairwise_loss(id,swapped,2,2,1,0)>expected)
stopifnot(is.finite(siglip_pairwise_loss(id,id,2,2,100,-10)))
expect_error(siglip_pairwise_loss(id,id,1,2,1,0))
expect_error(siglip_pairwise_loss(id,id,65,2,1,0))
expect_error(siglip_pairwise_loss(id,id,2,0,1,0))
expect_error(siglip_pairwise_loss(id,id,2,129,1,0))
expect_error(siglip_pairwise_loss(id,id,2,2,0,0))
expect_error(siglip_pairwise_loss(id,id,2,2,101,0))
expect_error(siglip_pairwise_loss(id,id,2,2,1,21))
expect_error(siglip_pairwise_loss(id,id,2,2,1,NaN))
expect_error(siglip_pairwise_loss(id,c(0,0,0,1),2,2,1,0))
expect_error(siglip_pairwise_loss(id,c(1,0,Inf,1),2,2,1,0))
expect_error(siglip_pairwise_loss(id,c(1,0,1001,1),2,2,1,0))
expect_error(siglip_pairwise_loss(id,c(1,0,1),2,2,1,0))
cat("R SigLIP pairwise loss tests passed\n")
