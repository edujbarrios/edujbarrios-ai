file_arg <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(file_arg)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",file_arg[[1L]])))
source(file.path(folder,"clip_zero_shot_classification.R"))
expect_error <- function(expr) {
  failed <- tryCatch({force(expr);FALSE},error=function(e) TRUE)
  stopifnot(failed)
}
close <- function(x,y) stopifnot(abs(x-y)<1e-12)
expected <- exp(1)/(exp(1)+1)
close(clip_zero_shot_classification(c(1,0),c(1,0,0,1),2,2,1)[[1L]],expected)
close(clip_zero_shot_classification(c(0,1),c(1,0,0,1),2,2,1)[[2L]],expected)
stopifnot(identical(clip_zero_shot_classification(c(1,0),c(1,0,1,0),2,2,1),c(.5,.5)))
close(clip_zero_shot_classification(c(2,0),c(3,0,0,5),2,2,1)[[1L]],expected)
stopifnot(clip_zero_shot_classification(c(1,0),c(1,0,0,1),2,2,100)[[1L]]>.99999)
expect_error(clip_zero_shot_classification(c(1,0),c(1,0,0,1),1,2,1))
expect_error(clip_zero_shot_classification(c(1,0),c(1,0,0,1),2,0,1))
expect_error(clip_zero_shot_classification(c(1,0),c(1,0,0,1),2,129,1))
expect_error(clip_zero_shot_classification(c(1,0),c(1,0,0,1),2,2,0))
expect_error(clip_zero_shot_classification(c(1,0),c(1,0,0,1),2,2,NaN))
expect_error(clip_zero_shot_classification(c(0,0),c(1,0,0,1),2,2,1))
expect_error(clip_zero_shot_classification(c(1,0),c(0,0,0,1),2,2,1))
expect_error(clip_zero_shot_classification(c(1,0),c(1,0,1001,1),2,2,1))
expect_error(clip_zero_shot_classification(c(1,0),c(1,0,1),2,2,1))
cat("R zero-shot classification tests passed\n")
