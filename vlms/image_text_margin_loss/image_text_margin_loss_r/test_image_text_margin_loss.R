file_arg <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(file_arg)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",file_arg[[1L]])))
source(file.path(folder,"image_text_margin_loss.R"))
expect_error <- function(expr) {
  failed <- tryCatch({force(expr);FALSE},error=function(e) TRUE)
  stopifnot(failed)
}
close <- function(x,y) stopifnot(abs(x-y)<1e-12)
aligned <- c(1,0,0,1)
swapped <- c(0,1,1,0)
duplicate <- c(1,0,1,0)
close(image_text_margin_loss(aligned,aligned,2,2,.25),0)
close(image_text_margin_loss(aligned,swapped,2,2,.25),1.25)
close(image_text_margin_loss(duplicate,duplicate,2,2,.25),.25)
close(image_text_margin_loss(c(2,0,0,3),aligned,2,2,.25),0)
close(image_text_margin_loss(aligned,aligned,2,2,2),1)
expect_error(image_text_margin_loss(aligned,aligned,1,2,.25))
expect_error(image_text_margin_loss(aligned,aligned,2,0,.25))
expect_error(image_text_margin_loss(aligned,aligned,2,129,.25))
expect_error(image_text_margin_loss(aligned,aligned,2,2,-1))
expect_error(image_text_margin_loss(aligned,aligned,2,2,2.1))
expect_error(image_text_margin_loss(aligned,aligned,2,2,NaN))
expect_error(image_text_margin_loss(c(0,0,0,1),aligned,2,2,.25))
expect_error(image_text_margin_loss(c(1,0,Inf,1),aligned,2,2,.25))
expect_error(image_text_margin_loss(c(1,0,1001,1),aligned,2,2,.25))
expect_error(image_text_margin_loss(c(1,0,1),aligned,2,2,.25))
cat("R image-text margin loss tests passed\n")
