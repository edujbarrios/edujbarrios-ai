args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
folder <- dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"average_pool2d.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
check <- function(image,h,w,want) {
  got <- average_pool2d(image,h,w)
  stopifnot(length(got)==length(want),all(abs(got-want)<1e-12))
}
check(1:16,4,4,c(3.5,5.5,11.5,13.5))
check(1:15,3,5,c(4,6))
check(1:4,2,2,2.5)
check(c(-4,-2,-6,-8),2,2,-5)
check(rep(0,4),2,2,0)
check(rep(1000,4),2,2,1000)
check(rep(-1000,4),2,2,-1000)
check(1:6,2,3,3)
check(1:6,3,2,2.5)
check(rep(1,1024),32,32,rep(1,256))
checker <- numeric(1024)
for(r in 0:31)for(c in 0:31)checker[[r*32L+c+1L]] <- if((r+c)%%2L==0L)1 else -1
check(checker,32,32,rep(0,256))
expect_error(average_pool2d(1,1,2))
expect_error(average_pool2d(1,2,1))
expect_error(average_pool2d(1,33,2))
expect_error(average_pool2d(1,2,33))
expect_error(average_pool2d(1,TRUE,2))
expect_error(average_pool2d(1,2,2.5))
expect_error(average_pool2d(numeric(0),2,2))
expect_error(average_pool2d(1:3,2,2))
expect_error(average_pool2d(c(1,2,3,NaN),2,2))
expect_error(average_pool2d(c(1,2,3,Inf),2,2))
expect_error(average_pool2d(c(1,2,3,1001),2,2))
expect_error(average_pool2d(c(TRUE,FALSE,TRUE,FALSE),2,2))
expect_error(average_pool2d(matrix(1:4,2,2),2,2))
cat("R average pooling tests passed\n")
