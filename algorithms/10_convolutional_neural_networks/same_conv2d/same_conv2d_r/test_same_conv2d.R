args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
folder <- dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"same_conv2d.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
check <- function(x,h,w,k,kh,kw,want) {
  result <- same_conv2d(x,h,w,k,kh,kw)
  stopifnot(length(result)==length(want),all(abs(result-want)<1e-9))
}
check(1:9,3,3,rep(1,9),3,3,c(12,21,16,27,45,33,24,39,28))
check(1:4,2,2,rep(1,9),3,3,rep(10,4))
check(5,1,1,rep(1,9),3,3,5)
check(1:3,1,3,c(1,2,3),1,3,c(8,14,8))
check(1:3,3,1,c(1,2,3),3,1,c(8,14,8))
check(c(-1,2,3,-4),2,2,-2,1,1,c(2,-4,-6,8))
check(1:4,2,2,0,1,1,rep(0,4))
check(10,1,1,rep(0,25),5,5,0)
check(1000,1,1,1000,1,1,1000000)
check(rep(1,1024),32,32,1,1,1,rep(1,1024))
check(rep(0,1024),32,32,rep(1,25),5,5,rep(0,1024))
expect_error(same_conv2d(1,0,1,1,1,1))
expect_error(same_conv2d(1,1,33,1,1,1))
expect_error(same_conv2d(1,1,1,1,2,1))
expect_error(same_conv2d(1,1,1,1,1,0))
expect_error(same_conv2d(numeric(0),1,1,1,1,1))
expect_error(same_conv2d(1,1,1,numeric(0),1,1))
expect_error(same_conv2d(NaN,1,1,1,1,1))
expect_error(same_conv2d(1,1,1,Inf,1,1))
expect_error(same_conv2d(1001,1,1,1,1,1))
expect_error(same_conv2d(TRUE,1,1,1,1,1))
expect_error(same_conv2d(1,1,1,TRUE,1,1))
expect_error(same_conv2d(matrix(1,1,1),1,1,1,1,1))
cat("R same_conv2d tests passed\n")
