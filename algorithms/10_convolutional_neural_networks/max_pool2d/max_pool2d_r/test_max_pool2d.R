args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(args)==0L) stop("run with Rscript")
source(file.path(dirname(normalizePath(sub("^--file=","",args[[1L]]))),"max_pool2d.R"))
bad <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e) TRUE))
stopifnot(identical(max_pool2d(1:16,4,4),c(6,8,14,16)))
stopifnot(identical(max_pool2d(1:9,3,3),5))
stopifnot(identical(max_pool2d(c(-4,-2,-1,-3),2,2),-1))
bad(max_pool2d(1:4,1,2))
bad(max_pool2d(1:4,2,1))
bad(max_pool2d(1:4,33,2))
bad(max_pool2d(1:3,2,2))
bad(max_pool2d(c(1,NaN,3,4),2,2))
bad(max_pool2d(c(1,1001,3,4),2,2))
cat("R max-pooling tests passed\n")
