args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
if (length(args)==0L) stop("run with Rscript")
source(file.path(dirname(normalizePath(sub("^--file=","",args[[1L]]))),
                 "global_average_pool2d.R"))
bad <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e) TRUE))
stopifnot(identical(global_average_pool2d(1:8,2,2,2),c(2.5,6.5)))
stopifnot(identical(global_average_pool2d(c(-3,-1),1,1,2),-2))
stopifnot(identical(global_average_pool2d(-3,1,1,1),-3))
bad(global_average_pool2d(1:4,0,2,2))
bad(global_average_pool2d(1:4,17,2,2))
bad(global_average_pool2d(1:4,1,0,2))
bad(global_average_pool2d(1:3,1,2,2))
bad(global_average_pool2d(c(1,NA,3,4),1,2,2))
bad(global_average_pool2d(c(1,1001,3,4),1,2,2))
