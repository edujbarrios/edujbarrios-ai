args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(args)==0L) stop("run with Rscript")
source(file.path(dirname(normalizePath(sub("^--file=","",args[[1L]]))),"valid_conv2d.R"))
bad <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e) TRUE))
im <- c(1,2,3,4,5,6,7,8,9)
k <- c(1,0,0,-1)
stopifnot(identical(valid_conv2d(im,3,3,k,2,2),rep(-4,4)))
stopifnot(identical(valid_conv2d(im,3,3,-2,1,1),as.double(-2*im)))
stopifnot(identical(valid_conv2d(5,1,1,3,1,1),15))
bad(valid_conv2d(im,0,3,k,2,2))
bad(valid_conv2d(im,3,0,k,2,2))
bad(valid_conv2d(im,33,3,k,2,2))
bad(valid_conv2d(im,3,3,k,4,2))
bad(valid_conv2d(im,3,3,k,0,2))
bad(valid_conv2d(im[-9],3,3,k,2,2))
bad(valid_conv2d(im,3,3,c(1,NaN,0,-1),2,2))
bad(valid_conv2d(im,3,3,c(1,1001,0,-1),2,2))
cat("R valid conv2d tests passed\n")
