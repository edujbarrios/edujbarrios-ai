args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "scalar_quantization.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr); FALSE}, error=function(e) TRUE))
stopifnot(identical(scalar_quantization(c(0,0.5,1,-3,8),0,1),c(0L,128L,255L,0L,255L)))
stopifnot(identical(scalar_quantization(numeric(),0,1),integer()))
expect_error(scalar_quantization(c(NaN),0,1))
expect_error(scalar_quantization(c(0),1,1))
expect_error(scalar_quantization(c(0),-1e308,1e308))
expect_error(scalar_quantization(c(0),0,Inf))
cat("R scalar quantization tests passed\n")
