args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "hamming_top_k.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr); FALSE}, error=function(e) TRUE))
stopifnot(identical(hamming_top_k(3, c(1,7,15,2,3), 4), c(4L,0L,1L,3L)))
stopifnot(identical(hamming_top_k(3, c(3,3,0), 2), c(0L,1L)))
stopifnot(identical(hamming_top_k(0, c(0,2^30-1), 2), c(0L,1L)))
expect_error(hamming_top_k(3, numeric(), 1))
expect_error(hamming_top_k(3, c(1), 0))
expect_error(hamming_top_k(3, c(1), 2))
expect_error(hamming_top_k(3, c(1,2^30), 1))
expect_error(hamming_top_k(2^30, c(0), 1))
expect_error(hamming_top_k(0, c(0.5), 1))
cat("R hamming_top_k tests passed\n")
