args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"exact_cosine_top_k.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
vectors<-matrix(c(1,0,0,1,-1,0,1,1,1,0),nrow=5,byrow=TRUE)
stopifnot(identical(exact_cosine_top_k(c(1,0),vectors,4),c(0L,4L,3L,1L)))
stopifnot(identical(exact_cosine_top_k(c(1),matrix(c(-2,3,3),ncol=1),3),c(1L,2L,0L)))
stopifnot(identical(exact_cosine_top_k(c(1),matrix(1,nrow=1),1),c(0L)))
expect_error(exact_cosine_top_k(numeric(),vectors,1))
expect_error(exact_cosine_top_k(c(1,0),vectors,0))
expect_error(exact_cosine_top_k(c(1,0),vectors,6))
expect_error(exact_cosine_top_k(c(1,0),matrix(c(1,0,0,0),nrow=2,byrow=TRUE),1))
expect_error(exact_cosine_top_k(c(1e308,1e308),matrix(c(1,0),nrow=1),1))
expect_error(exact_cosine_top_k(c(1,0),matrix(c(1,0,NaN,1),nrow=2,byrow=TRUE),1))
cat("R exact_cosine_top_k tests passed\n")
