args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"random_hyperplane_hash.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
normals<-matrix(c(1,0,0,1,-1,-1),nrow=3,byrow=TRUE)
stopifnot(identical(random_hyperplane_hash(c(1,2),normals),3L))
stopifnot(identical(random_hyperplane_hash(c(0,1),normals),3L))
stopifnot(identical(random_hyperplane_hash(c(-1,-2),normals),4L))
stopifnot(identical(random_hyperplane_hash(c(1),matrix(rep(1,30),ncol=1)),1073741823L))
expect_error(random_hyperplane_hash(numeric(),normals))
expect_error(random_hyperplane_hash(c(0,0),normals))
expect_error(random_hyperplane_hash(c(1),matrix(0,ncol=1)))
expect_error(random_hyperplane_hash(c(1e308),matrix(1e308,ncol=1)))
expect_error(random_hyperplane_hash(c(1),matrix(rep(1,31),ncol=1)))
cat("R random hyperplane hash tests passed\n")
