args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"lsh_bucket_index.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
idx<-build_lsh_bucket_index(c(3,7,3,0,7))
stopifnot(identical(lsh_bucket_index_query(idx,3),c(0L,2L)))
stopifnot(identical(lsh_bucket_index_query(idx,7),c(1L,4L)))
stopifnot(identical(lsh_bucket_index_query(idx,4),integer()))
stopifnot(identical(lsh_bucket_index_query(idx,3),c(0L,2L)))
idx<-build_lsh_bucket_index(2^30-1)
stopifnot(identical(lsh_bucket_index_query(idx,2^30-1),0L))
expect_error(build_lsh_bucket_index(numeric()))
expect_error(build_lsh_bucket_index(c(0,2^30)))
expect_error(build_lsh_bucket_index(c(-1,0)))
expect_error(build_lsh_bucket_index(c(0,0.5)))
expect_error(lsh_bucket_index_query(idx,-1))
expect_error(lsh_bucket_index_query(idx,2^30))
cat("R LSH bucket index tests passed\n")
