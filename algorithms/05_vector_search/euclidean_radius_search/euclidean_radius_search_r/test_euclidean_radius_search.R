args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
folder <- dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"euclidean_radius_search.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
check <- function(q,x,r,want) {
  stopifnot(identical(euclidean_radius_search(q,x,r),as.integer(want)))
}
x <- matrix(c(1,0, 0,1, 3,4, 0,0, -1,0),ncol=2,byrow=TRUE)
check(c(0,0),x,1,c(3,0,1,4))
check(c(0,0),x,0,3)
check(c(0,0),x,5,c(3,0,1,4,2))
check(c(0,0),x,0.99,3)
check(c(0,0),matrix(c(1,0),nrow=1),0.5,integer(0))
check(2,matrix(c(2,2,3),ncol=1),0,c(0,1))
check(0,matrix(c(-1,1,0),ncol=1),1,c(2,0,1))
check(rep(0,32),matrix(0,nrow=128,ncol=32),0,0:127)
check(rep(1000,32),matrix(-1000,nrow=1,ncol=32),10000,integer(0))
check(rep(1000,16),matrix(-1000,nrow=1,ncol=16),10000,0)
expect_error(euclidean_radius_search(numeric(0),matrix(0,1,1),1))
expect_error(euclidean_radius_search(0,matrix(0,0,1),1))
expect_error(euclidean_radius_search(0,matrix(0,129,1),1))
expect_error(euclidean_radius_search(0,matrix(0,1,2),1))
expect_error(euclidean_radius_search(1001,matrix(0,1,1),1))
expect_error(euclidean_radius_search(0,matrix(1001,1,1),1))
expect_error(euclidean_radius_search(NA_real_,matrix(0,1,1),1))
expect_error(euclidean_radius_search(0,matrix(Inf,1,1),1))
expect_error(euclidean_radius_search(0,matrix(0,1,1),-1))
expect_error(euclidean_radius_search(0,matrix(0,1,1),10001))
expect_error(euclidean_radius_search(0,matrix(0,1,1),TRUE))
expect_error(euclidean_radius_search(TRUE,matrix(0,1,1),1))
expect_error(euclidean_radius_search(0,matrix(TRUE,1,1),1))
cat("R Euclidean radius search tests passed\n")
