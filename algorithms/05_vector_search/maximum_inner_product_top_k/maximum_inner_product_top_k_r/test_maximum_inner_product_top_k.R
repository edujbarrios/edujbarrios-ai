args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"maximum_inner_product_top_k.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
x<-matrix(c(1,0,0,1,1,2,-1,0,1,2),nrow=5,byrow=TRUE)
stopifnot(identical(maximum_inner_product_top_k(c(1,2),x,5),c(2L,4L,1L,0L,3L)))
stopifnot(identical(maximum_inner_product_top_k(c(0,0),x,3),c(0L,1L,2L)))
stopifnot(identical(maximum_inner_product_top_k(1,matrix(5,nrow=1),1),c(0L)))
expect_error(maximum_inner_product_top_k(numeric(),x,1))
expect_error(maximum_inner_product_top_k(c(1,2),x,0))
expect_error(maximum_inner_product_top_k(c(1,2),x,6))
expect_error(maximum_inner_product_top_k(c(1,2),matrix(c(0,0,NaN,1),nrow=2,byrow=TRUE),1))
expect_error(maximum_inner_product_top_k(c(1e308),matrix(1e308,nrow=1),1))
expect_error(maximum_inner_product_top_k(c(1e308,1e308),matrix(c(2,2),nrow=1),1))
cat("R maximum inner-product search tests passed\n")
