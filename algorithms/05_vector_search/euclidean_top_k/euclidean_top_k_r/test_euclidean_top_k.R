args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"euclidean_top_k.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
points<-matrix(c(1,0,0,1,3,4,0,0,-1,0),nrow=5,byrow=TRUE)
stopifnot(identical(euclidean_top_k(c(0,0),points,5),c(3L,0L,1L,4L,2L)))
stopifnot(identical(euclidean_top_k(c(0,0),matrix(c(1,0,1,0,0,0),nrow=3,byrow=TRUE),3),c(2L,0L,1L)))
stopifnot(identical(euclidean_top_k(c(0,0),matrix(c(1e200,0,2e200,0),nrow=2,byrow=TRUE),2),c(0L,1L)))
expect_error(euclidean_top_k(numeric(),points,1))
expect_error(euclidean_top_k(c(0,0),points,0))
expect_error(euclidean_top_k(c(0,0),points,6))
expect_error(euclidean_top_k(c(0,0),matrix(c(0,0,NaN,1),nrow=2,byrow=TRUE),1))
expect_error(euclidean_top_k(c(1.7e308),matrix(-1.7e308,nrow=1),1))
cat("R Euclidean Top-K tests passed\n")
