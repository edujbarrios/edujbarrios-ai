args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"hamming_radius_search.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
values<-c(3,1,7,15,2)
stopifnot(identical(hamming_radius_search(3,values,1),c(0L,1L,2L,4L)))
stopifnot(identical(hamming_radius_search(3,values,0),c(0L)))
stopifnot(identical(hamming_radius_search(3,values,30),c(0L,1L,2L,4L,3L)))
stopifnot(identical(hamming_radius_search(3,c(3,3,1),0),c(0L,1L)))
stopifnot(identical(hamming_radius_search(0,numeric(),0),integer()))
stopifnot(identical(hamming_radius_search(0,c(0,2^30-1),30),c(0L,1L)))
expect_error(hamming_radius_search(3,c(3,2^30),0))
expect_error(hamming_radius_search(2^30,c(3),0))
expect_error(hamming_radius_search(3,c(3),31))
expect_error(hamming_radius_search(3,c(3),-1))
expect_error(hamming_radius_search(3,c(3),1.5))
cat("R hamming radius tests passed\n")
