args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"temperature_softmax.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
x<-c(0,log(3))
stopifnot(abs(temperature_softmax(x,1)[[1]]-.25)<1e-12)
stopifnot(abs(temperature_softmax(x,.5)[[1]]-.1)<1e-12)
stopifnot(abs(temperature_softmax(x,2)[[1]]-1/(1+sqrt(3)))<1e-12)
stopifnot(identical(temperature_softmax(c(10,10),1),c(.5,.5)))
stopifnot(identical(temperature_softmax(c(0),1),c(1.0)))
stopifnot(abs(temperature_softmax(c(1000,1001),1)[[1]]-1/(1+exp(1)))<1e-12)
expect_error(temperature_softmax(numeric(),1))
expect_error(temperature_softmax(c(0,1),0))
expect_error(temperature_softmax(c(0,1),-1))
expect_error(temperature_softmax(c(0,NaN),1))
expect_error(temperature_softmax(c(-1e308,1e308),1))
cat("R temperature-softmax tests passed\n")
