args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"scaled_dot_product_attention.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
keys<-matrix(c(1,0,0,1),nrow=2,byrow=TRUE)
vals<-matrix(c(10,0,0,20),nrow=2,byrow=TRUE)
weight<-exp(1/sqrt(2))/(exp(1/sqrt(2))+1)
result<-scaled_dot_product_attention(c(1,0),keys,vals)
stopifnot(abs(result[[1]]-10*weight)<1e-12,
          abs(result[[2]]-20*(1-weight))<1e-12)
tie<-scaled_dot_product_attention(c(1,1),keys,matrix(c(2,4,6,8),nrow=2,byrow=TRUE))
stopifnot(identical(tie,c(4,6)))
stopifnot(identical(scaled_dot_product_attention(c(1),matrix(1,nrow=1),matrix(7,nrow=1)),c(7)))
stopifnot(identical(scaled_dot_product_attention(c(1000),matrix(c(-1000,1000),ncol=1),matrix(c(0,1),ncol=1)),c(1)))
expect_error(scaled_dot_product_attention(numeric(),keys,vals))
expect_error(scaled_dot_product_attention(c(1),keys,vals))
expect_error(scaled_dot_product_attention(c(1),matrix(NaN,nrow=1),matrix(1,nrow=1)))
expect_error(scaled_dot_product_attention(c(1e308),matrix(1e308,nrow=1),matrix(1,nrow=1)))
cat("R scaled dot product attention tests passed\n")
