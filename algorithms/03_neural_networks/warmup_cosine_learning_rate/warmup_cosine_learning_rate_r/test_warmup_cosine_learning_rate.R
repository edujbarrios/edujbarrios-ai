args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
if(length(args)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder,"warmup_cosine_learning_rate.R"))
error <- function(expr) stopifnot(tryCatch({force(expr); FALSE},error=function(e) TRUE))
expected <- c(0,0.5,1,0.8535533905932737,0.5,0.1464466094067262,0)
actual <- vapply(0:6,function(s) warmup_cosine_learning_rate(1,0,2,6,s),numeric(1))
stopifnot(max(abs(expected-actual)) < 1e-12)
stopifnot(identical(warmup_cosine_learning_rate(2,2,1,2,1),2.0))
stopifnot(identical(warmup_cosine_learning_rate(2,2,1,2,2),2.0))
error(warmup_cosine_learning_rate(1,0,0,6,1))
error(warmup_cosine_learning_rate(1,0,6,6,1))
error(warmup_cosine_learning_rate(1,0,2,6,7))
error(warmup_cosine_learning_rate(0,1,2,6,1))
error(warmup_cosine_learning_rate(Inf,0,2,6,1))
error(warmup_cosine_learning_rate(1,0,2,100001,1))
error(warmup_cosine_learning_rate(1,0,2,6,TRUE))
