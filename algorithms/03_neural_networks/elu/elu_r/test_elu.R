file_arg <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(file_arg)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",file_arg[[1L]])))
source(file.path(folder,"elu.R"))
close <- function(a,b,tol=1e-12) stopifnot(all(abs(a-b)<tol))
err <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e) TRUE))
close(elu(c(-1,0,1)),c(exp(-1)-1,0,1))
close(elu(c(-1000000,1000000)),c(-1,1000000))
close(elu(c(-1e-9,1e-9)),c(exp(-1e-9)-1,1e-9))
close(elu(0),0)
err(elu(numeric()))
err(elu(NaN))
err(elu(Inf))
err(elu(1000001))
err(elu(-1000001))
err(elu("1"))
err(elu(matrix(1,nrow=1)))
