args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"adamw_optimizer.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
p<-adamw_optimizer(c(2,-3),c(1,-2),c(0,0),c(0,0),1,.1)
stopifnot(abs(p$m[[1]]-.1)<1e-12,abs(p$m[[2]]+.2)<1e-12)
stopifnot(abs(p$v[[1]]-.001)<1e-12,abs(p$v[[2]]-.004)<1e-12)
stopifnot(abs(p$parameters[[1]]-(2-.1*(1/(1+1e-8)+.02)))<1e-12)
stopifnot(abs(p$parameters[[2]]-(-3-.1*(-2/(2+1e-8)-.03)))<1e-12)
next_step<-adamw_optimizer(p$parameters,c(0,0),p$m,p$v,2,.1)
stopifnot(abs(next_step$m[[1]]-.09)<1e-12,abs(next_step$v[[1]]-.000999)<1e-12)
stopifnot(next_step$parameters[[1]]<p$parameters[[1]],
          next_step$parameters[[2]]>p$parameters[[2]])
stopifnot(abs(adamw_optimizer(c(1),c(0),c(0),c(0),1,.1)$parameters[[1]]-.999)<1e-12)
expect_error(adamw_optimizer(numeric(),numeric(),numeric(),numeric(),1,.1))
expect_error(adamw_optimizer(c(1),numeric(),c(0),c(0),1,.1))
expect_error(adamw_optimizer(c(1),c(1),c(0),c(-1),1,.1))
expect_error(adamw_optimizer(c(1),c(1),c(0),c(0),0,.1))
expect_error(adamw_optimizer(c(1),c(NaN),c(0),c(0),1,.1))
expect_error(adamw_optimizer(c(1),c(1e308),c(0),c(0),1,.1))
cat("R AdamW tests passed\n")
