args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "contrastive_pair_loss.R"))
error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e) TRUE))
loss <- contrastive_pair_loss
stopifnot(loss(c(0,0),c(3,4),1,6) == 12.5)
stopifnot(loss(c(0,0),c(3,4),0,6) == 0.5)
stopifnot(loss(c(0,0),c(3,4),0,3) == 0)
stopifnot(loss(c(1,2),c(1,2),0,2) == 2)
stopifnot(loss(c(1,2),c(1,2),1,2) == 0)
stopifnot(loss(c(0,0),c(3,4),0,0) == 0)
stopifnot(loss(rep(0,512),rep(1,512),1,0) == 256)
stopifnot(loss(rep(0,512),rep(1,512),0,1) == 0)
error(loss(numeric(),numeric(),1,1))
error(loss(0,c(0,1),1,1))
error(loss(rep(0,513),rep(0,513),1,1))
error(loss(0,0,2,1))
error(loss(0,0,TRUE,1))
error(loss(0,0,0.5,1))
error(loss(0,0,1,-1))
error(loss(0,0,1,1001))
error(loss(0,0,1,Inf))
error(loss(0,0,1,TRUE))
error(loss(NaN,0,1,1))
error(loss(0,Inf,1,1))
error(loss(0,1001,1,1))
error(loss(TRUE,0,1,1))
error(loss(matrix(0,nrow=1),0,1,1))
