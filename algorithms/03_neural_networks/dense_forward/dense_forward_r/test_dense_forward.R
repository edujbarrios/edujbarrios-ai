args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
folder <- dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"dense_forward.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e) TRUE))
weights <- matrix(c(1,1,-1,2),nrow=2,byrow=TRUE)
stopifnot(identical(dense_forward(c(2,-1),weights,c(0,1)),c(1,0)))
stopifnot(identical(dense_forward(c(1),matrix(3,1,1),c(2)),c(5)))
stopifnot(identical(dense_forward(c(-1),matrix(3,1,1),c(2)),c(0)))
expect_error(dense_forward(numeric(),matrix(1,1,1),c(0)))
expect_error(dense_forward(c(1,2),matrix(1,1,1),c(0)))
expect_error(dense_forward(c(1),matrix(NaN,1,1),c(0)))
expect_error(dense_forward(c(1),matrix(1,1,1),c(Inf)))
expect_error(dense_forward(c(1e308),matrix(1e308,1,1),c(0)))
cat("R dense forward tests passed\n")
