args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"momentum_sgd.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
v<-momentum_sgd(c(2,-3),c(1,-2),c(0,0),.1)
stopifnot(abs(v$parameters[[1]]-1.9)<1e-12,abs(v$parameters[[2]]+2.8)<1e-12)
stopifnot(identical(v$velocity,c(1,-2)))
w<-momentum_sgd(v$parameters,c(0,0),v$velocity,.1)
stopifnot(abs(w$parameters[[1]]-1.81)<1e-12,abs(w$parameters[[2]]+2.62)<1e-12)
stopifnot(abs(w$velocity[[1]]-.9)<1e-12,abs(w$velocity[[2]]+1.8)<1e-12)
stopifnot(identical(momentum_sgd(c(1),c(0),c(0),.1)$parameters,c(1)))
expect_error(momentum_sgd(numeric(),numeric(),numeric(),.1))
expect_error(momentum_sgd(c(1),c(0),numeric(),.1))
expect_error(momentum_sgd(c(1),c(0),c(0),0))
expect_error(momentum_sgd(c(1),c(NaN),c(0),.1))
expect_error(momentum_sgd(c(1e308),c(1e308),c(0),1e308))
cat("R momentum SGD tests passed\n")
