args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if(length(args)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"gradient_clip_by_value.R"))
error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e) TRUE))
stopifnot(identical(gradient_clip_by_value(c(-3,-0.5,0,0.5,3),1),c(-1,-0.5,0,0.5,1)))
stopifnot(identical(gradient_clip_by_value(c(-1,0,1),1),c(-1,0,1)))
stopifnot(identical(gradient_clip_by_value(c(-1e308,1e308),1),c(-1,1)))
stopifnot(identical(gradient_clip_by_value(0,2),0))
error(gradient_clip_by_value(numeric(),1))
error(gradient_clip_by_value(NaN,1))
error(gradient_clip_by_value(Inf,1))
error(gradient_clip_by_value(TRUE,1))
error(gradient_clip_by_value(1,0))
error(gradient_clip_by_value(1,Inf))
cat("R gradient value clipping tests passed\n")
