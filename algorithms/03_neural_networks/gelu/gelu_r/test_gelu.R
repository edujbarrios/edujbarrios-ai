args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"gelu.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
v<-gelu(c(0,1,-1,100,-100))
t<-tanh(0.7978845608028654*(1+0.044715))
gate<-0.5*(1+t)
deriv<-gate+0.5*(1-t*t)*0.7978845608028654*(1+3*0.044715)
stopifnot(identical(v$values[[1]],0.0),identical(v$derivatives[[1]],0.5))
stopifnot(abs(v$values[[2]]-gate)<1e-12,abs(v$derivatives[[2]]-deriv)<1e-12)
stopifnot(abs(v$values[[3]]-(gate-1))<1e-12,abs(v$derivatives[[3]]-(1-deriv))<1e-12)
stopifnot(v$values[[4]]==100,v$derivatives[[4]]==1)
stopifnot(v$values[[5]]==0,v$derivatives[[5]]==0)
expect_error(gelu(numeric()))
expect_error(gelu(c(NaN)))
expect_error(gelu(c(Inf)))
expect_error(gelu(c(1e308)))
cat("R GELU tests passed\n")
