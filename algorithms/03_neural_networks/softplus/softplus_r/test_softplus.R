args <- grep("^--file=", commandArgs(FALSE), value = TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "softplus.R"))
expect_error <- function(expr) {
  stopifnot(tryCatch({ force(expr); FALSE }, error = function(e) TRUE))
}
out <- softplus(c(0, 1, -1, 1000, -1000))
stopifnot(abs(out$values[[1]] - log(2)) < 1e-12, out$derivatives[[1]] == 0.5)
stopifnot(abs(out$values[[2]] - log1p(exp(1))) < 1e-12)
stopifnot(abs(out$values[[3]] - log1p(exp(-1))) < 1e-12)
stopifnot(abs(out$derivatives[[2]] - 1 / (1 + exp(-1))) < 1e-12)
stopifnot(abs(out$derivatives[[3]] - 1 / (1 + exp(1))) < 1e-12)
stopifnot(identical(as.numeric(out$values[4:5]), c(1000, 0)))
stopifnot(identical(as.numeric(out$derivatives[4:5]), c(1, 0)))
expect_error(softplus(numeric()))
expect_error(softplus(NaN))
expect_error(softplus(Inf))
expect_error(softplus("invalid"))
cat("R Softplus tests passed\n")
