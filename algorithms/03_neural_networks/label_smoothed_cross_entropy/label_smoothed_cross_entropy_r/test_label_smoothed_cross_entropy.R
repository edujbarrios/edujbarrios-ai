args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"label_smoothed_cross_entropy.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
z<-c(0,log(3))
x<-label_smoothed_cross_entropy(z,1,.2)
stopifnot(abs(x$loss-(-.1*log(.25)-.9*log(.75)))<1e-12)
stopifnot(abs(x$gradients[[1]]-.15)<1e-12,
          abs(x$gradients[[2]]+.15)<1e-12)
stopifnot(abs(label_smoothed_cross_entropy(z,1,0)$loss+log(.75))<1e-12)
stopifnot(abs(label_smoothed_cross_entropy(z,1,1)$gradients[[1]]+.25)<1e-12)
stopifnot(abs(label_smoothed_cross_entropy(c(0,0),0,.5)$loss-log(2))<1e-12)
stopifnot(identical(label_smoothed_cross_entropy(c(12),0,.6)$gradients,c(0.0)))
stopifnot(is.finite(label_smoothed_cross_entropy(c(1000,1001),1,.2)$loss))
expect_error(label_smoothed_cross_entropy(numeric(),0,.2))
expect_error(label_smoothed_cross_entropy(z,2,.2))
expect_error(label_smoothed_cross_entropy(z,1,-.1))
expect_error(label_smoothed_cross_entropy(z,1,1.1))
expect_error(label_smoothed_cross_entropy(c(0,NaN),1,.2))
expect_error(label_smoothed_cross_entropy(c(-1e308,1e308),1,.2))
cat("R label-smoothed cross-entropy tests passed\n")
