args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"hinge_loss.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
x<-hinge_loss(c(2,0,-.5,1),c(1,1,-1,-1))
stopifnot(abs(x$loss-.875)<1e-12)
stopifnot(identical(x$gradients,c(0,-.25,.25,.25)))
x<-hinge_loss(c(1,-1),c(1,-1))
stopifnot(identical(x$loss,0.0),identical(x$gradients,c(0,0)))
x<-hinge_loss(c(0),c(-1))
stopifnot(identical(x$loss,1.0),identical(x$gradients,c(1.0)))
expect_error(hinge_loss(numeric(),numeric()))
expect_error(hinge_loss(c(0),numeric()))
expect_error(hinge_loss(c(0),c(0)))
expect_error(hinge_loss(c(NaN),c(1)))
expect_error(hinge_loss(c(-1e308,-1e308),c(1,1)))
cat("R hinge loss tests passed\n")
