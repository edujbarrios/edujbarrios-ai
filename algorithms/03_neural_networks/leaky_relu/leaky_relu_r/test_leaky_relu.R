args <- grep("^--file=", commandArgs(FALSE), value = TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "leaky_relu.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr); FALSE}, error = function(e) TRUE))
stopifnot(max(abs(leaky_relu(c(-2, 0, 3), 0.1) - c(-0.2, 0, 3))) < 1e-12)
stopifnot(identical(leaky_relu(numeric(), 0.1), numeric()))
expect_error(leaky_relu(c(1), 0))
expect_error(leaky_relu(c(1), 1))
expect_error(leaky_relu(c(NaN), 0.1))
expect_error(leaky_relu(c(1), Inf))
cat("R leaky_relu tests passed\n")
