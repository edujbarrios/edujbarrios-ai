file_arg <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(file_arg)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",file_arg[[1L]])))
source(file.path(folder,"binary_cross_entropy_with_logits.R"))
expect_error <- function(expr) {
  failed <- tryCatch({force(expr);FALSE},error=function(e) TRUE)
  stopifnot(failed)
}
close <- function(actual,expected,tol=1e-12) stopifnot(abs(actual-expected)<tol)
expected <- (log(2)+2*log1p(exp(-2))+2)/3
close(binary_cross_entropy_with_logits(c(0,2,-2),c(0,1,1)),expected)
close(binary_cross_entropy_with_logits(0,0.5),log(2))
close(binary_cross_entropy_with_logits(1e6,1),0)
close(binary_cross_entropy_with_logits(-1e6,1),1e6,1e-9)
close(binary_cross_entropy_with_logits(1e6,0.5),5e5,1e-9)
expect_error(binary_cross_entropy_with_logits(numeric(),numeric()))
expect_error(binary_cross_entropy_with_logits(c(1,2),1))
expect_error(binary_cross_entropy_with_logits(0,-0.1))
expect_error(binary_cross_entropy_with_logits(0,1.1))
expect_error(binary_cross_entropy_with_logits(NaN,1))
expect_error(binary_cross_entropy_with_logits(Inf,1))
expect_error(binary_cross_entropy_with_logits(1000001,1))
expect_error(binary_cross_entropy_with_logits(0,NA))
expect_error(binary_cross_entropy_with_logits(0,"1"))
cat("R BCE with logits tests passed\n")
