file_arg <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(file_arg)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",file_arg[[1L]])))
source(file.path(folder,"log_softmax.R"))
expect_error <- function(expr) {
  failed <- tryCatch({force(expr);FALSE},error=function(e) TRUE)
  stopifnot(failed)
}
close <- function(actual,expected) stopifnot(all(abs(actual-expected)<1e-12))
close(log_softmax(c(0,0)),rep(-log(2),2))
reference <- log_softmax(c(0,log(2)))
close(reference,c(-log(3),log(2)-log(3)))
close(sum(exp(reference)),1)
close(log_softmax(c(100,100+log(2))),reference)
close(log_softmax(c(1e6,-1e6)),c(0,-2e6))
close(log_softmax(5),0)
expect_error(log_softmax(numeric()))
expect_error(log_softmax(NaN))
expect_error(log_softmax(Inf))
expect_error(log_softmax(1000001))
expect_error(log_softmax("0"))
expect_error(log_softmax(matrix(0,nrow=1)))
cat("R log-softmax tests passed\n")
