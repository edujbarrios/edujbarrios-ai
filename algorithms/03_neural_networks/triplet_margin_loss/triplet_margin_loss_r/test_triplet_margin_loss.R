args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "triplet_margin_loss.R"))
error <- function(expr) stopifnot(tryCatch({force(expr); FALSE}, error=function(e) TRUE))
loss <- triplet_margin_loss
stopifnot(loss(c(0,0), c(1,0), c(3,0), 1) == 0)
stopifnot(loss(c(0,0), c(1,0), c(3,0), 3) == 1)
stopifnot(loss(c(0,0), c(3,4), c(0,0), 1) == 6)
stopifnot(loss(c(0,0), c(0,0), c(0,0), 0.5) == 0.5)
stopifnot(loss(c(-2,-2), c(-2,-2), c(-2,-2), 0) == 0)
stopifnot(loss(rep(0,512), rep(0,512), rep(1,512), 0) == 0)
stopifnot(abs(loss(rep(0,512), rep(1,512), rep(0,512), 0) - sqrt(512)) < 1e-9)
error(loss(numeric(), numeric(), numeric(), 1))
error(loss(0, numeric(), 1, 1))
error(loss(0, 1, c(1,2), 1))
error(loss(rep(0,513), rep(0,513), rep(0,513), 1))
error(loss(0, 1, 1, -1))
error(loss(0, 1, 1, 1001))
error(loss(0, 1, 1, Inf))
error(loss(0, NaN, 1, 1))
error(loss(0, 1000001, 1, 1))
error(loss(0, 1, 1, TRUE))
error(loss(matrix(0,nrow=1), 1, 1, 1))
cat("R triplet margin loss tests passed\n")
