args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"layer_normalization.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
inv<-1/sqrt(2/3+1e-5)
result<-layer_normalization(c(1,2,3),c(1,1,1),c(0,0,0),1e-5)
stopifnot(max(abs(result-c(-inv,0,inv)))<1e-12)
result<-layer_normalization(c(1,2,3),c(2,1,0.5),c(1,2,3),1e-5)
stopifnot(max(abs(result-c(1-2*inv,2,3+0.5*inv)))<1e-12)
stopifnot(identical(layer_normalization(c(7,7),c(1,1),c(4,5),1e-5),c(4,5)))
stopifnot(identical(layer_normalization(c(10),c(1),c(4),1e-5),c(4)))
expect_error(layer_normalization(numeric(),numeric(),numeric(),1e-5))
expect_error(layer_normalization(c(1,2),c(1),c(0,0),1e-5))
expect_error(layer_normalization(c(1),c(1),c(0),0))
expect_error(layer_normalization(c(1,NaN),c(1,1),c(0,0),1e-5))
expect_error(layer_normalization(c(1.7e308,-1.7e308),c(1,1),c(0,0),1e-5))
cat("R layer normalization tests passed\n")
