file_arg <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(file_arg)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",file_arg[[1L]])))
source(file.path(folder,"log_cosh_loss.R"))
expect_error <- function(expr) {
  failed <- tryCatch({force(expr);FALSE},error=function(e) TRUE)
  stopifnot(failed)
}
close <- function(actual,expected,tol=1e-12) stopifnot(abs(actual-expected)<tol)
close(log_cosh_loss(c(0,1,2),c(0,2,0)),0.5862611926136305)
close(log_cosh_loss(c(0,1,2),c(0,1,2)),0)
close(log_cosh_loss(c(1e6),c(-1e6)),2e6-log(2),1e-8)
close(log_cosh_loss(1,2),log(cosh(1)))
expect_error(log_cosh_loss(numeric(),numeric()))
expect_error(log_cosh_loss(c(1,2),c(1)))
expect_error(log_cosh_loss(1,NA))
expect_error(log_cosh_loss(1,Inf))
expect_error(log_cosh_loss(1,1000001))
expect_error(log_cosh_loss(c("1"),1))
expect_error(log_cosh_loss(matrix(1,nrow=1),1))
cat("R log-cosh loss tests passed\n")
