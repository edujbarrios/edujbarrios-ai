args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"swish.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
result<-swish(c(0,1,-1,1000,-1000))
s<-1/(1+exp(-1))
stopifnot(identical(result$values[[1]],0.0),identical(result$derivatives[[1]],0.5))
stopifnot(abs(result$values[[2]]-s)<1e-12)
stopifnot(abs(result$derivatives[[2]]-(s+s*(1-s)))<1e-12)
stopifnot(abs(result$values[[3]]-(s-1))<1e-12)
stopifnot(abs(result$derivatives[[3]]-(1-s)*(1-s))<1e-12)
stopifnot(identical(result$values[[4]],1000.0))
stopifnot(identical(result$derivatives[[4]],1.0))
stopifnot(result$values[[5]]==0,result$derivatives[[5]]==0)
expect_error(swish(numeric()))
expect_error(swish(c(1,NaN)))
expect_error(swish(c(Inf)))
cat("R Swish tests passed\n")
