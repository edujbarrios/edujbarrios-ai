args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"huber_loss.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
x<-huber_loss(c(2,0,-2),c(0,1,0),1)
stopifnot(abs(x$loss-7/6)<1e-12)
stopifnot(max(abs(x$gradients-c(1/3,-1/3,-1/3)))<1e-12)
x<-huber_loss(c(1,-1),c(0,0),1)
stopifnot(identical(x$loss,.5),identical(x$gradients,c(.5,-.5)))
x<-huber_loss(c(0,0),c(0,0),1)
stopifnot(identical(x$loss,0.0),identical(x$gradients,c(0,0)))
x<-huber_loss(c(.5),c(0),1)
stopifnot(identical(x$loss,.125),identical(x$gradients,c(.5)))
expect_error(huber_loss(numeric(),numeric(),1))
expect_error(huber_loss(c(1),numeric(),1))
expect_error(huber_loss(c(1),c(0),0))
expect_error(huber_loss(c(NaN),c(0),1))
expect_error(huber_loss(c(1.7e308),c(-1.7e308),1))
expect_error(huber_loss(c(1e308),c(0),1e308))
cat("R Huber loss tests passed\n")
