file_arg<-grep("^--file=",commandArgs(FALSE),value=TRUE)
if(length(file_arg)==0L) stop("run with Rscript")
folder<-dirname(normalizePath(sub("^--file=","",file_arg[[1L]])))
source(file.path(folder,"cosine_annealing_learning_rate.R"))
close<-function(x,y) stopifnot(abs(x-y)<1e-12)
err<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e) TRUE))
close(cosine_annealing_learning_rate(1,0,0,4),1)
close(cosine_annealing_learning_rate(1,0,4,4),0)
