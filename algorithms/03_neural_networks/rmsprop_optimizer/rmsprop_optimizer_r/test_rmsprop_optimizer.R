args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"rmsprop_optimizer.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
v<-rmsprop_optimizer(c(2,-3),c(1,-2),c(0,0),.1)
stopifnot(abs(v$squared_average[[1]]-.1)<1e-12)
stopifnot(abs(v$squared_average[[2]]-.4)<1e-12)
stopifnot(abs(v$parameters[[1]]-(2-.1/(sqrt(.1)+1e-8)))<1e-12)
stopifnot(abs(v$parameters[[2]]-(-3+.2/(sqrt(.4)+1e-8)))<1e-12)
w<-rmsprop_optimizer(v$parameters,c(0,0),v$squared_average,.1)
stopifnot(identical(w$parameters,v$parameters))
stopifnot(abs(w$squared_average[[1]]-.09)<1e-12)
stopifnot(abs(w$squared_average[[2]]-.36)<1e-12)
stopifnot(identical(rmsprop_optimizer(c(1),c(0),c(0),.1)$parameters,c(1)))
expect_error(rmsprop_optimizer(numeric(),numeric(),numeric(),.1))
expect_error(rmsprop_optimizer(c(1),c(1),numeric(),.1))
expect_error(rmsprop_optimizer(c(1),c(1),c(-1),.1))
expect_error(rmsprop_optimizer(c(1),c(1),c(0),0))
expect_error(rmsprop_optimizer(c(1),c(NaN),c(0),.1))
expect_error(rmsprop_optimizer(c(1e308),c(1e308),c(0),.1))
cat("R RMSProp tests passed\n")
