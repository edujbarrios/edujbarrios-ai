args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"batch_normalization.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
x<-matrix(c(1,10,3,10),nrow=2,byrow=TRUE)
out<-batch_normalization(x,c(1,2),c(0,-1))
s<-1/sqrt(1+1e-5)
stopifnot(abs(out[1,1]+s)<1e-12,abs(out[2,1]-s)<1e-12)
stopifnot(identical(as.double(out[,2]),c(-1.0,-1.0)))
single<-batch_normalization(matrix(c(7,4),nrow=1),c(1,2),c(0,-1))
stopifnot(identical(as.double(single[1,]),c(0.0,-1.0)))
negative<-batch_normalization(x,c(-1,0),c(0,-1))
stopifnot(abs(negative[1,1]-s)<1e-12)
expect_error(batch_normalization(matrix(numeric(),nrow=0,ncol=1),c(1),c(0)))
expect_error(batch_normalization(x,c(1),c(0)))
expect_error(batch_normalization(matrix(c(1,NaN),ncol=1),c(1),c(0)))
expect_error(batch_normalization(matrix(c(1000001),ncol=1),c(1),c(0)))
cat("R batch normalization tests passed\n")
