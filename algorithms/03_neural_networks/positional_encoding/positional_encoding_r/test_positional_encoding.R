args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"positional_encoding.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
v<-positional_encoding(2,4)
stopifnot(identical(unname(v[1,]),c(0,1,0,1)))
stopifnot(abs(v[2,1]-sin(1))<1e-12)
stopifnot(abs(v[2,2]-cos(1))<1e-12)
stopifnot(abs(v[2,3]-sin(0.01))<1e-12)
stopifnot(abs(v[2,4]-cos(0.01))<1e-12)
stopifnot(identical(unname(positional_encoding(1,1)),matrix(0,nrow=1,ncol=1)))
stopifnot(identical(unname(positional_encoding(2,3)[1,]),c(0,1,0)))
expect_error(positional_encoding(0,4))
expect_error(positional_encoding(4,0))
expect_error(positional_encoding(4097,1))
expect_error(positional_encoding(1,1025))
expect_error(positional_encoding(1.5,3))
v<-positional_encoding(4,7)
stopifnot(all(is.finite(v)),all(v>=-1),all(v<=1))
cat("R positional encoding tests passed\n")
