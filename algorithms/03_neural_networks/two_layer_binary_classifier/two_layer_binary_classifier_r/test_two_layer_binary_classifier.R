args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
folder <- dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"two_layer_binary_classifier.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
error <- 1/(1+exp(-0.5))-1
fit <- two_layer_binary_classifier(c(0),c(1),0.2,1)
stopifnot(abs(fit[["w1"]]-1)<1e-12)
stopifnot(abs(fit[["b1"]]-(0.5-0.2*error))<1e-12)
stopifnot(abs(fit[["w2"]]-(1-0.2*error*0.5))<1e-12)
stopifnot(abs(fit[["b2"]]-(-0.2*error))<1e-12)
dead <- two_layer_binary_classifier(c(-1),c(1),0.2,1)
stopifnot(identical(unname(dead[1:3]),c(1,0.5,1)))
fit <- two_layer_binary_classifier(c(0,1,2,3),c(0,0,1,1),0.1,500)
stopifnot(two_layer_predict(fit,0)<0.1,two_layer_predict(fit,3)>0.9)
expect_error(two_layer_binary_classifier(numeric(),numeric(),0.1,1))
expect_error(two_layer_binary_classifier(c(0),c(2),0.1,1))
expect_error(two_layer_binary_classifier(c(NaN),c(1),0.1,1))
expect_error(two_layer_binary_classifier(c(0),c(1),0.0,1))
expect_error(two_layer_binary_classifier(c(0),c(1),0.1,0))
expect_error(two_layer_binary_classifier(c(1e308),c(0),1e308,2))
expect_error(two_layer_predict(fit,Inf))
cat("R two-layer binary classifier tests passed\n")
