args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
if(length(args)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder,"cross_entropy.R"))
error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e) TRUE))
stopifnot(abs(cross_entropy(c(0,0),0)-log(2))<1e-12)
stopifnot(abs(cross_entropy(c(1000,0),0))<1e-12)
stopifnot(abs(cross_entropy(c(1000,0),1)-1000)<1e-12)
error(cross_entropy(numeric(),0))
error(cross_entropy(c(1,2),2))
error(cross_entropy(c(1,2),-1))
error(cross_entropy(c(NaN),0))
error(cross_entropy(c(Inf),0))
cat("R cross entropy tests passed\n")
