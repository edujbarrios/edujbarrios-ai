args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
folder <- dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"group_normalization.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
near <- function(result,want) {
  stopifnot(length(result)==length(want),
            all(abs(result-want)<1e-10))
}
x <- 1:8
want <- rep(c(-1.5,-0.5,0.5,1.5)/sqrt(1.5),2)
near(group_normalization(x,4,2,2,rep(1,4),rep(0,4),0.25),want)
near(group_normalization(c(10,20),2,1,2,c(3,4),c(5,6),1e-5),c(5,6))
near(group_normalization(rep(7,4),2,2,2,c(3,4),c(5,6),1e-5),c(5,5,6,6))
near(group_normalization(9,1,1,1,2,3,1e-5),3)
want_affine <- c(1-6/sqrt(6),1-2/sqrt(6),-1+0.5/sqrt(6),-1+1.5/sqrt(6))
near(group_normalization(c(1,3,5,7),2,2,1,c(2,0.5),c(1,-1),1),want_affine)
near(group_normalization(rep(0,2048),32,64,8,rep(1,32),rep(0,32),1e-5),rep(0,2048))
near(group_normalization(rep(0,2048),32,64,32,rep(1,32),rep(2,32),1e-5),rep(2,2048))
near(group_normalization(rep(0,2048),32,64,1,rep(1,32),rep(3,32),1e-5),rep(3,2048))
expect_error(group_normalization(1,0,1,1,1,0,1e-5))
expect_error(group_normalization(1,33,1,1,1,0,1e-5))
expect_error(group_normalization(1,1,0,1,1,0,1e-5))
expect_error(group_normalization(1,1,65,1,1,0,1e-5))
expect_error(group_normalization(1,1,1,0,1,0,1e-5))
expect_error(group_normalization(1:3,3,1,2,1:3,rep(0,3),1e-5))
expect_error(group_normalization(1,TRUE,1,1,1,0,1e-5))
expect_error(group_normalization(numeric(0),1,1,1,1,0,1e-5))
expect_error(group_normalization(1,1,1,1,numeric(0),0,1e-5))
expect_error(group_normalization(1,1,1,1,1,numeric(0),1e-5))
expect_error(group_normalization(TRUE,1,1,1,1,0,1e-5))
expect_error(group_normalization(1,1,1,1,Inf,0,1e-5))
expect_error(group_normalization(1,1,1,1,1,NaN,1e-5))
expect_error(group_normalization(1001,1,1,1,1,0,1e-5))
expect_error(group_normalization(1,1,1,1,1,0,0))
expect_error(group_normalization(1,1,1,1,1,0,2))
expect_error(group_normalization(1,1,1,1,1,0,NaN))
expect_error(group_normalization(matrix(1,1,1),1,1,1,1,0,1e-5))
cat("R group normalization tests passed\n")
