args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"rotary_positional_embedding.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
v<-rotary_positional_embedding(c(1,0),c(0,1),1,0)
stopifnot(abs(v$query[[1]]-cos(1))<1e-12)
stopifnot(abs(v$query[[2]]-sin(1))<1e-12)
stopifnot(max(abs(v$key-c(0,1)))<1e-12)
v<-rotary_positional_embedding(c(3,4),c(5,6),0,0)
stopifnot(identical(v$query,c(3,4)),identical(v$key,c(5,6)))
v<-rotary_positional_embedding(c(1,0,1,0),c(1,0,1,0),1,1)
stopifnot(abs(v$query[[3]]-cos(.01))<1e-12)
stopifnot(abs(v$query[[4]]-sin(.01))<1e-12)
stopifnot(identical(v$query,v$key))
expect_error(rotary_positional_embedding(c(1),c(0),1,0))
expect_error(rotary_positional_embedding(c(1,0,2),c(0,1,2),1,0))
expect_error(rotary_positional_embedding(c(1,0),c(0,1),-1,0))
expect_error(rotary_positional_embedding(c(1,0),c(0,1),1000001,0))
expect_error(rotary_positional_embedding(c(NaN,0),c(0,1),1,0))
expect_error(rotary_positional_embedding(c(1.7e308,1.7e308),c(0,1),1,0))
cat("R rotary positional embedding tests passed\n")
