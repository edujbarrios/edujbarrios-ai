args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "inverted_dropout.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr); FALSE},
                                                  error=function(e) TRUE))
stopifnot(identical(inverted_dropout(c(2,-4,0), c(1,0,1), .5), c(4,0,0)))
stopifnot(identical(inverted_dropout(c(3,-2), c(1,1), 0), c(3,-2)))
stopifnot(identical(inverted_dropout(1e308, 0, .99), 0))
stopifnot(identical(inverted_dropout(numeric(), numeric(), .5), numeric()))
expect_error(inverted_dropout(1, numeric(), .5))
expect_error(inverted_dropout(1, 2, .5))
expect_error(inverted_dropout(NaN, 0, .5))
expect_error(inverted_dropout(Inf, 1, .5))
expect_error(inverted_dropout(1, 1, -.1))
expect_error(inverted_dropout(1, 1, 1))
expect_error(inverted_dropout(1, 1, NaN))
expect_error(inverted_dropout(1e308, 1, .99))
cat("R inverted dropout tests passed\n")
