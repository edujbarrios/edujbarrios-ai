args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"adam_optimizer.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
first<-adam_optimizer(c(2,-3),c(1,-2),c(0,0),c(0,0),0.1,1)
stopifnot(abs(first$parameters[[1]]-(2-0.1/(1+1e-8)))<1e-12)
stopifnot(abs(first$parameters[[2]]-(-3+0.2/(2+1e-8)))<1e-12)
stopifnot(max(abs(first$m-c(0.1,-0.2)))<1e-12)
stopifnot(max(abs(first$v-c(0.001,0.004)))<1e-12)
second<-adam_optimizer(first$parameters,c(0,0),first$m,first$v,0.1,2)
stopifnot(second$m[[1]]<first$m[[1]],second$m[[2]]>first$m[[2]])
expect_error(adam_optimizer(numeric(),numeric(),numeric(),numeric(),0.1,1))
expect_error(adam_optimizer(c(1),numeric(),c(0),c(0),0.1,1))
expect_error(adam_optimizer(c(1),c(1),c(0),c(-1),0.1,1))
expect_error(adam_optimizer(c(1),c(NaN),c(0),c(0),0.1,1))
expect_error(adam_optimizer(c(1),c(1e308),c(0),c(0),0.1,1))
expect_error(adam_optimizer(c(1),c(1),c(0),c(0),0,1))
expect_error(adam_optimizer(c(1),c(1),c(0),c(0),0.1,0))
cat("R Adam optimizer tests passed\n")
