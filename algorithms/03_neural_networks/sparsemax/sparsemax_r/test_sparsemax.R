args <- grep("^--file=", commandArgs(FALSE), value = TRUE)
if (length(args) == 0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "sparsemax.R"))
errors <- function(expr) stopifnot(tryCatch({force(expr); FALSE}, error = function(e) TRUE))

stopifnot(identical(sparsemax(c(0, 0, -1)), c(0.5, 0.5, 0)))
stopifnot(identical(sparsemax(c(3, 1, 0)), c(1, 0, 0)))
stopifnot(identical(sparsemax(c(100, 100, 99)), c(0.5, 0.5, 0)))
stopifnot(max(abs(sparsemax(c(1, 1, 1)) - rep(1 / 3, 3))) < 1e-12)
stopifnot(identical(sparsemax(1e308), 1.0))
stopifnot(identical(sparsemax(c(1e308, -1e308)), c(1, 0)))
stopifnot(max(abs(sparsemax(c(2, 1, 0)) - sparsemax(c(102, 101, 100)))) < 1e-12)
errors(sparsemax(numeric()))
errors(sparsemax(c(NaN)))
errors(sparsemax(c(Inf)))
errors(sparsemax(c(TRUE)))
cat("R sparsemax tests passed\n")
