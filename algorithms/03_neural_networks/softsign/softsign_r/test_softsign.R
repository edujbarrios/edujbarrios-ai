file_arg <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(file_arg)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",file_arg[[1L]])))
source(file.path(folder,"softsign.R"))
close <- function(actual,expected) stopifnot(all(abs(actual-expected)<1e-12))
expect_error <- function(expr) {
  failed <- tryCatch({force(expr);FALSE},error=function(e) TRUE)
  stopifnot(failed)
}
close(softsign(c(-2,-1,0,1,2)),c(-2/3,-0.5,0,0.5,2/3))
close(softsign(c(1000000,-1000000)),c(1000000/1000001,-1000000/1000001))
close(softsign(0),0)
expect_error(softsign(numeric()))
expect_error(softsign(NaN))
expect_error(softsign(Inf))
expect_error(softsign(1000001))
expect_error(softsign(-1000001))
expect_error(softsign("1"))
expect_error(softsign(matrix(1,nrow=1)))
cat("R Softsign tests passed\n")
