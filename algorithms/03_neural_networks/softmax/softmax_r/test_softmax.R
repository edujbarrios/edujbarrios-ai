args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
if(length(args)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "softmax.R"))
error <- function(expr) stopifnot(tryCatch({force(expr); FALSE},error=function(e) TRUE))
stopifnot(max(abs(softmax(c(1,1,1)) - rep(1/3,3))) < 1e-12)
x <- softmax(c(1000,1001))
stopifnot(all(is.finite(x)), x[[2]]>x[[1]], abs(sum(x)-1)<1e-12)
stopifnot(identical(softmax(c(1e308)),1.0))
error(softmax(numeric()))
error(softmax(c(1,NaN)))
error(softmax(c(Inf)))
cat("R softmax tests passed\n")
