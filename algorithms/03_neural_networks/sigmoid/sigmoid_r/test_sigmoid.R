args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
if(length(args)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder,"sigmoid.R"))
error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e) TRUE))
out <- sigmoid(c(-1,0,1))
stopifnot(abs(out[[1]]-0.2689414213699951)<1e-12)
stopifnot(out[[2]]==0.5)
stopifnot(abs(out[[3]]-0.7310585786300049)<1e-12)
stopifnot(identical(sigmoid(c(-1e308,1e308)),c(0,1)))
stopifnot(identical(sigmoid(numeric()),numeric()))
error(sigmoid(c(1,NaN)))
error(sigmoid(c(Inf)))
