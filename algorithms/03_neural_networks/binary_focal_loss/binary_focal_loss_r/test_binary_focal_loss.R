args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"binary_focal_loss.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
stopifnot(abs(binary_focal_loss(c(.5,.5),c(1,0))-log(2)/8)<1e-12)
stopifnot(identical(binary_focal_loss(c(0,1),c(0,1)),0.0))
stopifnot(abs(binary_focal_loss(c(0,1),c(1,0))-log(1e12)/2)<1e-10)
stopifnot(abs(binary_focal_loss(c(.5),c(1))-log(2)/16)<1e-12)
stopifnot(binary_focal_loss(c(.1),c(1))>binary_focal_loss(c(.9),c(1)))
expect_error(binary_focal_loss(numeric(),numeric()))
expect_error(binary_focal_loss(c(.5),numeric()))
expect_error(binary_focal_loss(c(1.2,.5),c(1,0)))
expect_error(binary_focal_loss(c(NaN),c(1)))
expect_error(binary_focal_loss(c(.5),c(2)))
cat("R binary focal loss tests passed\n")
