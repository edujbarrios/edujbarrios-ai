args <- grep("^--file=", commandArgs(FALSE), value = TRUE)
if (length(args) == 0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "gradient_clip_global_norm.R"))
errors <- function(expr) stopifnot(tryCatch({force(expr); FALSE}, error = function(e) TRUE))

stopifnot(max(abs(gradient_clip_global_norm(c(3, 4), 1) - c(0.6, 0.8))) < 1e-12)
stopifnot(identical(gradient_clip_global_norm(c(3, 4), 5), c(3, 4)))
stopifnot(identical(gradient_clip_global_norm(c(0, 0), 1), c(0, 0)))
extreme <- gradient_clip_global_norm(c(1e308, -1e308), 1)
stopifnot(all(is.finite(extreme)), max(abs(extreme - c(sqrt(0.5), -sqrt(0.5)))) < 1e-12)
errors(gradient_clip_global_norm(numeric(), 1))
errors(gradient_clip_global_norm(1, 0))
errors(gradient_clip_global_norm(c(1, NaN), 1))
errors(gradient_clip_global_norm(1, Inf))
errors(gradient_clip_global_norm(TRUE, 1))
cat("R gradient norm clipping tests passed\n")
