args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
if (length(args) == 0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "binary_dice_coefficient.R"))
error <- function(expr) stopifnot(tryCatch({force(expr); FALSE}, error=function(e) TRUE))
stopifnot(identical(binary_dice_coefficient(c(1,1,0,0),c(1,0,1,0)),0.5))
stopifnot(identical(binary_dice_coefficient(c(0,0),c(0,0)),1.0))
stopifnot(identical(binary_dice_coefficient(c(1,0),c(0,1)),0))
stopifnot(identical(binary_dice_coefficient(c(1,0),c(1,0)),1.0))
error(binary_dice_coefficient(numeric(),numeric()))
error(binary_dice_coefficient(1,c(1,0)))
error(binary_dice_coefficient(c(1,2),c(1,0)))
error(binary_dice_coefficient(TRUE,1))
cat("R binary Dice tests passed\n")
