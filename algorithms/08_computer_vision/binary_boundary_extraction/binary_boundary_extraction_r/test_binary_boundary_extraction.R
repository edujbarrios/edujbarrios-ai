args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
folder <- dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"binary_boundary_extraction.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
check <- function(p,h,w,want) {
  stopifnot(identical(binary_boundary_extraction(p,h,w),as.integer(want)))
}
check(rep(1,9),3,3,c(1,1,1,1,0,1,1,1,1))
check(c(0,0,0,0,1,0,0,0,0),3,3,c(0,0,0,0,1,0,0,0,0))
check(c(1,1,1,1,0,1,1,1,1),3,3,c(1,1,1,1,0,1,1,1,1))
check(rep(0,9),3,3,rep(0,9))
check(1,1,1,1)
check(0,1,1,0)
check(rep(1,4),1,4,rep(1,4))
check(rep(1,4),4,1,rep(1,4))
check(c(1,0,0,1),2,2,c(1,0,0,1))
result <- binary_boundary_extraction(rep.int(1L,4096),64,64)
stopifnot(sum(result)==252L,result[[1L]]==1L,result[[32L*64L+33L]]==0L)
check(rep(0,4096),64,64,rep(0,4096))
checker <- integer(4096)
for (r in 0:63) for (c in 0:63) checker[[r*64L+c+1L]] <- (r+c)%%2L
check(checker,64,64,checker)
expect_error(binary_boundary_extraction(1,0,1))
expect_error(binary_boundary_extraction(1,1,0))
expect_error(binary_boundary_extraction(1,65,1))
expect_error(binary_boundary_extraction(1,1,65))
expect_error(binary_boundary_extraction(TRUE,1,1))
expect_error(binary_boundary_extraction(1,TRUE,1))
expect_error(binary_boundary_extraction(c(0,2),1,2))
expect_error(binary_boundary_extraction(0.5,1,1))
expect_error(binary_boundary_extraction(c(0,NA_real_),1,2))
expect_error(binary_boundary_extraction(matrix(1:4,2,2),2,2))
cat("R boundary extraction tests passed\n")
