file_arg <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(file_arg)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",file_arg[[1L]])))
source(file.path(folder,"binary_erosion.R"))
expect_error <- function(expr) {
  failed <- tryCatch({force(expr);FALSE},error=function(e) TRUE)
  stopifnot(failed)
}
stopifnot(identical(binary_erosion(rep(1,9),3,3),c(0L,0L,0L,0L,1L,0L,0L,0L,0L)))
stopifnot(identical(binary_erosion(rep(0,9),3,3),rep(0L,9)))
stopifnot(identical(binary_erosion(c(1,1,1,1,0,1,1,1,1),3,3),rep(0L,9)))
stopifnot(identical(binary_erosion(rep(1,3),1,3),rep(0L,3)))
stopifnot(identical(binary_erosion(1,1,1),0L))
expect_error(binary_erosion(rep(1,9),0,3))
expect_error(binary_erosion(rep(1,9),3,0))
expect_error(binary_erosion(rep(1,9),65,3))
expect_error(binary_erosion(rep(1,9),3,65))
expect_error(binary_erosion(rep(1,8),3,3))
expect_error(binary_erosion(c(0,2,0),1,3))
expect_error(binary_erosion(c(0,NA,0),1,3))
cat("R erosion tests passed\n")
