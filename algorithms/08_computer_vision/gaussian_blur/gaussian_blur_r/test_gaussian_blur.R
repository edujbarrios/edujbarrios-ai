file_arg <- grep("^--file=", commandArgs(FALSE), value=TRUE)
if (length(file_arg) == 0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=", "", file_arg[[1L]])))
source(file.path(folder, "gaussian_blur.R"))
expect_error <- function(expr) {
  failed <- tryCatch({force(expr); FALSE}, error=function(e) TRUE)
  stopifnot(failed)
}
impulse <- c(0,0,0,0,16,0,0,0,0)
stopifnot(isTRUE(all.equal(gaussian_blur(impulse,3,3),c(1,2,1,2,4,2,1,2,1))))
stopifnot(isTRUE(all.equal(gaussian_blur(c(0,0,8),1,3),c(0,2,6))))
stopifnot(isTRUE(all.equal(gaussian_blur(7,1,1),7)))
stopifnot(isTRUE(all.equal(gaussian_blur(rep(5,6),2,3),rep(5,6))))
stopifnot(isTRUE(all.equal(gaussian_blur(c(0,8,0),1,3),c(2,4,2))))
expect_error(gaussian_blur(numeric(0),0,0))
expect_error(gaussian_blur(c(0,0,0,0),0,2))
expect_error(gaussian_blur(c(0,0,0,0),2,65))
expect_error(gaussian_blur(c(0,0,0),2,2))
expect_error(gaussian_blur(c(0,0,NaN,0),2,2))
expect_error(gaussian_blur(c(0,0,Inf,0),2,2))
expect_error(gaussian_blur(c(0,0,1000001,0),2,2))
expect_error(gaussian_blur(matrix(1,2,2),2,2))
cat("R gaussian_blur tests passed\n")
