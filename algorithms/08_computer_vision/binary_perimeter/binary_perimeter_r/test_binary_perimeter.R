args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
folder <- dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"binary_perimeter.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
check <- function(p,h,w,want) {
  stopifnot(identical(binary_perimeter(p,h,w),as.integer(want)))
}
check(1,1,1,4)
check(0,1,1,0)
check(rep(1,4),2,2,8)
check(rep(0,4),2,2,0)
check(c(1,0,1),1,3,8)
check(c(1,1,1),1,3,8)
check(c(1,1,1),3,1,8)
check(c(1,1,1,1,0,1,1,1,1),3,3,16)
check(c(0,0,0,0,1,0,0,0,0),3,3,4)
check(c(1,0,0,1),2,2,8)
check(rep.int(1L,4096),64,64,256)
checker <- integer(4096)
for (r in 0:63) for (c in 0:63) checker[[r*64L+c+1L]] <- (r+c)%%2L
check(checker,64,64,8192)
check(rep.int(0L,4096),64,64,0)
expect_error(binary_perimeter(1,0,1))
expect_error(binary_perimeter(1,1,0))
expect_error(binary_perimeter(1,65,1))
expect_error(binary_perimeter(1,1,65))
expect_error(binary_perimeter(TRUE,1,1))
expect_error(binary_perimeter(1,TRUE,1))
expect_error(binary_perimeter(c(0,2),1,2))
expect_error(binary_perimeter(0.5,1,1))
expect_error(binary_perimeter(c(0,NA_real_),1,2))
expect_error(binary_perimeter(matrix(1:4,2,2),2,2))
cat("R binary perimeter tests passed\n")
