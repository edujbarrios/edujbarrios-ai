file_arg <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(file_arg)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",file_arg[[1L]])))
source(file.path(folder,"otsu_threshold.R"))
expect_error <- function(expr) {
  failed <- tryCatch({force(expr);FALSE},error=function(e) TRUE)
  stopifnot(failed)
}
stopifnot(identical(otsu_threshold(c(10,20,200,210)),20L))
stopifnot(identical(otsu_threshold(c(0,0,255,255)),0L))
stopifnot(identical(otsu_threshold(c(1,2)),1L))
stopifnot(identical(otsu_threshold(c(7,7,7)),0L))
stopifnot(identical(otsu_threshold(255),0L))
expect_error(otsu_threshold(numeric()))
expect_error(otsu_threshold(rep(0,4097)))
expect_error(otsu_threshold(-1))
expect_error(otsu_threshold(256))
expect_error(otsu_threshold(1.5))
expect_error(otsu_threshold(NA))
expect_error(otsu_threshold(Inf))
cat("R Otsu threshold tests passed\n")
