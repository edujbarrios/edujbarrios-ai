args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "soft_dice_loss.R"))
error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e) TRUE))
loss <- soft_dice_loss
near <- function(actual,expected) stopifnot(abs(actual-expected) < 1e-12)
near(loss(c(0,0),c(0,0)),0)
near(loss(c(1,0),c(1,0)),0)
near(loss(c(0,1),c(1,0)),2/3)
near(loss(c(.5,.5),c(1,0)),1/3)
near(loss(c(1,1),c(0,0)),2/3)
near(loss(c(0,0),c(1,0)),.5)
near(loss(1,1),0)
near(loss(rep(0,512),rep(0,512)),0)
near(loss(rep(1,512),rep(1,512)),0)
error(loss(numeric(),numeric()))
error(loss(0,c(0,1)))
error(loss(rep(0,513),rep(0,513)))
error(loss(NULL,0))
error(loss(NaN,0))
error(loss(Inf,0))
error(loss(-.1,0))
error(loss(1.1,1))
error(loss(TRUE,1))
error(loss(0,TRUE))
error(loss(0,.5))
error(loss(0,2))
error(loss(0,-1))
error(loss(matrix(0,nrow=1),0))
cat("R soft Dice loss tests passed\n")
