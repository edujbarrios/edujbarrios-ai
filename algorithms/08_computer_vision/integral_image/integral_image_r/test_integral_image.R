args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "integral_image.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr); FALSE}, error=function(e) TRUE))
stopifnot(identical(integral_image(c(1,2,3,4),2,2), c(1L,3L,4L,10L)))
stopifnot(identical(integral_image(c(0,0,0,0),2,2), integer(4)))
stopifnot(identical(integral_image(5,1,1), 5L))
stopifnot(identical(integral_image(c(1,2,3),1,3), c(1L,3L,6L)))
stopifnot(identical(integral_image(c(1,2,3),3,1), c(1L,3L,6L)))
full <- integral_image(rep(255,4096),64,64)
stopifnot(identical(full[[1]], 255L))
stopifnot(identical(full[[64]], 64L*255L))
stopifnot(identical(full[[4096]], 64L*64L*255L))
expect_error(integral_image(0,0,1))
expect_error(integral_image(0,65,1))
expect_error(integral_image(0,1,65))
expect_error(integral_image(0,TRUE,1))
expect_error(integral_image(c(0,1),1,1))
expect_error(integral_image(-1,1,1))
expect_error(integral_image(256,1,1))
expect_error(integral_image(1.0/2,1,1))
expect_error(integral_image(TRUE,1,1))
expect_error(integral_image(matrix(1:4,2,2),2,2))
cat("R integral image tests passed\n")
