args <- grep("^--file=", commandArgs(FALSE), value = TRUE)
if (length(args) == 0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "binary_iou.R"))
errors <- function(expr) stopifnot(tryCatch({force(expr); FALSE}, error = function(e) TRUE))

stopifnot(abs(binary_iou(c(1, 1, 0, 0), c(1, 0, 1, 0)) - 1 / 3) < 1e-12)
stopifnot(identical(binary_iou(c(1, 0), c(1, 0)), 1.0))
stopifnot(identical(binary_iou(c(0, 0), c(0, 0)), 1.0))
stopifnot(identical(binary_iou(c(1, 0), c(0, 1)), 0))
errors(binary_iou(numeric(), numeric()))
errors(binary_iou(1, c(1, 0)))
errors(binary_iou(c(0, 2), c(0, 1)))
errors(binary_iou(TRUE, 1))
errors(binary_iou(NA_real_, 0))
cat("R binary IoU tests passed\n")
