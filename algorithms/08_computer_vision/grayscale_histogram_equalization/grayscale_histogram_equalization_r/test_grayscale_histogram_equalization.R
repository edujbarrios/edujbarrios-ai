args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "grayscale_histogram_equalization.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
stopifnot(identical(grayscale_histogram_equalization(c(10,10,20,30),2,2),c(0L,0L,128L,255L)))
stopifnot(identical(grayscale_histogram_equalization(c(20,20,20),1,3),c(20L,20L,20L)))
stopifnot(identical(grayscale_histogram_equalization(c(0,255),1,2),c(0L,255L)))
stopifnot(identical(grayscale_histogram_equalization(1,1,1),1L))
stopifnot(identical(grayscale_histogram_equalization(0:4,1,5),c(0L,64L,128L,191L,255L)))
big <- c(rep(0L,4095),255L)
out <- grayscale_histogram_equalization(big,64,64)
stopifnot(identical(out[[1]],0L),identical(out[[4095]],0L),identical(out[[4096]],255L))
expect_error(grayscale_histogram_equalization(0,0,1))
expect_error(grayscale_histogram_equalization(0,65,1))
expect_error(grayscale_histogram_equalization(0,1,0))
expect_error(grayscale_histogram_equalization(0,1,65))
expect_error(grayscale_histogram_equalization(0,TRUE,1))
expect_error(grayscale_histogram_equalization(c(0,1),1,1))
expect_error(grayscale_histogram_equalization(-1,1,1))
expect_error(grayscale_histogram_equalization(256,1,1))
expect_error(grayscale_histogram_equalization(0.5,1,1))
expect_error(grayscale_histogram_equalization(TRUE,1,1))
expect_error(grayscale_histogram_equalization(matrix(1:4,2,2),2,2))
cat("R histogram equalization tests passed\n")
