args <- grep("^--file=", commandArgs(FALSE), value = TRUE)
if (length(args) == 0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "bounding_box_iou.R"))
errors <- function(expr) stopifnot(tryCatch({force(expr); FALSE}, error = function(e) TRUE))

a <- c(0, 0, 2, 2)
stopifnot(abs(bounding_box_iou(a, c(1, 1, 3, 3)) - 1/7) < 1e-12)
stopifnot(identical(bounding_box_iou(a, a), 1.0))
stopifnot(identical(bounding_box_iou(a, c(2, 0, 3, 1)), 0))
stopifnot(identical(bounding_box_iou(a, c(4, 4, 5, 5)), 0))
errors(bounding_box_iou(a, c(0, 0, 1)))
errors(bounding_box_iou(a, c(0, 0, 0, 1)))
errors(bounding_box_iou(a, c(0, Inf, 2, 2)))
errors(bounding_box_iou(a, c(0, 0, 1000001, 2)))
errors(bounding_box_iou(a, c(TRUE, FALSE, TRUE, FALSE)))
cat("R bounding box IoU tests passed\n")
