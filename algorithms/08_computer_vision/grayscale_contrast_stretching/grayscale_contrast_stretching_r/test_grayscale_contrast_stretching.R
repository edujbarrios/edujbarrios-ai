args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder,"grayscale_contrast_stretching.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
stopifnot(identical(grayscale_contrast_stretching(c(10,10,15,20),2,2),c(0L,0L,128L,255L)))
stopifnot(identical(grayscale_contrast_stretching(5:8,1,4),c(0L,85L,170L,255L)))
stopifnot(identical(grayscale_contrast_stretching(c(99,99),1,2),c(99L,99L)))
stopifnot(identical(grayscale_contrast_stretching(c(0,255),1,2),c(0L,255L)))
stopifnot(identical(grayscale_contrast_stretching(5,1,1),5L))
stopifnot(identical(grayscale_contrast_stretching(c(0,1,2),1,3),c(0L,128L,255L)))
big <- c(rep(50L,4095),100L)
answer <- grayscale_contrast_stretching(big,64,64)
stopifnot(identical(answer[[1]],0L),identical(answer[[4095]],0L),identical(answer[[4096]],255L))
stopifnot(identical(grayscale_contrast_stretching(rep(120,4096),64,64),rep(120L,4096)))
expect_error(grayscale_contrast_stretching(0,0,1))
expect_error(grayscale_contrast_stretching(0,1,0))
expect_error(grayscale_contrast_stretching(0,65,1))
expect_error(grayscale_contrast_stretching(0,1,65))
expect_error(grayscale_contrast_stretching(0,TRUE,1))
expect_error(grayscale_contrast_stretching(c(0,1),1,1))
expect_error(grayscale_contrast_stretching(-1,1,1))
expect_error(grayscale_contrast_stretching(256,1,1))
expect_error(grayscale_contrast_stretching(0.5,1,1))
expect_error(grayscale_contrast_stretching(TRUE,1,1))
expect_error(grayscale_contrast_stretching(matrix(1:4,2,2),2,2))
cat("R grayscale contrast stretching tests passed\n")
