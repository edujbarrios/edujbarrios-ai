args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
folder <- dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"binary_distance_transform.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
stopifnot(identical(binary_distance_transform(c(1,1,1,1,0,1,1,1,1),3,3),
                    c(2L,1L,2L,1L,0L,1L,2L,1L,2L)))
stopifnot(identical(binary_distance_transform(c(0,1,1,1),2,2),c(0L,1L,1L,2L)))
stopifnot(identical(binary_distance_transform(rep(1,4),2,2),rep(4L,4)))
stopifnot(identical(binary_distance_transform(rep(0,4),2,2),integer(4)))
stopifnot(identical(binary_distance_transform(0,1,1),0L))
stopifnot(identical(binary_distance_transform(1,1,1),2L))
stopifnot(identical(binary_distance_transform(c(1,0,1,1),1,4),c(1L,0L,1L,2L)))
stopifnot(identical(binary_distance_transform(c(1,0,1,1),4,1),c(1L,0L,1L,2L)))
big <- rep.int(1L,4096)
big[[1L]] <- 0L
result <- binary_distance_transform(big,64,64)
stopifnot(identical(result[[1L]],0L),identical(result[[2L]],1L))
stopifnot(identical(result[[65L]],1L),identical(result[[4096L]],126L))
stopifnot(identical(binary_distance_transform(rep(1L,4096),64,64),rep.int(128L,4096)))
expect_error(binary_distance_transform(1,0,1))
expect_error(binary_distance_transform(1,1,0))
expect_error(binary_distance_transform(1,65,1))
expect_error(binary_distance_transform(1,1,65))
expect_error(binary_distance_transform(TRUE,1,1))
expect_error(binary_distance_transform(1,TRUE,1))
expect_error(binary_distance_transform(c(0,2),1,2))
expect_error(binary_distance_transform(1.5,1,1))
expect_error(binary_distance_transform(c(0,NA_real_),1,2))
expect_error(binary_distance_transform(matrix(1:4,2,2),2,2))
cat("R binary distance transform tests passed\n")
