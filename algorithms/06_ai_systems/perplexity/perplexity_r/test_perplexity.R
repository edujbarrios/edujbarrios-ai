args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"perplexity.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
stopifnot(abs(perplexity(c(log(.5),log(.25)))-sqrt(8))<1e-12)
stopifnot(abs(perplexity(rep(log(.25),2))-4)<1e-12)
stopifnot(identical(perplexity(c(0,0,0)),1.0))
stopifnot(abs(perplexity(c(log(.5)))-2)<1e-12)
stopifnot(abs(perplexity(rep(log(.5),100))-2)<1e-12)
expect_error(perplexity(numeric()))
expect_error(perplexity(c(NaN)))
expect_error(perplexity(c(Inf)))
expect_error(perplexity(c(-Inf)))
expect_error(perplexity(c(.1)))
expect_error(perplexity(c(-1000)))
cat("R perplexity tests passed\n")
