args <- grep("^--file=", commandArgs(FALSE), value = TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "f_beta_score.R"))
expect_error <- function(expr) {
  stopifnot(tryCatch({ force(expr); FALSE }, error = function(e) TRUE))
}
stopifnot(abs(f_beta_score(8, 2, 4) - 8 / 11) < 1e-12)
stopifnot(abs(f_beta_score(8, 2, 4, 2) - 20 / 29) < 1e-12)
stopifnot(abs(f_beta_score(8, 2, 4, 0.5) - 10 / 13) < 1e-12)
stopifnot(abs(f_beta_score(8, 2, 4, 1e-300) - 0.8) < 1e-12)
stopifnot(abs(f_beta_score(8, 2, 4, 1e300) - 2 / 3) < 1e-12)
stopifnot(f_beta_score(0, 0, 0) == 0)
stopifnot(f_beta_score(2147483647, 0, 0) == 1)
expect_error(f_beta_score(-1, 0, 0))
expect_error(f_beta_score(1, 0, 0, 0))
expect_error(f_beta_score(1, 0, 0, Inf))
expect_error(f_beta_score(1, 0, 0, NaN))
expect_error(f_beta_score(1, 0, 0, TRUE))
cat("R F-beta tests passed\n")
