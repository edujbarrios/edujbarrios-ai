args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"expected_calibration_error.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
stopifnot(abs(expected_calibration_error(c(.9,.8,.2,.6),c(1,0,0,1),2)-.025)<1e-12)
stopifnot(abs(expected_calibration_error(c(.9,.8,.2,.6),c(1,0,0,1),4)-.225)<1e-12)
stopifnot(identical(expected_calibration_error(c(1,0),c(1,0),10),0.0))
stopifnot(identical(expected_calibration_error(c(.5,.5),c(0,1),1),0.0))
stopifnot(identical(expected_calibration_error(c(1),c(0),100),1.0))
expect_error(expected_calibration_error(numeric(),numeric(),2))
expect_error(expected_calibration_error(c(.5),numeric(),2))
expect_error(expected_calibration_error(c(.5),c(1),0))
expect_error(expected_calibration_error(c(.5),c(1),101))
expect_error(expected_calibration_error(c(1.1),c(1),2))
expect_error(expected_calibration_error(c(NaN),c(1),2))
expect_error(expected_calibration_error(c(.5),c(2),2))
cat("R expected calibration error tests passed\n")
