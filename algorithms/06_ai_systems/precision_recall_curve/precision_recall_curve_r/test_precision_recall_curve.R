args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "precision_recall_curve.R"))
expect_error <- function(expr) stopifnot(tryCatch({ force(expr); FALSE },
                                                  error=function(e) TRUE))
observed <- precision_recall_curve(c(.8, .8, .5, .2), c(1, 0, 1, 0))
expected <- rbind(c(.8, .5, .5), c(.5, 2/3, 1), c(.2, .5, 1))
stopifnot(nrow(observed) == 3L, all(abs(unname(observed) - expected) < 1e-12))
stopifnot(identical(colnames(observed), c("threshold", "precision", "recall")))
stopifnot(identical(unname(precision_recall_curve(1, 1)), matrix(c(1,1,1),nrow=1)))
stopifnot(all(precision_recall_curve(c(.4,.4),c(1,1))[,2:3] == 1))
expect_error(precision_recall_curve(numeric(), numeric()))
expect_error(precision_recall_curve(.5, numeric()))
expect_error(precision_recall_curve(.5, 0))
expect_error(precision_recall_curve(-.1, 1))
expect_error(precision_recall_curve(1.1, 1))
expect_error(precision_recall_curve(NaN, 1))
expect_error(precision_recall_curve(.5, 2))
cat("R precision–recall curve tests passed\n")
