args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if(length(args)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"weighted_mean_absolute_error.R"))
error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e) TRUE))
stopifnot(identical(weighted_mean_absolute_error(c(1,3),c(2,1),c(1,3)),1.75))
stopifnot(identical(weighted_mean_absolute_error(c(1,3),c(1,3),c(1,3)),0))
stopifnot(identical(weighted_mean_absolute_error(c(1,3),c(2,1),c(0,2)),2))
stopifnot(identical(weighted_mean_absolute_error(1,2,1),1))
error(weighted_mean_absolute_error(numeric(),numeric(),numeric()))
error(weighted_mean_absolute_error(1,2,0))
error(weighted_mean_absolute_error(1,2,-1))
error(weighted_mean_absolute_error(1,2,Inf))
error(weighted_mean_absolute_error(1,2,TRUE))
error(weighted_mean_absolute_error(1,2,1000001))
error(weighted_mean_absolute_error(1,2:3,1))
cat("R weighted MAE tests passed\n")
