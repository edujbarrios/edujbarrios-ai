args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"average_precision_at_k.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
rel<-c(1,0,1,0,1)
stopifnot(abs(average_precision_at_k(rel,2,3)-.5)<1e-12)
stopifnot(abs(average_precision_at_k(rel,4,3)-5/9)<1e-12)
stopifnot(abs(average_precision_at_k(rel,5,3)-34/45)<1e-12)
stopifnot(identical(average_precision_at_k(c(0,0),2,0),0.0))
stopifnot(identical(average_precision_at_k(c(1,1,1),3,3),1.0))
stopifnot(identical(average_precision_at_k(c(0,0,1),2,1),0.0))
expect_error(average_precision_at_k(numeric(),1,0))
expect_error(average_precision_at_k(c(1,0),0,1))
expect_error(average_precision_at_k(c(1,0),3,1))
expect_error(average_precision_at_k(c(1,0,1),1,1))
expect_error(average_precision_at_k(c(0,0,2),1,2))
expect_error(average_precision_at_k(c(1),1,-1))
cat("R average precision at K tests passed\n")
