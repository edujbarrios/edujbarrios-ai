args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"top_p_nucleus_filtering.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
p<-c(.4,.3,.2,.1)
stopifnot(identical(top_p_nucleus_filtering(p,.6),c(0L,1L)))
stopifnot(identical(top_p_nucleus_filtering(p,.85),c(0L,1L,2L)))
stopifnot(identical(top_p_nucleus_filtering(p,.95),c(0L,1L,2L,3L)))
stopifnot(identical(top_p_nucleus_filtering(c(.5,.5,0),.5),c(0L)))
stopifnot(identical(top_p_nucleus_filtering(c(.5,.5,0),.75),c(0L,1L)))
stopifnot(identical(top_p_nucleus_filtering(c(.5,.5,0),1),c(0L,1L)))
stopifnot(identical(top_p_nucleus_filtering(c(1),1),c(0L)))
expect_error(top_p_nucleus_filtering(numeric(),.5))
expect_error(top_p_nucleus_filtering(c(.7,.7),.5))
expect_error(top_p_nucleus_filtering(c(1.1,-.1),.5))
expect_error(top_p_nucleus_filtering(c(NaN,1),.5))
expect_error(top_p_nucleus_filtering(c(.5,.5),0))
expect_error(top_p_nucleus_filtering(c(.5,.5),1.1))
cat("R nucleus top-p tests passed\n")
