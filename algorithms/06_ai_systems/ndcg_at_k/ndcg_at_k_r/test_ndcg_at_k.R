args <- grep("^--file=", commandArgs(FALSE), value = TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "ndcg_at_k.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr); FALSE}, error = function(e) TRUE))
stopifnot(abs(ndcg_at_k(c(3,2,1,0),3)-1)<1e-12)
value <- ndcg_at_k(c(3,2,0,1),3)
stopifnot(value > 0.9, value < 1)
stopifnot(identical(ndcg_at_k(c(0,0,0),2),0.0))
expect_error(ndcg_at_k(numeric(),1))
expect_error(ndcg_at_k(c(1),0))
expect_error(ndcg_at_k(c(1),2))
expect_error(ndcg_at_k(c(1,2,21),1))
expect_error(ndcg_at_k(c(0.5),1))
cat("R NDCG@K tests passed\n")
