file_arg<-grep("^--file=",commandArgs(FALSE),value=TRUE)
if(length(file_arg)==0L) stop("run with Rscript")
folder<-dirname(normalizePath(sub("^--file=","",file_arg[[1L]])))
source(file.path(folder,"root_mean_squared_error.R"))
err<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e) TRUE))
close<-function(a,b) stopifnot(abs(a-b)<1e-12)
close(root_mean_squared_error(c(0,1,2),c(0,2,4)),sqrt(5/3))
close(root_mean_squared_error(c(0,1,2),c(0,1,2)),0)
close(root_mean_squared_error(-1000000,1000000),2000000)
close(root_mean_squared_error(0,1),1)
close(root_mean_squared_error(0,0),0)
err(root_mean_squared_error(numeric(),numeric()))
err(root_mean_squared_error(c(0,1),0))
err(root_mean_squared_error(0,NaN))
err(root_mean_squared_error(Inf,0))
err(root_mean_squared_error(0,1000001))
err(root_mean_squared_error(-1000001,0))
err(root_mean_squared_error(TRUE,0))
err(root_mean_squared_error(matrix(1,nrow=1),0))
err(root_mean_squared_error(0,"1"))
cat("R RMSE tests passed\n")
