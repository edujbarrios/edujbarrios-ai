args <- grep("^--file=", commandArgs(FALSE), value = TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "precision_at_k.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr); FALSE}, error = function(e) TRUE))
stopifnot(abs(precision_at_k(c(1, 0, 1, 1), 3) - 2/3) < 1e-12)
stopifnot(identical(precision_at_k(c(1, 0, 1, 1), 4), 0.75))
stopifnot(identical(precision_at_k(c(0, 0), 2), 0.0))
expect_error(precision_at_k(numeric(), 1))
expect_error(precision_at_k(c(1, 0, 2), 2))
expect_error(precision_at_k(c(1), 0))
expect_error(precision_at_k(c(1), 2))
cat("R precision_at_k tests passed\n")
