args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"f1_score.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
stopifnot(abs(f1_score(c(0,0,1,1,1),c(0,1,1,0,1))-2/3)<1e-12)
stopifnot(identical(f1_score(c(0,0),c(0,0)),0.0))
stopifnot(identical(f1_score(c(1,1),c(1,1)),1.0))
stopifnot(identical(f1_score(c(1,0),c(0,1)),0.0))
expect_error(f1_score(numeric(),numeric()))
expect_error(f1_score(c(1),numeric()))
expect_error(f1_score(c(0,2),c(0,1)))
expect_error(f1_score(c(0,1),c(0,NaN)))
cat("R F1 score tests passed\n")
