args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "recall_at_k.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr); FALSE}, error=function(e) TRUE))
stopifnot(abs(recall_at_k(c(1,0,1,0),3,3)-2/3)<1e-12)
stopifnot(abs(recall_at_k(c(1,0,1,0),1,3)-1/3)<1e-12)
stopifnot(identical(recall_at_k(c(0,0),2,5),0.0))
expect_error(recall_at_k(numeric(),1,3))
expect_error(recall_at_k(c(1,0),0,3))
expect_error(recall_at_k(c(1,0),3,3))
expect_error(recall_at_k(c(1,0),1,0))
expect_error(recall_at_k(c(1,0,1),2,1))
expect_error(recall_at_k(c(1,0,2),1,3))
cat("R recall at k tests passed\n")
