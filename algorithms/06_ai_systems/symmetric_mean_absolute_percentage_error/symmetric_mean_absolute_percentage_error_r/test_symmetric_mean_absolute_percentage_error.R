file_arg <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(file_arg)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",file_arg[[1L]])))
source(file.path(folder,"symmetric_mean_absolute_percentage_error.R"))
expect_error <- function(expr) {
  failed <- tryCatch({force(expr);FALSE},error=function(e) TRUE)
  stopifnot(failed)
}
close <- function(actual,expected) stopifnot(abs(actual-expected)<1e-12)
close(symmetric_mean_absolute_percentage_error(c(0,1,-1),c(0,2,1)),8/9)
close(symmetric_mean_absolute_percentage_error(c(0,1,-1),c(0,1,-1)),0)
close(symmetric_mean_absolute_percentage_error(0,0),0)
close(symmetric_mean_absolute_percentage_error(1,0),2)
close(symmetric_mean_absolute_percentage_error(1,-1),2)
close(symmetric_mean_absolute_percentage_error(1e6,-1e6),2)
close(symmetric_mean_absolute_percentage_error(1,2),2/3)
expect_error(symmetric_mean_absolute_percentage_error(numeric(),numeric()))
expect_error(symmetric_mean_absolute_percentage_error(c(0,1),0))
expect_error(symmetric_mean_absolute_percentage_error(0,NA))
expect_error(symmetric_mean_absolute_percentage_error(Inf,0))
expect_error(symmetric_mean_absolute_percentage_error(0,1000001))
expect_error(symmetric_mean_absolute_percentage_error(-1000001,0))
expect_error(symmetric_mean_absolute_percentage_error(TRUE,0))
expect_error(symmetric_mean_absolute_percentage_error(matrix(1,nrow=1),0))
