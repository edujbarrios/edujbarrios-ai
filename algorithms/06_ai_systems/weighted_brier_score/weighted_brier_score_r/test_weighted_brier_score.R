args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if(length(args)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"weighted_brier_score.R"))
error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e) TRUE))
stopifnot(identical(weighted_brier_score(c(0,1),c(0.5,0),c(1,3)),0.8125))
stopifnot(identical(weighted_brier_score(c(0,1),c(0,1),c(1,3)),0))
stopifnot(identical(weighted_brier_score(c(0,1),c(0.5,0),c(0,1)),1))
stopifnot(identical(weighted_brier_score(0,0.5,1),0.25))
error(weighted_brier_score(numeric(),numeric(),numeric()))
error(weighted_brier_score(0,0.5,0))
error(weighted_brier_score(2,0.5,1))
error(weighted_brier_score(0,1.1,1))
error(weighted_brier_score(0,0.5,-1))
error(weighted_brier_score(0,0.5,Inf))
error(weighted_brier_score(TRUE,0.5,1))
error(weighted_brier_score(0,0.5,TRUE))
cat("R weighted Brier tests passed\n")
