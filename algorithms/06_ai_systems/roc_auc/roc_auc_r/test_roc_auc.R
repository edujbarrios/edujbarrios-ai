args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"roc_auc.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
stopifnot(abs(roc_auc(c(.1,.4,.35,.8),c(0,0,1,1))-.75)<1e-12)
stopifnot(identical(roc_auc(c(.5,.5),c(0,1)),.5))
stopifnot(identical(roc_auc(c(.9,.1),c(0,1)),0.0))
stopifnot(identical(roc_auc(c(.1,.9),c(0,1)),1.0))
stopifnot(abs(roc_auc(c(0,0,0,1),c(0,1,0,1))-.75)<1e-12)
expect_error(roc_auc(numeric(),numeric()))
expect_error(roc_auc(c(.1),c(1)))
expect_error(roc_auc(c(.1,.9),c(1,1)))
expect_error(roc_auc(c(.1,.9),c(0,0)))
expect_error(roc_auc(c(NaN,.9),c(0,1)))
expect_error(roc_auc(c(.1,.9),c(0,2)))
cat("R ROC AUC tests passed\n")
