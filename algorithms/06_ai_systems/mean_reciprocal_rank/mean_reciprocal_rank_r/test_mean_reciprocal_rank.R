args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "mean_reciprocal_rank.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr); FALSE},error=function(e) TRUE))
stopifnot(identical(mean_reciprocal_rank(c(1,2,0,4)),0.4375))
stopifnot(identical(mean_reciprocal_rank(c(0,0,0)),0.0))
stopifnot(identical(mean_reciprocal_rank(c(1)),1.0))
expect_error(mean_reciprocal_rank(numeric()))
expect_error(mean_reciprocal_rank(c(-1)))
expect_error(mean_reciprocal_rank(c(1.5)))
expect_error(mean_reciprocal_rank(c(NaN)))
cat("R mean reciprocal rank tests passed\n")
