args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
folder <- dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"macro_f1_score.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
near <- function(a,p,k,want) {
  actual <- macro_f1_score(a,p,k)
  stopifnot(length(actual)==1L,is.finite(actual),abs(actual-want)<1e-12)
}
near(c(0,1,2,2),c(0,2,1,2),3,0.5)
near(c(0,0),c(0,0),3,1/3)
near(c(0,1,2),c(0,1,2),3,1)
near(c(0,0),c(1,1),2,0)
near(c(0,1),c(0,1),2,1)
near(c(0,1,2),c(0,0,2),3,(2/3+1)/3)
near(rep(0,512),rep(0,512),2,0.5)
near(rep(0,512),rep(0,512),16,1/16)
near(15,15,16,1/16)
near(1,0,2,0)
expect_error(macro_f1_score(numeric(0),numeric(0),2))
expect_error(macro_f1_score(0,numeric(0),2))
expect_error(macro_f1_score(0,0,1))
expect_error(macro_f1_score(0,0,17))
expect_error(macro_f1_score(0,0,TRUE))
expect_error(macro_f1_score(0,0,2.5))
expect_error(macro_f1_score(2,0,2))
expect_error(macro_f1_score(0,2,2))
expect_error(macro_f1_score(-1,0,2))
expect_error(macro_f1_score(TRUE,0,2))
expect_error(macro_f1_score(0,FALSE,2))
expect_error(macro_f1_score(0.5,0,2))
expect_error(macro_f1_score(0,NA_real_,2))
expect_error(macro_f1_score(matrix(0,1,1),0,2))
expect_error(macro_f1_score(rep(0,513),rep(0,513),2))
cat("R macro F1 tests passed\n")
