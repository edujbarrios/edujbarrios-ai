expect_error <- function(expr) stopifnot(inherits(tryCatch(expr, error=identity), "error"))
stopifnot(abs(mean_absolute_error(c(2,-1,5),c(1,1,3)) - 5/3) < 1e-12)
stopifnot(identical(mean_absolute_error(c(2,-1),c(2,-1)), 0.0))
stopifnot(identical(mean_absolute_error(2,0), 2.0))
stopifnot(identical(mean_absolute_error(c(1e308,1e308),c(0,0)), 1e308))
expect_error(mean_absolute_error(numeric(0),numeric(0)))
expect_error(mean_absolute_error(1,numeric(0)))
expect_error(mean_absolute_error(NaN,0))
expect_error(mean_absolute_error(Inf,0))
expect_error(mean_absolute_error(1e308,-1e308))
cat("R mean_absolute_error tests passed\n")
