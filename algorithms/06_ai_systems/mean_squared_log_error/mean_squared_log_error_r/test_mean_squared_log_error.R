err <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e) TRUE))
close <- function(a,b) stopifnot(abs(a-b)<1e-11)
close(mean_squared_log_error(c(0,1,9),c(0,3,9)),log(2)^2/3)
close(mean_squared_log_error(c(0,1,9),c(0,1,9)),0)
