args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"matthews_correlation_coefficient.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
y<-c(1,1,0,0)
stopifnot(identical(matthews_correlation_coefficient(y,y),1.0))
stopifnot(identical(matthews_correlation_coefficient(y,c(0,0,1,1)),-1.0))
stopifnot(identical(matthews_correlation_coefficient(y,c(1,0,1,0)),0.0))
stopifnot(identical(matthews_correlation_coefficient(y,c(0,0,0,0)),0.0))
stopifnot(abs(matthews_correlation_coefficient(c(1,1,1,0,0),c(1,1,0,1,0))-
              1/6)<1e-12)
expect_error(matthews_correlation_coefficient(numeric(),numeric()))
expect_error(matthews_correlation_coefficient(c(0),numeric()))
expect_error(matthews_correlation_coefficient(c(0,2),c(0,1)))
expect_error(matthews_correlation_coefficient(c(0,1),c(0,3)))
cat("R MCC tests passed\n")
