args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"cohens_kappa.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
stopifnot(abs(cohens_kappa(c(0,0,1,1),c(0,0,0,1))-.5)<1e-12)
stopifnot(identical(cohens_kappa(c(0,1),c(1,0)),-1.0))
stopifnot(identical(cohens_kappa(c(0,1),c(0,1)),1.0))
stopifnot(identical(cohens_kappa(c(0,0,1,1),c(0,1,0,1)),0.0))
stopifnot(identical(cohens_kappa(c(0,0),c(1,1)),0.0))
expect_error(cohens_kappa(numeric(),numeric()))
expect_error(cohens_kappa(c(0),numeric()))
expect_error(cohens_kappa(c(0,0),c(0,0)))
expect_error(cohens_kappa(c(1,1),c(1,1)))
expect_error(cohens_kappa(c(0,2),c(0,1)))
expect_error(cohens_kappa(c(0,1),c(0,.5)))
cat("R Cohen kappa tests passed\n")
