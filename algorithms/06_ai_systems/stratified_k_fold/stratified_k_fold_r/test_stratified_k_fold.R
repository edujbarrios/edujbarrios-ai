args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"stratified_k_fold.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
stopifnot(identical(stratified_k_fold(c(0,1,0,1,0,1),3),c(0L,0L,1L,1L,2L,2L)))
stopifnot(identical(stratified_k_fold(c(0,0,0,0,1,1,1,1),3),c(0L,1L,2L,0L,1L,2L,0L,1L)))
labels<-c(rep(0,7),rep(1,5))
folds<-stratified_k_fold(labels,4)
sizes<-tabulate(folds+1L,nbins=4L)
stopifnot(max(sizes)-min(sizes)<=1)
for (f in 0:3) {
  stopifnot(sum(labels==0 & folds==f)>=1)
  stopifnot(sum(labels==1 & folds==f)>=1)
}
expect_error(stratified_k_fold(numeric(),2))
expect_error(stratified_k_fold(c(0,1),1))
expect_error(stratified_k_fold(c(0,1),2))
expect_error(stratified_k_fold(c(0,0,1,1),3))
expect_error(stratified_k_fold(c(0,0,1,2),2))
cat("R stratified K-fold tests passed\n")
