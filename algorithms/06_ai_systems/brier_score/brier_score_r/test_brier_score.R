args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"brier_score.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
stopifnot(abs(brier_score(c(.1,.8,.6,.2),c(0,1,1,0))-.0625)<1e-12)
stopifnot(identical(brier_score(c(0,1),c(0,1)),0.0))
stopifnot(identical(brier_score(c(1,0),c(0,1)),1.0))
stopifnot(identical(brier_score(c(.5,.5),c(0,1)),.25))
stopifnot(identical(brier_score(c(.5),c(0)),.25))
expect_error(brier_score(numeric(),numeric()))
expect_error(brier_score(c(.2),numeric()))
expect_error(brier_score(c(-.1,.5),c(0,1)))
expect_error(brier_score(c(1.1,.5),c(0,1)))
expect_error(brier_score(c(NaN,.5),c(0,1)))
expect_error(brier_score(c(0,1),c(0,2)))
cat("R Brier score tests passed\n")
