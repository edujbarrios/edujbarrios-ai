expect_error <- function(expr) stopifnot(inherits(tryCatch(expr, error=identity), "error"))
stopifnot(abs(balanced_accuracy(c(0,0,0,1,1),c(0,0,1,1,0)) - 7/12) < 1e-12)
stopifnot(identical(balanced_accuracy(c(0,1),c(0,1)),1.0))
stopifnot(identical(balanced_accuracy(c(0,1),c(1,0)),0.0))
stopifnot(identical(balanced_accuracy(c(0,0,1),c(0,0,0)),0.5))
expect_error(balanced_accuracy(numeric(0),numeric(0)))
expect_error(balanced_accuracy(0,numeric(0)))
expect_error(balanced_accuracy(c(0,0),c(0,0)))
expect_error(balanced_accuracy(c(1,1),c(1,1)))
expect_error(balanced_accuracy(c(0,1),c(0,2)))
expect_error(balanced_accuracy(c(0,1),c(NA,1)))
cat("R balanced_accuracy tests passed\n")
