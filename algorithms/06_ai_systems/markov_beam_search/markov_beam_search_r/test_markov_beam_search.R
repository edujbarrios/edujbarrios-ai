args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"markov_beam_search.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
p<-c(.6,.4)
a<-matrix(c(.9,.1,.2,.8),nrow=2,byrow=TRUE)
m<-markov_beam_search(p,a,3,2)
stopifnot(identical(m$tokens,c(0L,0L,0L)))
stopifnot(abs(m$log_probability-log(.486))<1e-12)
u<-matrix(.5,nrow=2,ncol=2)
stopifnot(identical(markov_beam_search(c(.5,.5),u,3,2)$tokens,c(0L,0L,0L)))
stopifnot(identical(markov_beam_search(p,a,3,1)$tokens,c(0L,0L,0L)))
stopifnot(identical(markov_beam_search(c(1),matrix(1,nrow=1),3,8)$tokens,c(0L,0L,0L)))
expect_error(markov_beam_search(numeric(),matrix(numeric(),0,0),1,1))
expect_error(markov_beam_search(c(0,1),a,2,2))
expect_error(markov_beam_search(p,matrix(c(.8,.8,.2,.8),2,byrow=TRUE),2,2))
expect_error(markov_beam_search(p,matrix(c(.9,NaN,.2,.8),2,byrow=TRUE),2,2))
expect_error(markov_beam_search(p,a,0,2))
expect_error(markov_beam_search(p,a,2,0))
cat("R Markov beam search tests passed\n")
