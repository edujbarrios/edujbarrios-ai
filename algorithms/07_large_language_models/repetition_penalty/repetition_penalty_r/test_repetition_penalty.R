file_arg <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(file_arg)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",file_arg[[1L]])))
source(file.path(folder,"repetition_penalty.R"))
expect_error <- function(expr) {
  failed <- tryCatch({force(expr);FALSE},error=function(e) TRUE)
  stopifnot(failed)
}
x <- c(2,-2,0,1)
stopifnot(identical(repetition_penalty(x,c(0,1,1,2),2),c(1,-4,0,1)))
stopifnot(identical(repetition_penalty(x,c(0,1,1,2),1),x))
stopifnot(identical(repetition_penalty(x,numeric(),10),x))
stopifnot(isTRUE(all.equal(repetition_penalty(c(1),c(0),10),c(.1))))
expect_error(repetition_penalty(x,c(4),2))
expect_error(repetition_penalty(x,c(-1),2))
expect_error(repetition_penalty(x,c(0.1),2))
expect_error(repetition_penalty(x,c(0,NA),2))
expect_error(repetition_penalty(x,rep(0,16385),2))
expect_error(repetition_penalty(x,numeric(),0.5))
expect_error(repetition_penalty(x,numeric(),11))
expect_error(repetition_penalty(x,numeric(),NaN))
expect_error(repetition_penalty(numeric(),numeric(),2))
expect_error(repetition_penalty(c(1001),numeric(),2))
cat("R repetition penalty tests passed\n")
