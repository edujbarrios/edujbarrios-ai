args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"z_score_standardization.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
x<-matrix(c(1,10,2,10,3,10),nrow=3,byrow=TRUE)
v<-z_score_standardization(x)
stopifnot(identical(v$means,c(2,10)))
stopifnot(abs(v$stds[[1]]-sqrt(2/3))<1e-12,v$stds[[2]]==0)
stopifnot(abs(v$standardized[1,1]+sqrt(1.5))<1e-12)
stopifnot(all(v$standardized[,2]==0))
stopifnot(v$standardized[2,1]==0)
v<-z_score_standardization(matrix(c(5,2),nrow=1))
stopifnot(identical(v$means,c(5,2)))
stopifnot(identical(v$stds,c(0,0)))
stopifnot(identical(unname(v$standardized),matrix(c(0,0),nrow=1)))
expect_error(z_score_standardization(matrix(numeric(),nrow=0,ncol=2)))
expect_error(z_score_standardization(matrix(c(1,NaN),nrow=1)))
expect_error(z_score_standardization(matrix(c(-1e308,1e308),ncol=1)))
cat("R z-score standardization tests passed\n")
