file_arg <- grep("^--file=", commandArgs(FALSE), value=TRUE)
if (length(file_arg)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=", "", file_arg[[1L]])))
source(file.path(folder, "spearman_rank_correlation.R"))
expect_error <- function(expr) {
  failed <- tryCatch({force(expr);FALSE}, error=function(e) TRUE)
  stopifnot(failed)
}
close <- function(actual,expected) stopifnot(abs(actual-expected)<1e-12)
close(spearman_rank_correlation(c(1,2,3),c(4,5,6)),1)
close(spearman_rank_correlation(c(1,2,3),c(6,5,4)),-1)
close(spearman_rank_correlation(c(1,2,3),c(1,3,2)),0.5)
close(spearman_rank_correlation(c(1,1,2,3),c(1,2,2,3)),5/6)
close(spearman_rank_correlation(c(1,2),c(2,1)),-1)
expect_error(spearman_rank_correlation(numeric(),numeric()))
expect_error(spearman_rank_correlation(c(1),c(1)))
expect_error(spearman_rank_correlation(c(1,2),c(1)))
expect_error(spearman_rank_correlation(c(1,2,3),c(7,7,7)))
expect_error(spearman_rank_correlation(c(1,2),c(1,NA)))
expect_error(spearman_rank_correlation(c(1,2),c(1,Inf)))
expect_error(spearman_rank_correlation(c(1,2),c(1,1000001)))
expect_error(spearman_rank_correlation(c(1,2),c("1","2")))
cat("R Spearman rank correlation tests passed\n")
