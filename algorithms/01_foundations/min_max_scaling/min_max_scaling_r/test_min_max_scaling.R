args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
folder <- dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"min_max_scaling.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e) TRUE))
stopifnot(identical(min_max_scaling(c(-5,0,5)),c(0,0.5,1)))
stopifnot(identical(min_max_scaling(c(10,20,30)),c(0,0.5,1)))
stopifnot(identical(min_max_scaling(c(2,1)),c(1,0)))
expect_error(min_max_scaling(numeric()))
expect_error(min_max_scaling(c(1)))
expect_error(min_max_scaling(c(7,7,7)))
expect_error(min_max_scaling(c(NaN,1)))
expect_error(min_max_scaling(c(-1e308,1e308)))
cat("R min-max scaling tests passed\n")
