args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"gaussian_rbf_kernel.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
k<-gaussian_rbf_kernel(matrix(c(0,1,2),ncol=1),1)
stopifnot(identical(as.double(diag(k)),c(1,1,1)))
stopifnot(abs(k[1,2]-exp(-.5))<1e-12,abs(k[1,3]-exp(-2))<1e-12)
stopifnot(identical(k[1,2],k[2,1]))
stopifnot(identical(gaussian_rbf_kernel(matrix(c(2,2),ncol=1),1),
                    matrix(1.0,nrow=2,ncol=2)))
stopifnot(identical(gaussian_rbf_kernel(matrix(0,nrow=1),1),matrix(1.0,nrow=1)))
stopifnot(abs(gaussian_rbf_kernel(matrix(c(0,1),ncol=1),2)[1,2]-exp(-.125))<1e-12)
expect_error(gaussian_rbf_kernel(matrix(numeric(),nrow=0,ncol=1),1))
expect_error(gaussian_rbf_kernel(matrix(c(0,1),ncol=1),0))
expect_error(gaussian_rbf_kernel(matrix(c(0,1),ncol=1),1e-7))
expect_error(gaussian_rbf_kernel(matrix(c(0,NaN),ncol=1),1))
expect_error(gaussian_rbf_kernel(matrix(c(0,1000001),ncol=1),1))
cat("R Gaussian RBF tests passed\n")
