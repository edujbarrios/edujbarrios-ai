args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "median_absolute_deviation.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr); FALSE}, error=function(e) TRUE))
stopifnot(identical(median_absolute_deviation(c(1,1,2,2,4,6,9)), 1.0))
stopifnot(identical(median_absolute_deviation(c(1,2,3,10)), 1.0))
stopifnot(identical(median_absolute_deviation(c(10,3,2,1)), 1.0))
stopifnot(identical(median_absolute_deviation(c(5,5,5)), 0.0))
stopifnot(identical(median_absolute_deviation(42), 0.0))
stopifnot(identical(median_absolute_deviation(c(-3,-1,2)), 2.0))
stopifnot(identical(median_absolute_deviation(rep(7, 512)), 0.0))
stopifnot(identical(median_absolute_deviation(c(-1e308, 1e308)), 1e308))
expect_error(median_absolute_deviation(numeric(0)))
expect_error(median_absolute_deviation(rep(1, 513)))
expect_error(median_absolute_deviation(c(1, Inf)))
expect_error(median_absolute_deviation(NaN))
expect_error(median_absolute_deviation(c(-1e308,-1e308,1e308)))
expect_error(median_absolute_deviation(c(TRUE, FALSE)))
expect_error(median_absolute_deviation("3"))
expect_error(median_absolute_deviation(matrix(1:4, 2, 2)))
cat("R MAD tests passed\n")
