args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"kullback_leibler_divergence.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
stopifnot(identical(kullback_leibler_divergence(c(.5,.5),c(.5,.5)),0.0))
stopifnot(abs(kullback_leibler_divergence(c(1,0),c(.5,.5))-1)<1e-12)
stopifnot(abs(kullback_leibler_divergence(c(.75,.25),c(.5,.5))-.1887218755408672)<1e-12)
stopifnot(identical(kullback_leibler_divergence(c(1,0),c(0,1)),Inf))
stopifnot(identical(kullback_leibler_divergence(c(1),c(1)),0.0))
stopifnot(abs(kullback_leibler_divergence(c(.75,.25),c(.5,.5))-
              kullback_leibler_divergence(c(.5,.5),c(.75,.25)))>1e-5)
expect_error(kullback_leibler_divergence(numeric(),numeric()))
expect_error(kullback_leibler_divergence(c(.5,.5),c(.2,.2)))
expect_error(kullback_leibler_divergence(c(1,0),c(1)))
expect_error(kullback_leibler_divergence(c(1.1,-.1),c(.5,.5)))
expect_error(kullback_leibler_divergence(c(.5,.5),c(NaN,1)))
cat("R KL divergence tests passed\n")
