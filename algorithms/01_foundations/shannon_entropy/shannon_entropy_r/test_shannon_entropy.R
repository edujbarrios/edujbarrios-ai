args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"shannon_entropy.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
stopifnot(identical(shannon_entropy(c(1,0)),0.0))
stopifnot(abs(shannon_entropy(c(.5,.5))-1)<1e-12)
stopifnot(abs(shannon_entropy(rep(.25,4))-2)<1e-12)
stopifnot(abs(shannon_entropy(c(.75,.25))-.8112781244591328)<1e-12)
stopifnot(identical(shannon_entropy(c(1)),0.0))
expect_error(shannon_entropy(numeric()))
expect_error(shannon_entropy(c(.2,.2)))
expect_error(shannon_entropy(c(1.1,-.1)))
expect_error(shannon_entropy(c(NaN,1)))
expect_error(shannon_entropy(c(Inf,0)))
cat("R Shannon entropy tests passed\n")
