args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"logsumexp.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
x<-logsumexp(c(0,0))
stopifnot(abs(x$value-log(2))<1e-12)
stopifnot(identical(x$gradient,c(.5,.5)))
x<-logsumexp(c(log(2),log(3)))
stopifnot(abs(x$value-log(5))<1e-12)
stopifnot(abs(x$gradient[[1]]-.4)<1e-12,abs(x$gradient[[2]]-.6)<1e-12)
x<-logsumexp(c(-1000,-1000))
stopifnot(abs(x$value-(-1000+log(2)))<1e-12)
stopifnot(identical(x$gradient,c(.5,.5)))
x<-logsumexp(c(5))
stopifnot(identical(x$value,5.0),identical(x$gradient,c(1.0)))
expect_error(logsumexp(numeric()))
expect_error(logsumexp(c(NaN,0)))
expect_error(logsumexp(c(Inf)))
expect_error(logsumexp(c(-1e308,1e308)))
cat("R log-sum-exp tests passed\n")
