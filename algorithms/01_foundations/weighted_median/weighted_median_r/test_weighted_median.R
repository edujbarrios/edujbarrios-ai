args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "weighted_median.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr);FALSE}, error=function(e)TRUE))
stopifnot(identical(weighted_median(c(1,2,10),c(1,1,8)),10.0))
stopifnot(identical(weighted_median(c(1,2,3,4),c(1,1,1,1)),2.0))
stopifnot(identical(weighted_median(c(10,1,3),c(0,2,1)),1.0))
stopifnot(identical(weighted_median(c(5,5,9),c(1,1,1)),5.0))
stopifnot(identical(weighted_median(c(1,100),c(0,2)),100.0))
stopifnot(identical(weighted_median(c(-5,2),c(1,1)),-5.0))
stopifnot(identical(weighted_median(42,0.01),42.0))
stopifnot(identical(weighted_median(rep(3,512),rep(1,512)),3.0))
stopifnot(identical(weighted_median(c(-1e308,1e308),c(1,1)),-1e308))
expect_error(weighted_median(numeric(0),numeric(0)))
expect_error(weighted_median(1,numeric(0)))
expect_error(weighted_median(1,0))
expect_error(weighted_median(c(1,2),c(0,0)))
expect_error(weighted_median(c(1,2),c(-1,2)))
expect_error(weighted_median(1,Inf))
expect_error(weighted_median(NA_real_,1))
expect_error(weighted_median(c(1,2),c(1e308,1e308)))
expect_error(weighted_median(rep(1,513),rep(1,513)))
expect_error(weighted_median(TRUE,1))
expect_error(weighted_median(1,"1"))
expect_error(weighted_median(matrix(1:4,2,2),rep(1,4)))
cat("R weighted median tests passed\n")
