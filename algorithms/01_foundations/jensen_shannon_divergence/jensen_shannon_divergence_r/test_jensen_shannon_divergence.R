args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"jensen_shannon_divergence.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
stopifnot(abs(jensen_shannon_divergence(c(1,0),c(0,1))-1)<1e-12)
stopifnot(abs(jensen_shannon_divergence(c(.5,.5),c(.5,.5)))<1e-12)
stopifnot(abs(jensen_shannon_divergence(c(1,0),c(.5,.5))-.31127812445913283)<1e-12)
stopifnot(identical(jensen_shannon_divergence(c(1),c(1)),0.0))
expect_error(jensen_shannon_divergence(numeric(),numeric()))
expect_error(jensen_shannon_divergence(c(1),c(.5)))
expect_error(jensen_shannon_divergence(c(1,0),c(1)))
expect_error(jensen_shannon_divergence(c(1,0),c(-.1,1.1)))
expect_error(jensen_shannon_divergence(c(1,0),c(NaN,1)))
expect_error(jensen_shannon_divergence(c(1,0),c(.2,.2)))
cat("R Jensen-Shannon divergence tests passed\n")
