expect_error <- function(expr) stopifnot(inherits(tryCatch(expr, error=identity), "error"))
stopifnot(identical(manhattan_distance(c(1,2,-1),c(4,-2,1)),9.0))
stopifnot(identical(manhattan_distance(numeric(0),numeric(0)),0.0))
stopifnot(identical(manhattan_distance(c(1,2),c(1,2)),0.0))
stopifnot(identical(manhattan_distance(c(-2,3),c(4,-1)),10.0))
expect_error(manhattan_distance(1,numeric(0)))
expect_error(manhattan_distance(NaN,0))
expect_error(manhattan_distance(Inf,0))
expect_error(manhattan_distance(1e308,-1e308))
expect_error(manhattan_distance(c(1e308,1e308),c(0,0)))
cat("R manhattan_distance tests passed\n")
