args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
folder <- dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"interquartile_range.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
near <- function(values,want) {
  result <- interquartile_range(values)
  stopifnot(abs(result-want)<=1e-11*max(abs(want),1))
}
near(c(1,2,3,4),1.5)
near(c(1,2,3,4,100),2)
near(c(1,5),2)
near(c(1,2,3),1)
near(42,0)
near(rep(7,512),0)
near(c(100,4,3,2,1),2)
near(c(-5,-3,-1,1,3),4)
near(c(1,1,1,50,50,50),49)
near(c(-1e308,1e308),1e308)
expect_error(interquartile_range(numeric(0)))
expect_error(interquartile_range(rep(1,513)))
expect_error(interquartile_range(NaN))
expect_error(interquartile_range(Inf))
expect_error(interquartile_range(TRUE))
expect_error(interquartile_range("1"))
expect_error(interquartile_range(matrix(1:4,2,2)))
expect_error(interquartile_range(c(-1e308,-1e308,1e308,1e308)))
cat("R interquartile range tests passed\n")
