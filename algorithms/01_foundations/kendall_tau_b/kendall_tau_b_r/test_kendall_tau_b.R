file_arg <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(file_arg)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",file_arg[[1L]])))
source(file.path(folder,"kendall_tau_b.R"))
expect_error <- function(expr) {
  failed <- tryCatch({force(expr);FALSE},error=function(e) TRUE)
  stopifnot(failed)
}
close <- function(actual,expected) stopifnot(abs(actual-expected)<1e-12)
close(kendall_tau_b(c(1,2,3),c(2,3,4)),1)
close(kendall_tau_b(c(1,2,3),c(4,3,2)),-1)
close(kendall_tau_b(c(1,2,3),c(1,3,2)),1/3)
close(kendall_tau_b(c(1,1,2,3),c(1,2,2,3)),0.8)
close(kendall_tau_b(c(1,2),c(1,2)),1)
expect_error(kendall_tau_b(numeric(),numeric()))
expect_error(kendall_tau_b(c(1),c(2)))
expect_error(kendall_tau_b(c(1,2),c(1)))
expect_error(kendall_tau_b(c(1,2,3),c(7,7,7)))
expect_error(kendall_tau_b(c(1,2),c(1,NA)))
expect_error(kendall_tau_b(c(1,2),c(1,Inf)))
expect_error(kendall_tau_b(c(1,2),c(1,1000001)))
expect_error(kendall_tau_b(c(1,2),c("1","2")))
cat("R Kendall tau-b tests passed\n")
