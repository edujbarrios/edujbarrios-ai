args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "geometric_mean.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
near <- function(v,expected) {
  stopifnot(abs(geometric_mean(v)-expected)<=1e-11*max(1,abs(expected)))
}
near(c(2,8),4)
near(c(1,1,1),1)
near(c(0,2,8),0)
near(c(1e-300,1e300),1)
near(c(2,4,8),4)
near(c(0.5,2),1)
near(42,42)
near(rep(7,512),7)
near(c(0,1e308),0)
expect_error(geometric_mean(numeric(0)))
expect_error(geometric_mean(rep(1,513)))
expect_error(geometric_mean(-1))
expect_error(geometric_mean(c(1,-0.01)))
expect_error(geometric_mean(NaN))
expect_error(geometric_mean(Inf))
expect_error(geometric_mean(TRUE))
expect_error(geometric_mean("2"))
expect_error(geometric_mean(matrix(1:4,2,2)))
cat("R geometric mean tests passed\n")
