args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "trimmed_mean.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
check <- function(v,f,expect) stopifnot(abs(trimmed_mean(v,f)-expect) < 1e-12*max(1,abs(expect)))
check(c(1,2,3,4,100),0.2,3)
check(c(1,2,3,100),0.25,2.5)
check(c(1,2,3,100),0,26.5)
check(c(100,3,2,1),0.25,2.5)
check(42,0.49,42)
check(c(1,2,3),0.49,2)
check(rep(7,512),0.49,7)
check(c(-1e308,1e308),0,0)
check(c(0,2,100),0.3,34)
expect_error(trimmed_mean(numeric(0),0))
expect_error(trimmed_mean(rep(1,513),0))
expect_error(trimmed_mean(1,-0.01))
expect_error(trimmed_mean(1,0.5))
expect_error(trimmed_mean(1,Inf))
expect_error(trimmed_mean(1,NaN))
expect_error(trimmed_mean(1,NA_real_))
expect_error(trimmed_mean(1,TRUE))
expect_error(trimmed_mean(TRUE,0))
expect_error(trimmed_mean(c(1,NaN),0))
expect_error(trimmed_mean("1",0))
expect_error(trimmed_mean(matrix(1:4,2,2),0))
cat("R trimmed mean tests passed\n")
