args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
folder <- dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"harmonic_mean.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
near <- function(x,expected) {
  actual <- harmonic_mean(x)
  stopifnot(abs(actual-expected) <= 1e-11*max(abs(expected),1e-320))
}
near(c(2,6),3)
near(c(1,2,4),12/7)
near(c(0,2,6),0)
near(42,42)
near(rep(7,512),7)
near(c(1e-300,1e300),2e-300)
near(c(1e-320,1e-320),1e-320)
near(c(1e308,1e308),1e308)
expect_error(harmonic_mean(numeric(0)))
expect_error(harmonic_mean(rep(1,513)))
expect_error(harmonic_mean(-1))
expect_error(harmonic_mean(c(0,NaN)))
expect_error(harmonic_mean(Inf))
expect_error(harmonic_mean(TRUE))
expect_error(harmonic_mean("2"))
expect_error(harmonic_mean(matrix(1:4,2,2)))
cat("R harmonic mean tests passed\n")
