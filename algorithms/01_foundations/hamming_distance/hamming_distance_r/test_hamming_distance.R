args <- grep("^--file=", commandArgs(FALSE), value = TRUE)
if (length(args) == 0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "hamming_distance.R"))
errors <- function(expr) stopifnot(tryCatch({force(expr); FALSE}, error = function(e) TRUE))

stopifnot(hamming_distance(as.raw(c(1, 0, 1, 1)), as.raw(c(1, 1, 0, 1))) == 2)
stopifnot(hamming_distance(charToRaw("abc"), charToRaw("abc")) == 0)
stopifnot(hamming_distance(raw(), raw()) == 0)
stopifnot(hamming_distance(as.raw(0), as.raw(255)) == 1)
errors(hamming_distance(as.raw(1), raw()))
errors(hamming_distance(c(1, 2), c(1, 2)))
errors(hamming_distance("ab", "ab"))
cat("R Hamming distance tests passed\n")
