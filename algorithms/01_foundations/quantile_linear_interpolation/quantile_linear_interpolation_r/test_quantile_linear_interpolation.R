args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
folder <- dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"quantile_linear_interpolation.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
near <- function(v,p,want) {
  got <- quantile_linear_interpolation(v,p)
  stopifnot(abs(got-want)<=1e-11*max(abs(want),1))
}
near(c(1,2,3,4),0.25,1.75)
near(c(1,2,3,4),0.5,2.5)
near(c(1,2,3,4),0.75,3.25)
near(c(5,10),0.2,6)
near(42,0.9,42)
near(c(100,2,-5),0,-5)
near(c(100,2,-5),1,100)
near(c(-1e308,1e308),0.5,0)
near(c(-1e308,1e308),0,-1e308)
near(c(-1e308,1e308),1,1e308)
near(rep(7,512),0.37,7)
expect_error(quantile_linear_interpolation(numeric(0),0.5))
expect_error(quantile_linear_interpolation(rep(1,513),0.5))
expect_error(quantile_linear_interpolation(Inf,0.5))
expect_error(quantile_linear_interpolation(NaN,0.5))
expect_error(quantile_linear_interpolation(TRUE,0.5))
expect_error(quantile_linear_interpolation(1,TRUE))
expect_error(quantile_linear_interpolation(1,-0.01))
expect_error(quantile_linear_interpolation(1,1.01))
expect_error(quantile_linear_interpolation(1,NA_real_))
expect_error(quantile_linear_interpolation(1,Inf))
expect_error(quantile_linear_interpolation(matrix(1:4,2,2),0.5))
cat("R quantile interpolation tests passed\n")
