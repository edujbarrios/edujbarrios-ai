args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "root_mean_square.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
near <- function(x,want) {
  got <- root_mean_square(x)
  stopifnot(abs(got-want) <= 1e-11*max(abs(want),1e-300))
}
near(c(3,4),sqrt(12.5))
near(c(-3,4),sqrt(12.5))
near(c(0,0,0),0)
near(-42,42)
near(c(1e308,-1e308),1e308)
near(c(1e-300,-1e-300),1e-300)
near(rep(3,512),3)
near(c(1,2,2),sqrt(3))
expect_error(root_mean_square(numeric(0)))
expect_error(root_mean_square(rep(1,513)))
expect_error(root_mean_square(NaN))
expect_error(root_mean_square(Inf))
expect_error(root_mean_square(-Inf))
expect_error(root_mean_square(TRUE))
expect_error(root_mean_square("1"))
expect_error(root_mean_square(matrix(1:4,2,2)))
cat("R RMS tests passed\n")
