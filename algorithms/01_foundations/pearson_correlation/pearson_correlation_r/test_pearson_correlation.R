file_arg <- grep("^--file=", commandArgs(FALSE), value = TRUE)
if (length(file_arg) == 0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=", "", file_arg[[1L]])))
source(file.path(folder, "pearson_correlation.R"))
expect_error <- function(expr) {
  failed <- tryCatch({ force(expr); FALSE }, error = function(e) TRUE)
  stopifnot(failed)
}
close <- function(actual, expected) stopifnot(abs(actual - expected) < 1e-12)
close(pearson_correlation(c(1,2,3), c(2,4,6)), 1)
close(pearson_correlation(c(1,2,3), c(6,4,2)), -1)
close(pearson_correlation(c(1,2,3), c(1,0,1)), 0)
close(pearson_correlation(c(1,2), c(3,4)), 1)
expect_error(pearson_correlation(numeric(), numeric()))
expect_error(pearson_correlation(c(1), c(2)))
expect_error(pearson_correlation(c(1,2), c(1)))
expect_error(pearson_correlation(c(1,2), c(4,4)))
expect_error(pearson_correlation(c(1,2), c(1,NA)))
expect_error(pearson_correlation(c(1,2), c(1,Inf)))
expect_error(pearson_correlation(c(1,2), c(1,1000001)))
expect_error(pearson_correlation(c(1,2), c("1","2")))
cat("R Pearson correlation tests passed\n")
