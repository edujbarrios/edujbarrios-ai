args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
if (length(args)==0L) stop("run using Rscript")
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "matrix_multiplication.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr); FALSE}, error=function(e) TRUE))

a <- matrix(c(1,2,3,4,5,6), nrow=2, byrow=TRUE)
b <- matrix(c(7,8,9,10,11,12), nrow=3, byrow=TRUE)
expected <- matrix(c(58,64,139,154), nrow=2, byrow=TRUE)
stopifnot(identical(unname(matrix_multiplication(a,b)), expected))
stopifnot(identical(matrix_multiplication(matrix(-3,1,1),matrix(2,1,1))[1,1], -6.0))
expect_error(matrix_multiplication(matrix(numeric(),0,0), matrix(1,1,1)))
expect_error(matrix_multiplication(matrix(1:2,1,2), matrix(1,1,1)))
expect_error(matrix_multiplication(matrix(NaN,1,1),matrix(1,1,1)))
expect_error(matrix_multiplication(matrix(1e308,1,1),matrix(1e308,1,1)))
cat("R matrix multiplication tests passed\n")
