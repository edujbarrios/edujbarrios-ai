source("algorithms/01_foundations/chebyshev_distance/chebyshev_distance_r/chebyshev_distance.R")
expect_error <- function(expr) stopifnot(inherits(tryCatch(expr, error = identity), "error"))
stopifnot(identical(chebyshev_distance(c(1,2,-1), c(4,-2,1)), 4.0))
stopifnot(identical(chebyshev_distance(c(4,-2,1), c(1,2,-1)), 4.0))
stopifnot(identical(chebyshev_distance(c(1,2), c(1,2)), 0.0))
stopifnot(identical(chebyshev_distance(numeric(0), numeric(0)), 0.0))
stopifnot(identical(chebyshev_distance(1e308, 0), 1e308))
expect_error(chebyshev_distance(1, numeric(0)))
expect_error(chebyshev_distance(NaN, 0))
expect_error(chebyshev_distance(Inf, 0))
expect_error(chebyshev_distance(1e308, -1e308))
cat("R chebyshev_distance tests passed\n")
