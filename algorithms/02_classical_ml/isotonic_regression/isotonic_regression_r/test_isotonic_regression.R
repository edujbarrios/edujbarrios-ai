args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "isotonic_regression.R"))
error <- function(expr) stopifnot(tryCatch({force(expr); FALSE}, error=function(e) TRUE))
stopifnot(identical(isotonic_regression(c(3, 1, 2, 4)), c(2, 2, 2, 4)))
stopifnot(identical(isotonic_regression(c(-2, 2, 0, 4)), c(-2, 1, 1, 4)))
stopifnot(identical(isotonic_regression(c(1, 2, 2, 3)), c(1, 2, 2, 3)))
stopifnot(identical(isotonic_regression(c(3, 2, 1)), c(2, 2, 2)))
stopifnot(identical(isotonic_regression(1), 1))
stopifnot(identical(isotonic_regression(c(1000000, -1000000)), c(0, 0)))
stopifnot(isTRUE(all.equal(isotonic_regression(512:1), rep(256.5, 512))))
error(isotonic_regression(numeric()))
error(isotonic_regression(rep(1, 513)))
error(isotonic_regression(TRUE))
error(isotonic_regression(NaN))
error(isotonic_regression(Inf))
error(isotonic_regression(1000001))
error(isotonic_regression(matrix(c(1, 2), nrow=1)))
cat("R isotonic regression tests passed\n")
