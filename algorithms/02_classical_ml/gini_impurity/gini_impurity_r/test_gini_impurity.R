file_arg <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(file_arg)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",file_arg[[1L]])))
source(file.path(folder,"gini_impurity.R"))
expect_error <- function(expr) {
  failed <- tryCatch({force(expr);FALSE},error=function(e) TRUE)
  stopifnot(failed)
}
close <- function(actual,expected) stopifnot(abs(actual-expected)<1e-12)
close(gini_impurity(c(5,0)),0)
close(gini_impurity(c(1,1)),0.5)
close(gini_impurity(c(3,1)),0.375)
close(gini_impurity(c(1,1,1)),2/3)
close(gini_impurity(c(1000000,1000000)),0.5)
close(gini_impurity(8),0)
expect_error(gini_impurity(numeric()))
expect_error(gini_impurity(c(0,0)))
expect_error(gini_impurity(c(-1,2)))
expect_error(gini_impurity(c(1.5,2)))
expect_error(gini_impurity(c(0,1000001)))
expect_error(gini_impurity(c(Inf,1)))
expect_error(gini_impurity(c(NaN,1)))
expect_error(gini_impurity(c("1","2")))
expect_error(gini_impurity(matrix(c(1,2),nrow=1)))
cat("R Gini impurity tests passed\n")
