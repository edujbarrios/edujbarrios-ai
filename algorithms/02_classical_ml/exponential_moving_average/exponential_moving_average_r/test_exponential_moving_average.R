source("algorithms/02_classical_ml/exponential_moving_average/exponential_moving_average_r/exponential_moving_average.R")
expect_error <- function(expr) stopifnot(inherits(tryCatch(expr, error=identity), "error"))
stopifnot(identical(exponential_moving_average(c(10,20,10), 0.5), c(10,15,12.5)))
stopifnot(identical(exponential_moving_average(c(10,20,10), 1), c(10,20,10)))
stopifnot(isTRUE(all.equal(exponential_moving_average(c(7,7,7), 0.1), c(7,7,7))))
stopifnot(identical(exponential_moving_average(c(1e308,-1e308), 0.5), c(1e308,0)))
expect_error(exponential_moving_average(numeric(0), 0.5))
expect_error(exponential_moving_average(c(1,NA), 0.5))
expect_error(exponential_moving_average(c(1,Inf), 0.5))
expect_error(exponential_moving_average(c(1,2), 0))
expect_error(exponential_moving_average(c(1,2), 1.1))
expect_error(exponential_moving_average(c(1,2), NaN))
cat("R exponential_moving_average tests passed\n")
