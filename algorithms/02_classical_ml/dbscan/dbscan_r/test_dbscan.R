args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"dbscan.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
points<-matrix(c(0,0,.1,0,0,.1,5,5,5.1,5,9,9),nrow=6,byrow=TRUE)
stopifnot(identical(dbscan(points,.2,2),c(0L,0L,0L,1L,1L,-1L)))
stopifnot(identical(dbscan(matrix(c(0,1,2,3),ncol=1),1.1,3),c(0L,0L,0L,0L)))
stopifnot(identical(dbscan(matrix(c(1,1,1),ncol=1),.1,3),c(0L,0L,0L)))
stopifnot(identical(dbscan(matrix(c(0,10,20),ncol=1),1,2),c(-1L,-1L,-1L)))
stopifnot(identical(dbscan(matrix(0,nrow=1),1,1),c(0L)))
expect_error(dbscan(matrix(numeric(),nrow=0,ncol=1),1,1))
expect_error(dbscan(points,0,2))
expect_error(dbscan(points,.2,0))
expect_error(dbscan(points,.2,7))
expect_error(dbscan(matrix(c(0,NaN),ncol=1),1,1))
expect_error(dbscan(matrix(c(-1.7e308,1.7e308),ncol=1),1,1))
cat("R DBSCAN tests passed\n")
