args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"farthest_first_traversal.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
points<-matrix(c(0,0,1,0,9,0,10,0),nrow=4,byrow=TRUE)
stopifnot(identical(farthest_first_traversal(points,3),c(0L,3L,1L)))
stopifnot(identical(farthest_first_traversal(points,4),c(0L,3L,1L,2L)))
dups<-matrix(c(0,0,0,0,2,0,2,0),nrow=4,byrow=TRUE)
stopifnot(identical(farthest_first_traversal(dups,3),c(0L,2L,1L)))
stopifnot(identical(farthest_first_traversal(matrix(0,nrow=1),1),c(0L)))
stopifnot(identical(farthest_first_traversal(matrix(c(0,0),ncol=1),2),c(0L,1L)))
expect_error(farthest_first_traversal(matrix(numeric(),nrow=0,ncol=1),1))
expect_error(farthest_first_traversal(points,0))
expect_error(farthest_first_traversal(points,5))
expect_error(farthest_first_traversal(matrix(c(0,NaN),ncol=1),1))
expect_error(farthest_first_traversal(matrix(c(1.7e308,-1.7e308),ncol=1),2))
cat("R farthest-first traversal tests passed\n")
