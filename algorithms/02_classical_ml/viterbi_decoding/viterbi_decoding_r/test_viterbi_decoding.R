args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"viterbi_decoding.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
p<-c(.6,.4)
a<-matrix(c(.7,.3,.4,.6),nrow=2,byrow=TRUE)
b<-matrix(c(.5,.5,.1,.9),nrow=2,byrow=TRUE)
fit<-viterbi_decoding(c(0,1,0),p,a,b)
stopifnot(identical(fit$states,c(0L,0L,0L)))
stopifnot(abs(fit$log_probability-log(.03675))<1e-12)
stopifnot(identical(viterbi_decoding(c(1,1,1),p,a,b)$states,c(1L,1L,1L)))
u<-matrix(.5,nrow=2,ncol=2)
stopifnot(identical(viterbi_decoding(c(0,1,0),c(.5,.5),u,u)$states,c(0L,0L,0L)))
stopifnot(identical(viterbi_decoding(c(0),p,a,b)$states,c(0L)))
expect_error(viterbi_decoding(numeric(),p,a,b))
expect_error(viterbi_decoding(rep(0,4097),p,a,b))
expect_error(viterbi_decoding(c(0,2),p,a,b))
expect_error(viterbi_decoding(c(0),c(0,1),a,b))
expect_error(viterbi_decoding(c(0),p,matrix(c(.7,.4,.4,.6),nrow=2,byrow=TRUE),b))
expect_error(viterbi_decoding(c(0),p,a,matrix(c(.5,.5,0,1),nrow=2,byrow=TRUE)))
cat("R Viterbi decoding tests passed\n")
