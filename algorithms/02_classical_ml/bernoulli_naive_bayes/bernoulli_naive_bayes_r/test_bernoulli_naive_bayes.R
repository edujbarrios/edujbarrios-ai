args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "bernoulli_naive_bayes.R"))
error <- function(expr) stopifnot(tryCatch({force(expr); FALSE}, error=function(e) TRUE))
x <- c(1,0, 1,1, 0,1, 0,0)
y <- c(0,0,1,1)
a <- bernoulli_naive_bayes(x, y, 4, 2, c(1,0))
b <- bernoulli_naive_bayes(x, y, 4, 2, c(0,1))
stopifnot(a$label == 0L, abs(a$probability_1 - 0.25) < 1e-12)
stopifnot(b$label == 1L, abs(b$probability_1 - 0.75) < 1e-12)
tie <- bernoulli_naive_bayes(c(0,0), c(0,1), 2, 1, 0)
stopifnot(tie$label == 0L, tie$probability_1 == 0.5)
imbalanced <- bernoulli_naive_bayes(c(0,0,0), c(0,0,1), 3, 1, 0)
stopifnot(imbalanced$label == 0L)
big <- c(rep(0, 64*16), rep(1, 64*16))
large <- bernoulli_naive_bayes(big, c(rep(0,64),rep(1,64)),128,16,rep(1,16))
stopifnot(large$label == 1L, large$probability_1 > 0.999)
error(bernoulli_naive_bayes(x, y, 1, 2, c(1,0)))
error(bernoulli_naive_bayes(x, y, 4, 0, c(1,0)))
error(bernoulli_naive_bayes(x, y, TRUE, 2, c(1,0)))
error(bernoulli_naive_bayes(x[-8], y, 4, 2, c(1,0)))
error(bernoulli_naive_bayes(x, y[-4], 4, 2, c(1,0)))
error(bernoulli_naive_bayes(x, rep(0,4), 4, 2, c(1,0)))
error(bernoulli_naive_bayes(x, c(0,0,1,2), 4, 2, c(1,0)))
error(bernoulli_naive_bayes(c(1,0,1,2,0,1,0,0), y, 4, 2, c(1,0)))
error(bernoulli_naive_bayes(x, y, 4, 2, c(1,2)))
error(bernoulli_naive_bayes(x, y, 4, 2, c(1,TRUE)))
error(bernoulli_naive_bayes(x, y, 4, 2, matrix(c(1,0), nrow=1)))
cat("R Bernoulli naive Bayes tests passed\n")
