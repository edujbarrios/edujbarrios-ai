args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "single_link_clustering.R"))
error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e) TRUE))
cluster <- single_link_clustering
p <- c(0,0, 0,1, 10,10, 10,11)
stopifnot(identical(cluster(p,4,2), c(0L,0L,1L,1L)))
stopifnot(identical(cluster(p,4,3), c(0L,0L,1L,2L)))
stopifnot(identical(cluster(p,4,1), rep(0L,4)))
stopifnot(identical(cluster(p,4,4), 0:3))
stopifnot(identical(cluster(c(0,0, 0,2, 2,0, 2,2),4,2), c(0L,0L,0L,1L)))
stopifnot(identical(cluster(c(0,0, 0,0, 10,10),3,2), c(0L,0L,1L)))
stopifnot(identical(cluster(c(-1000,-1000, 1000,1000),2,1), c(0L,0L)))
stopifnot(identical(cluster(c(0,0),1,1), 0L))
big <- as.vector(rbind(0:31, rep(0,32)))
stopifnot(identical(cluster(big,32,1), rep(0L,32)))
stopifnot(identical(cluster(big,32,32), 0:31))
error(cluster(p,0,1))
error(cluster(p,33,2))
error(cluster(p,4,0))
error(cluster(p,4,5))
error(cluster(p,TRUE,2))
error(cluster(p,4,FALSE))
error(cluster(p[-8],4,2))
error(cluster(NULL,4,2))
error(cluster(c(0,0, 1001,0),2,1))
error(cluster(c(0,0, -1001,0),2,1))
error(cluster(c(0,0, 1.5,0),2,1))
error(cluster(c(0,0, Inf,0),2,1))
error(cluster(matrix(c(0,0),nrow=1),1,1))
cat("R single-link clustering tests passed\n")
