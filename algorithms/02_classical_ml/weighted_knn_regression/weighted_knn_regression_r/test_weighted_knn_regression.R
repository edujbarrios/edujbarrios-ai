args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
folder <- dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"weighted_knn_regression.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
check <- function(train,targets,query,k,want) {
  result <- weighted_knn_regression(train,targets,query,k)
  stopifnot(abs(result-want)<=1e-11*max(1,abs(want)))
}
col <- function(x) matrix(x,ncol=1L)
check(col(c(0,4)),c(0,20),1,2,5)
check(col(c(0,2,4)),c(0,10,20),1,2,5)
check(col(c(0,2,4)),c(0,10,20),1,3,50/7)
check(col(c(0,0,2)),c(3,7,20),0,3,5)
check(col(c(0,0,2)),c(3,7,20),0,1,3)
check(col(c(0,0,2)),c(3,7,20),0,2,5)
check(col(c(-1,1)),c(2,8),0,1,2)
check(col(c(-1,1)),c(2,8),0,2,5)
check(col(c(0,3,5)),c(-2,10,20),1,2,2)
check(col(4),12,-3,1,12)
check(matrix(c(0,0,2,0,0,2),ncol=2L,byrow=TRUE),c(2,4,6),c(1,0),2,3)
check(matrix(0,nrow=128,ncol=16),rep(7,128),rep(0,16),128,7)
check(col(c(0,0,1e-300)),c(5,15,100),0,3,10)
expect_error(weighted_knn_regression(matrix(0,0,1),numeric(0),0,1))
expect_error(weighted_knn_regression(col(0),numeric(0),0,1))
expect_error(weighted_knn_regression(col(0),1,numeric(0),1))
expect_error(weighted_knn_regression(col(0),1,0,0))
expect_error(weighted_knn_regression(col(0),1,0,2))
expect_error(weighted_knn_regression(col(0),1,0,TRUE))
expect_error(weighted_knn_regression(col(0),1,0,1.5))
expect_error(weighted_knn_regression(matrix(0,1,2),1,0,1))
expect_error(weighted_knn_regression(matrix(0,1,17),1,rep(0,17),1))
expect_error(weighted_knn_regression(matrix(NaN,1,1),1,0,1))
expect_error(weighted_knn_regression(col(0),Inf,0,1))
expect_error(weighted_knn_regression(col(1001),1,0,1))
expect_error(weighted_knn_regression(col(0),1001,0,1))
expect_error(weighted_knn_regression(col(TRUE),1,0,1))
expect_error(weighted_knn_regression(col(0),1,TRUE,1))
cat("R weighted kNN regression tests passed\n")
