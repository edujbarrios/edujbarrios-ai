args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"silhouette_score.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
points<-matrix(c(0,1,5,6),ncol=1)
stopifnot(abs(silhouette_score(points,c(0,0,1,1))-79/99)<1e-12)
stopifnot(abs(silhouette_score(points,c(1,1,3,3))-79/99)<1e-12)
stopifnot(identical(silhouette_score(matrix(rep(0,4),ncol=1),c(0,0,1,1)),0.0))
stopifnot(is.finite(silhouette_score(points,c(0,0,1,2))))
expect_error(silhouette_score(points,c(0,1,2,3)))
expect_error(silhouette_score(points,c(0,0,0,0)))
expect_error(silhouette_score(points,c(0,0,1,4)))
expect_error(silhouette_score(points,c(0,0,1)))
expect_error(silhouette_score(matrix(c(0,1,NaN,6),ncol=1),c(0,0,1,1)))
expect_error(silhouette_score(matrix(c(-1.7e308,1.7e308,0,1),ncol=1),c(0,0,1,1)))
cat("R silhouette score tests passed\n")
