args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "k_means.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr); FALSE},error=function(e) TRUE))
data <- matrix(c(0,0,10,10,0,2,10,12),nrow=4,byrow=TRUE)
result <- k_means(data,2,10)
expected <- matrix(c(0,1,10,11),nrow=2,byrow=TRUE)
stopifnot(identical(unname(result$centroids),expected))
stopifnot(identical(result$assignments,c(0L,1L,0L,1L)))
one <- k_means(matrix(c(0,0,10,10),nrow=2,byrow=TRUE),1,10)
stopifnot(identical(unname(one$centroids),matrix(c(5,5),nrow=1)))
stopifnot(identical(one$assignments,c(0L,0L)))
expect_error(k_means(matrix(numeric(),nrow=0,ncol=1),1,10))
expect_error(k_means(data,0,10))
expect_error(k_means(data,5,10))
expect_error(k_means(data,2,0))
expect_error(k_means(matrix(c(0,0,2),ncol=1),2,10))
expect_error(k_means(matrix(c(NaN,1),ncol=1),1,10))
expect_error(k_means(matrix(c(1e308,1e308),ncol=1),1,10))
cat("R K-means tests passed\n")
