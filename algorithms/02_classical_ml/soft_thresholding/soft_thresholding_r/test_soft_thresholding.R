args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if(length(args)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"soft_thresholding.R"))
error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e) TRUE))
stopifnot(identical(soft_thresholding(c(-3,-0.5,0,0.5,3),1),c(-2,0,0,0,2)))
stopifnot(identical(soft_thresholding(c(-1,1),1),c(0,0)))
stopifnot(identical(soft_thresholding(c(-3,3),0),c(-3,3)))
stopifnot(identical(soft_thresholding(c(1e308,-1e308),1),c(1e308,-1e308)))
error(soft_thresholding(numeric(),1))
error(soft_thresholding(NaN,1))
error(soft_thresholding(Inf,1))
error(soft_thresholding(TRUE,1))
error(soft_thresholding(1,-1))
error(soft_thresholding(1,Inf))
cat("R soft thresholding tests passed\n")
