args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "gaussian_kde_1d.R"))
error <- function(expr) stopifnot(tryCatch({force(expr); FALSE}, error=function(e) TRUE))
kde <- gaussian_kde_1d
s <- sqrt(2*pi)
stopifnot(abs(kde(0,0,1) - 1/s) < 1e-12)
stopifnot(abs(kde(c(-1,1),0,1) - exp(-0.5)/s) < 1e-12)
stopifnot(abs(kde(c(1,1),1,2) - 1/(2*s)) < 1e-12)
stopifnot(kde(0,1000,0.001) == 0)
stopifnot(abs(kde(rep(0,512),0,1) - 1/s) < 1e-12)
stopifnot(abs(kde(0,-1000,1000) - exp(-0.5)/(1000*s)) < 1e-12)
error(kde(numeric(),0,1))
error(kde(rep(0,513),0,1))
error(kde(TRUE,0,1))
error(kde(NaN,0,1))
error(kde(Inf,0,1))
error(kde(1001,0,1))
error(kde(0,TRUE,1))
error(kde(0,1001,1))
error(kde(0,0,TRUE))
error(kde(0,0,0))
error(kde(0,0,0.0001))
error(kde(0,0,1001))
error(kde(0,0,Inf))
error(kde(matrix(0,nrow=1),0,1))
cat("R Gaussian KDE tests passed\n")
