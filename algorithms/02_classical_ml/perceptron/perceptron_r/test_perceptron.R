args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"perceptron.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
x<-matrix(c(-2,-1,-1,-1,1,1,2,1),nrow=4,byrow=TRUE)
fit<-perceptron(x,c(0,0,1,1),1,1)
stopifnot(identical(fit$weights,c(1,1)),identical(fit$bias,1.0))
stopifnot(identical(perceptron_predict(fit$weights,c(-2,-1),fit$bias),0L))
stopifnot(identical(perceptron_predict(fit$weights,c(2,1),fit$bias),1L))
fit<-perceptron(matrix(c(0,0),nrow=1),c(1),1,1)
stopifnot(identical(fit$weights,c(0,0)),identical(fit$bias,1.0))
stopifnot(identical(perceptron_predict(c(0,0),c(0,0),0),0L))
expect_error(perceptron(matrix(numeric(),nrow=0,ncol=2),numeric(),1,1))
expect_error(perceptron(matrix(1,nrow=1),c(2),1,1))
expect_error(perceptron(matrix(NaN,nrow=1),c(0),1,1))
expect_error(perceptron(matrix(1,nrow=1),c(0),0,1))
expect_error(perceptron(matrix(1,nrow=1),c(0),1,0))
expect_error(perceptron(matrix(1e308,nrow=1),c(1),1e308,2))
cat("R perceptron tests passed\n")
