args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"nearest_centroid_classifier.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
x<-matrix(c(0,0,2,0,8,0,10,0),nrow=4,byrow=TRUE)
m<-nearest_centroid_classifier(x,c(0,0,1,1))
stopifnot(identical(unname(m),matrix(c(1,0,9,0),nrow=2,byrow=TRUE)))
stopifnot(identical(nearest_centroid_classifier_predict(m,c(2,0)),0L))
stopifnot(identical(nearest_centroid_classifier_predict(m,c(8,0)),1L))
stopifnot(identical(nearest_centroid_classifier_predict(m,c(5,0)),0L))
expect_error(nearest_centroid_classifier(matrix(numeric(),nrow=0,ncol=2),numeric()))
expect_error(nearest_centroid_classifier(x,c(0,0,0,0)))
expect_error(nearest_centroid_classifier(x,c(0,0,1,2)))
expect_error(nearest_centroid_classifier(matrix(c(0,NaN),ncol=1),c(0,1)))
expect_error(nearest_centroid_classifier_predict(m,c(NaN,0)))
expect_error(nearest_centroid_classifier_predict(m,c(0)))
cat("R nearest centroid tests passed\n")
