file_arg <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(file_arg)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",file_arg[[1L]])))
source(file.path(folder,"entropy_impurity.R"))
err <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e) TRUE))
close <- function(x,y) stopifnot(abs(x-y)<1e-12)
close(entropy_impurity(c(5,0)),0)
close(entropy_impurity(c(1,1)),1)
close(entropy_impurity(c(1,1,1,1)),2)
close(entropy_impurity(c(3,1)),0.8112781244591328)
close(entropy_impurity(1000000),0)
close(entropy_impurity(c(1000000,1000000)),1)
err(entropy_impurity(numeric()))
err(entropy_impurity(c(0,0)))
err(entropy_impurity(c(-1,1)))
err(entropy_impurity(c(1000001,0)))
err(entropy_impurity(c(1.5,1)))
err(entropy_impurity(c(NaN,1)))
err(entropy_impurity(c(Inf,1)))
err(entropy_impurity(c("1","2")))
err(entropy_impurity(matrix(1,nrow=1)))
