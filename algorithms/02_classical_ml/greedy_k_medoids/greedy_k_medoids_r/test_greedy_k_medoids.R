args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"greedy_k_medoids.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
x<-matrix(c(0,1,9,10),ncol=1)
stopifnot(identical(greedy_k_medoids(x,1),c(1L)))
stopifnot(identical(greedy_k_medoids(x,2),c(1L,2L)))
stopifnot(identical(greedy_k_medoids(x,3),c(1L,2L,0L)))
stopifnot(identical(greedy_k_medoids(x,4),c(1L,2L,0L,3L)))
stopifnot(identical(greedy_k_medoids(matrix(c(0,0,0),ncol=1),3),c(0L,1L,2L)))
stopifnot(identical(greedy_k_medoids(matrix(5,nrow=1),1),c(0L)))
expect_error(greedy_k_medoids(matrix(numeric(),nrow=0,ncol=1),1))
expect_error(greedy_k_medoids(x,0))
expect_error(greedy_k_medoids(x,5))
expect_error(greedy_k_medoids(matrix(c(NaN,1),ncol=1),1))
expect_error(greedy_k_medoids(matrix(c(-1.7e308,1.7e308),ncol=1),1))
cat("R greedy k-medoids tests passed\n")
