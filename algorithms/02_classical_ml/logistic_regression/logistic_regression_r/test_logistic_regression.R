args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"logistic_regression.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr); FALSE},error=function(e) TRUE))
fit <- logistic_regression(c(0,1,2,3),c(0,0,1,1),0.2,2000)
stopifnot(fit$weight>0, fit$bias < -2, fit$weight*3 + fit$bias > 2)
single <- logistic_regression(c(0),c(1),0.2,1)
stopifnot(abs(single$weight)<1e-12, abs(single$bias-0.1)<1e-12)
expect_error(logistic_regression(numeric(),numeric(),0.2,1))
expect_error(logistic_regression(c(0,1),c(0,2),0.2,1))
expect_error(logistic_regression(c(NaN),c(0),0.2,1))
expect_error(logistic_regression(c(0),c(1),0,1))
expect_error(logistic_regression(c(0),c(1),0.2,0))
expect_error(logistic_regression(c(1e308,0),c(0,1),1e308,20))
cat("R logistic regression tests passed\n")
