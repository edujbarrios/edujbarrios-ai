args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
if (length(args)==0L) stop("run using Rscript")
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "linear_regression.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr); FALSE},error=function(e) TRUE))
fit <- linear_regression(c(0,1,2,3), c(1,3,5,7))
stopifnot(abs(fit$slope-2)<1e-12, abs(fit$intercept-1)<1e-12)
fit <- linear_regression(c(0,1,2,3), c(3,3,3,3))
stopifnot(identical(fit$slope, 0.0), identical(fit$intercept, 3.0))
expect_error(linear_regression(numeric(),numeric()))
expect_error(linear_regression(c(1),c(1)))
expect_error(linear_regression(c(1,2),c(3)))
expect_error(linear_regression(c(2,2),c(1,3)))
expect_error(linear_regression(c(NaN,1),c(1,2)))
expect_error(linear_regression(c(1e308,-1e308),c(1e308,-1e308)))
cat("R linear regression tests passed\n")
