args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"ridge_regression_1d.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
fit<-ridge_regression_1d(c(0,1,2),c(1,3,5),0)
stopifnot(abs(fit$intercept-1)<1e-12,abs(fit$slope-2)<1e-12)
fit<-ridge_regression_1d(c(0,1,2),c(1,3,5),2)
stopifnot(abs(fit$intercept-2)<1e-12,abs(fit$slope-1)<1e-12)
stopifnot(abs(fit$intercept+3*fit$slope-5)<1e-12)
fit<-ridge_regression_1d(c(2,2,2),c(1,2,3),0)
stopifnot(identical(fit$intercept,2.0),identical(fit$slope,0.0))
fit<-ridge_regression_1d(c(0),c(1),0)
stopifnot(identical(fit$intercept,1.0),identical(fit$slope,0.0))
expect_error(ridge_regression_1d(numeric(),numeric(),0))
expect_error(ridge_regression_1d(c(0,1),c(1),0))
expect_error(ridge_regression_1d(c(1),c(1),-1))
expect_error(ridge_regression_1d(c(NaN),c(1),0))
expect_error(ridge_regression_1d(c(1000001),c(1),0))
cat("R ridge regression 1D tests passed\n")
