args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"gaussian_naive_bayes.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
x<-matrix(c(0,0,0,1,5,5,5,6),nrow=4,byrow=TRUE)
y<-c(0,0,1,1)
a<-gaussian_naive_bayes(x,y,c(5,5))
stopifnot(identical(a$label,1L),a$probability_1>0.99)
b<-gaussian_naive_bayes(x,y,c(0,0))
stopifnot(identical(b$label,0L),b$probability_1<0.01)
tie<-gaussian_naive_bayes(matrix(c(0,2),ncol=1),c(0,1),c(1))
stopifnot(identical(tie$label,0L),abs(tie$probability_1-0.5)<1e-12)
expect_error(gaussian_naive_bayes(x,c(0,0,0,0),c(1,1)))
expect_error(gaussian_naive_bayes(x,c(0,0,1,2),c(1,1)))
expect_error(gaussian_naive_bayes(x,y,c(NaN,0)))
expect_error(gaussian_naive_bayes(x,y,c(0)))
cat("R Gaussian Naive Bayes tests passed\n")
