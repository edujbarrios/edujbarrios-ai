args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"decision_stump.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
fit<-decision_stump(c(0,1,2,3),c(0,0,1,1))
stopifnot(identical(fit,list(threshold=1.0,positive_right=TRUE,errors=0L)))
fit<-decision_stump(c(0,1,2,3),c(1,1,0,0))
stopifnot(identical(fit,list(threshold=1.0,positive_right=FALSE,errors=0L)))
fit<-decision_stump(c(3,0,2,1),c(1,0,1,0))
stopifnot(identical(fit,list(threshold=1.0,positive_right=TRUE,errors=0L)))
stopifnot(identical(decision_stump(c(4,4),c(1,1))$positive_right,FALSE))
stopifnot(identical(decision_stump(c(4,4),c(0,0))$positive_right,TRUE))
stopifnot(identical(decision_stump(c(4,4),c(0,1))$errors,1L))
stopifnot(identical(decision_stump_predict(2,1,TRUE),1L))
expect_error(decision_stump(numeric(),numeric()))
expect_error(decision_stump(c(NaN),c(0)))
expect_error(decision_stump(c(0),c(2)))
expect_error(decision_stump_predict(Inf,1,TRUE))
cat("R decision stump tests passed\n")
