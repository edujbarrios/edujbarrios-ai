args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"mini_batch_gradient_descent.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
fit<-mini_batch_gradient_descent(c(0,1),c(1,3),0.1,1,1)
stopifnot(abs(fit$weight-0.29)<1e-12,abs(fit$bias-0.39)<1e-12)
fit<-mini_batch_gradient_descent(c(0,1,2,3),c(1,3,5,7),0.05,2000,3)
stopifnot(abs(fit$weight-2)<0.01,abs(fit$bias-1)<0.01)
expect_error(mini_batch_gradient_descent(numeric(),numeric(),0.1,1,1))
expect_error(mini_batch_gradient_descent(c(1),c(1),0,1,1))
expect_error(mini_batch_gradient_descent(c(1),c(1),0.1,0,1))
expect_error(mini_batch_gradient_descent(c(1),c(1),0.1,1,2))
expect_error(mini_batch_gradient_descent(c(NaN),c(1),0.1,1,1))
expect_error(mini_batch_gradient_descent(c(1e308,1e308),c(1,3),1e308,2,2))
cat("R mini-batch gradient descent tests passed\n")
