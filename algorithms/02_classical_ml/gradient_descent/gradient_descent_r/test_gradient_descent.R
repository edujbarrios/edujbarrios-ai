args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
if (length(args)==0L) stop("run using Rscript")
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "gradient_descent.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr); FALSE}, error=function(e) TRUE))
fit <- gradient_descent(c(0,1,2,3),c(1,3,5,7),0.05,2000)
stopifnot(abs(fit$weight-2)<1e-3, abs(fit$bias-1)<1e-3)
fit <- gradient_descent(c(0,1,2,3),c(3,3,3,3),0.05,2000)
stopifnot(abs(fit$weight)<1e-3, abs(fit$bias-3)<1e-3)
expect_error(gradient_descent(numeric(),numeric(),0.05,10))
expect_error(gradient_descent(c(1),numeric(),0.05,10))
expect_error(gradient_descent(c(1),c(2),0,10))
expect_error(gradient_descent(c(1),c(2),0.05,0))
expect_error(gradient_descent(c(NaN),c(2),0.05,10))
cat("R gradient descent tests passed\n")
