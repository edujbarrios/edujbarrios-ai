args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"multinomial_naive_bayes.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
x<-matrix(c(3,0,2,0,0,3,0,2),nrow=4,byrow=TRUE)
m<-multinomial_naive_bayes(x,c(0,0,1,1))
stopifnot(abs(m$log_priors[[1]]-log(.5))<1e-12)
stopifnot(abs(m$log_likelihoods[1,1]-log(6/7))<1e-12)
stopifnot(abs(m$log_likelihoods[1,2]-log(1/7))<1e-12)
stopifnot(abs(m$log_likelihoods[2,1]-log(1/7))<1e-12)
stopifnot(abs(m$log_likelihoods[2,2]-log(6/7))<1e-12)
stopifnot(identical(multinomial_naive_bayes_predict(m,c(2,0)),0L))
stopifnot(identical(multinomial_naive_bayes_predict(m,c(0,2)),1L))
stopifnot(identical(multinomial_naive_bayes_predict(m,c(0,0)),0L))
expect_error(multinomial_naive_bayes(matrix(numeric(),nrow=0,ncol=2),numeric()))
expect_error(multinomial_naive_bayes(x,c(0,0,0,0)))
expect_error(multinomial_naive_bayes(x,c(0,0,1,2)))
expect_error(multinomial_naive_bayes(matrix(c(1000001,0),nrow=1),c(0)))
expect_error(multinomial_naive_bayes_predict(m,c(0)))
expect_error(multinomial_naive_bayes_predict(m,c(1000001,0)))
m$log_priors[[1]]<-NaN
expect_error(multinomial_naive_bayes_predict(m,c(1,0)))
cat("R multinomial Naive Bayes tests passed\n")
