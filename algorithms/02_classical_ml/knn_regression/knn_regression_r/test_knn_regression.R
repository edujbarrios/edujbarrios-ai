args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"knn_regression.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
x<-matrix(c(0,0,2,0,0,2,5,5),nrow=4,byrow=TRUE)
y<-c(2,4,6,10)
stopifnot(identical(knn_regression(x,y,c(0,0),1),2.0))
stopifnot(identical(knn_regression(x,y,c(0,0),2),3.0))
stopifnot(identical(knn_regression(x,y,c(0,0),3),4.0))
stopifnot(identical(knn_regression(x,y,c(0,0),4),5.5))
stopifnot(identical(knn_regression(matrix(rep(0,4),nrow=2),c(-5,7),c(0,0),2),1.0))
stopifnot(identical(knn_regression(matrix(c(0,0),nrow=1),c(2),c(0,0),1),2.0))
stopifnot(abs(knn_regression(matrix(rep(0,4),nrow=2),c(1e308,1e308),c(0,0),2)/1e308-1)<1e-12)
expect_error(knn_regression(matrix(numeric(),nrow=0,ncol=2),numeric(),c(0,0),1))
expect_error(knn_regression(x,y,c(0,0),0))
expect_error(knn_regression(x,y,c(0,0),5))
expect_error(knn_regression(x,y,c(0),1))
expect_error(knn_regression(x,c(2,4),c(0,0),1))
expect_error(knn_regression(matrix(c(0,0,NaN,0),nrow=2,byrow=TRUE),c(1,2),c(0,0),1))
expect_error(knn_regression(matrix(c(-1.7e308,1.7e308),ncol=1),c(1,2),-1.7e308,1))
cat("R KNN regression tests passed\n")
