args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"hmm_forward_algorithm.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
p<-c(.6,.4)
a<-matrix(c(.7,.3,.4,.6),nrow=2,byrow=TRUE)
b<-matrix(c(.5,.5,.1,.9),nrow=2,byrow=TRUE)
stopifnot(abs(hmm_forward_algorithm(c(0,1,0),p,a,b)-log(.069616))<1e-12)
stopifnot(abs(hmm_forward_algorithm(c(0),p,a,b)-log(.34))<1e-12)
u<-matrix(.5,nrow=2,ncol=2)
stopifnot(abs(hmm_forward_algorithm(rep(c(0,1),50),c(.5,.5),u,u)-
              100*log(.5))<1e-11)
expect_error(hmm_forward_algorithm(numeric(),p,a,b))
expect_error(hmm_forward_algorithm(rep(0,4097),p,a,b))
expect_error(hmm_forward_algorithm(c(0,2),p,a,b))
expect_error(hmm_forward_algorithm(c(0),c(0,1),a,b))
expect_error(hmm_forward_algorithm(c(0),p,matrix(c(.7,.4,.4,.6),nrow=2,byrow=TRUE),b))
expect_error(hmm_forward_algorithm(c(0),p,a,matrix(c(.5,.5,0,1),nrow=2,byrow=TRUE)))
cat("R HMM Forward tests passed\n")
