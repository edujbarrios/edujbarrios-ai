args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "top_k.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr); FALSE},error=function(e) TRUE))
stopifnot(identical(top_k(c(0.8,0.9,0.9,-1),3), c(1L,2L,0L)))
stopifnot(identical(top_k(c(1,1,1),2),c(0L,1L)))
stopifnot(identical(top_k(c(2,-4),2),c(0L,1L)))
expect_error(top_k(numeric(),1))
expect_error(top_k(c(1),0))
expect_error(top_k(c(1),2))
expect_error(top_k(c(NaN,1),1))
expect_error(top_k(c(Inf),1))
cat("R Top-K tests passed\n")
