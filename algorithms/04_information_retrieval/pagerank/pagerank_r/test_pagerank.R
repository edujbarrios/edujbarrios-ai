args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"pagerank.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
p<-pagerank(matrix(c(0,1,0,0),nrow=2,byrow=TRUE))
stopifnot(abs(p[[1]]-1/2.85)<1e-12,abs(p[[2]]-(1-1/2.85))<1e-12)
cycle<-pagerank(matrix(c(0,1,0,0,0,1,1,0,0),nrow=3,byrow=TRUE))
stopifnot(all(abs(cycle-1/3)<1e-12))
stopifnot(identical(pagerank(matrix(0,nrow=2,ncol=2)),c(.5,.5)))
stopifnot(abs(pagerank(matrix(0,nrow=1))[[1]]-1)<1e-12)
stopifnot(abs(sum(pagerank(matrix(c(0,2,1,0),nrow=2,byrow=TRUE)))-1)<1e-12)
expect_error(pagerank(matrix(numeric(),nrow=0,ncol=0)))
expect_error(pagerank(matrix(c(0,1),nrow=1)))
expect_error(pagerank(matrix(c(0,-1,0,0),nrow=2)))
expect_error(pagerank(matrix(c(0,NaN,0,0),nrow=2)))
expect_error(pagerank(matrix(c(0,1000001,0,0),nrow=2)))
cat("R PageRank tests passed\n")
