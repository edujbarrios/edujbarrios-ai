args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"postings_union.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
stopifnot(identical(postings_union(c(0,2,4),c(1,2,5)),c(0L,1L,2L,4L,5L)))
stopifnot(identical(postings_union(numeric(),c(0,2,4)),c(0L,2L,4L)))
stopifnot(identical(postings_union(c(0,2,4),numeric()),c(0L,2L,4L)))
stopifnot(identical(postings_union(numeric(),numeric()),integer()))
stopifnot(identical(postings_union(c(2147483647),numeric()),c(2147483647L)))
expect_error(postings_union(c(1,1),numeric()))
expect_error(postings_union(numeric(),c(5,4)))
expect_error(postings_union(c(-1),c(1)))
expect_error(postings_union(c(2147483648),numeric()))
expect_error(postings_union(c(1.5),numeric()))
cat("R postings union tests passed\n")
