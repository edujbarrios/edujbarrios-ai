args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "jaccard_similarity.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr); FALSE},error=function(e) TRUE))
stopifnot(identical(jaccard_similarity(c(1,1,2,3),c(2,3,4)),0.5))
stopifnot(identical(jaccard_similarity(numeric(),numeric()),1.0))
stopifnot(identical(jaccard_similarity(numeric(),c(3)),0.0))
stopifnot(identical(jaccard_similarity(c(-5,3),c(3,-5)),1.0))
stopifnot(identical(jaccard_similarity(c(-2147483648,2147483647),c(2147483647,-2147483648)),1.0))
expect_error(jaccard_similarity(c(1.5),numeric()))
expect_error(jaccard_similarity(c(2147483648),numeric()))
expect_error(jaccard_similarity(c(NaN),numeric()))
cat("R Jaccard tests passed\n")
