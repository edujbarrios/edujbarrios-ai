args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
if(length(args)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder,"reciprocal_rank_fusion.R"))
error <- function(expr) stopifnot(tryCatch({force(expr); FALSE},error=function(e) TRUE))
stopifnot(identical(reciprocal_rank_fusion(c(10,20,30),c(30,10,40)),
                    c(10L,30L,20L,40L)))
stopifnot(identical(reciprocal_rank_fusion(c(2,1),c(1,2)),c(1L,2L)))
stopifnot(identical(reciprocal_rank_fusion(c(10,20,30),numeric()),c(10L,20L,30L)))
error(reciprocal_rank_fusion(numeric(),numeric()))
error(reciprocal_rank_fusion(c(1,1),numeric()))
error(reciprocal_rank_fusion(c(-1),numeric()))
error(reciprocal_rank_fusion(c(2147483648),numeric()))
cat("R reciprocal rank fusion tests passed\n")
