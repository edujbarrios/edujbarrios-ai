args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "jaro_winkler_similarity.R"))
near <- function(a, b, target) stopifnot(abs(jaro_winkler_similarity(a, b) - target) < 1e-12)
expect_error <- function(expr) stopifnot(tryCatch({ force(expr); FALSE }, error=function(e) TRUE))
near("MARTHA", "MARHTA", 0.9611111111111111)
near("DIXON", "DICKSONX", 0.8133333333333334)
near("JELLYFISH", "SMELLYFISH", 0.8962962962962963)
near("ABCD", "ACBD", 0.925)
near("abc", "axz", 5/9)
near("MARHTA", "MARTHA", 0.9611111111111111)
near("", "", 1.0)
near("", "abc", 0.0)
near("abc", "", 0.0)
near("x", "x", 1.0)
near("x", "y", 0.0)
near("A", "a", 0.0)
near(paste(rep("a", 512), collapse=""), paste(rep("a", 512), collapse=""), 1.0)
expect_error(jaro_winkler_similarity(paste(rep("a", 513), collapse=""), "a"))
expect_error(jaro_winkler_similarity("a", paste(rep("b", 513), collapse="")))
expect_error(jaro_winkler_similarity("a\tb", "a"))
expect_error(jaro_winkler_similarity("é", "e"))
expect_error(jaro_winkler_similarity(NA_character_, "a"))
expect_error(jaro_winkler_similarity(3, "a"))
