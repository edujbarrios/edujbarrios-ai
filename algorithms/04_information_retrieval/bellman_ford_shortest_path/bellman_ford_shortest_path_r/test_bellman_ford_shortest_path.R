file_arg <- grep("^--file=", commandArgs(FALSE), value = TRUE)
if (length(file_arg)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=", "", file_arg[[1L]])))
source(file.path(folder, "bellman_ford_shortest_path.R"))
expect_error <- function(expr) {
  failed <- tryCatch({force(expr);FALSE}, error=function(e) TRUE)
  stopifnot(failed)
}
edge_matrix <- function(values) matrix(values, ncol=3L, byrow=TRUE)
graph <- edge_matrix(c(0,1,4, 0,2,5, 1,2,-2, 2,3,3))
result <- bellman_ford_shortest_path(graph,5,0)
stopifnot(identical(result[1:4],c(0,4,2,5)),is.infinite(result[[5L]]))
stopifnot(identical(bellman_ford_shortest_path(edge_matrix(numeric()),1,0),0.0))
zeros <- edge_matrix(c(0,1,0,0,1,5,1,2,-1))
stopifnot(identical(bellman_ford_shortest_path(zeros,3,0),c(0,0,-1)))
remote <- edge_matrix(c(2,3,-3,3,2,1))
stopifnot(is.infinite(bellman_ford_shortest_path(remote,4,0)[[3L]]))
expect_error(bellman_ford_shortest_path(edge_matrix(c(0,1,1,1,2,-3,2,1,1)),3,0))
expect_error(bellman_ford_shortest_path(edge_matrix(c(0,0,-1)),1,0))
expect_error(bellman_ford_shortest_path(graph,0,0))
expect_error(bellman_ford_shortest_path(graph,5,5))
expect_error(bellman_ford_shortest_path(edge_matrix(c(0,5,1)),3,0))
expect_error(bellman_ford_shortest_path(edge_matrix(c(0,1,NaN)),3,0))
expect_error(bellman_ford_shortest_path(edge_matrix(c(0,1,1000001)),3,0))
expect_error(bellman_ford_shortest_path(edge_matrix(c(0.5,1,1)),3,0))
expect_error(bellman_ford_shortest_path(matrix(1,nrow=2,ncol=2),3,0))
cat("R Bellman-Ford tests passed\n")
