args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "sorted_lexicon_prefix_search.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr); FALSE},
                                                  error=function(e) TRUE))
words <- c("ant", "antenna", "ape", "bat", "batch", "cat")
stopifnot(identical(sorted_lexicon_prefix_search(words, "an"), c(0L,1L)))
stopifnot(identical(sorted_lexicon_prefix_search(words, "ba"), c(3L,4L)))
stopifnot(identical(sorted_lexicon_prefix_search(words, "cat"), 5L))
stopifnot(identical(sorted_lexicon_prefix_search(words, "zzz"), integer()))
stopifnot(identical(sorted_lexicon_prefix_search(words, ""), 0:5))
stopifnot(identical(sorted_lexicon_prefix_search(character(), ""), integer()))
stopifnot(identical(sorted_lexicon_prefix_search("a", "a"), 0L))
expect_error(sorted_lexicon_prefix_search(c("bat","ant"), "a"))
expect_error(sorted_lexicon_prefix_search(c("ant","ant"), "a"))
expect_error(sorted_lexicon_prefix_search("", ""))
expect_error(sorted_lexicon_prefix_search("Ant", "a"))
expect_error(sorted_lexicon_prefix_search("mañana", "m"))
expect_error(sorted_lexicon_prefix_search("ant", "A"))
expect_error(sorted_lexicon_prefix_search("ant", paste(rep("a",513),collapse="")))
cat("R sorted lexicon prefix search tests passed\n")
