args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "rabin_karp_substring_search.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr); FALSE}, error=function(e) TRUE))
stopifnot(identical(rabin_karp_substring_search("aaaa", "aa"), c(0L, 1L, 2L)))
stopifnot(identical(rabin_karp_substring_search("abababa", "aba"), c(0L, 2L, 4L)))
stopifnot(identical(rabin_karp_substring_search("ABABDABACDABABCABAB", "ABABCABAB"), 10L))
stopifnot(identical(rabin_karp_substring_search("abc", "ABC"), integer(0)))
stopifnot(identical(rabin_karp_substring_search("ab", "abc"), integer(0)))
stopifnot(identical(rabin_karp_substring_search("abc", ""), 0:3))
stopifnot(identical(rabin_karp_substring_search("", ""), 0L))
stopifnot(identical(rabin_karp_substring_search("", "a"), integer(0)))
stopifnot(identical(rabin_karp_substring_search(paste(rep("a", 512), collapse=""), "aa"),
                    as.integer(0:510)))
expect_error(rabin_karp_substring_search(paste(rep("a", 513), collapse=""), "a"))
expect_error(rabin_karp_substring_search("a", paste(rep("b", 513), collapse="")))
expect_error(rabin_karp_substring_search("é", "e"))
expect_error(rabin_karp_substring_search("a\tb", "a"))
expect_error(rabin_karp_substring_search(NA_character_, "a"))
cat("R Rabin-Karp tests passed\n")
