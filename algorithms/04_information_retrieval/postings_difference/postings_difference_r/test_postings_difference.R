args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"postings_difference.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
stopifnot(identical(postings_difference(c(0,2,4,7),c(1,2,5,7)),c(0L,4L)))
stopifnot(identical(postings_difference(c(0,2,4),c(0,2,4)),integer()))
stopifnot(identical(postings_difference(c(0,2,4),numeric()),c(0L,2L,4L)))
stopifnot(identical(postings_difference(numeric(),c(0,2,4)),integer()))
stopifnot(identical(postings_difference(numeric(),numeric()),integer()))
stopifnot(identical(postings_difference(c(2147483647),numeric()),c(2147483647L)))
expect_error(postings_difference(c(1,1),numeric()))
expect_error(postings_difference(numeric(),c(5,4)))
expect_error(postings_difference(c(-1),c(0)))
expect_error(postings_difference(c(2147483648),numeric()))
expect_error(postings_difference(numeric(),c(0,0)))
cat("R postings difference tests passed\n")
