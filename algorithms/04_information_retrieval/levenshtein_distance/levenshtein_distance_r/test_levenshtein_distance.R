args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"levenshtein_distance.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
stopifnot(identical(levenshtein_distance("kitten","sitting"),3L))
stopifnot(identical(levenshtein_distance("sitting","kitten"),3L))
stopifnot(identical(levenshtein_distance("","abc"),3L))
stopifnot(identical(levenshtein_distance("abc",""),3L))
stopifnot(identical(levenshtein_distance("cat","cat"),0L))
stopifnot(identical(levenshtein_distance("ab","ba"),2L))
stopifnot(identical(levenshtein_distance("A","a"),1L))
stopifnot(identical(levenshtein_distance(paste(rep("a",512),collapse=""),""),512L))
expect_error(levenshtein_distance(paste(rep("a",513),collapse=""),""))
expect_error(levenshtein_distance("a\tb","ab"))
expect_error(levenshtein_distance("a\nb","ab"))
expect_error(levenshtein_distance("é","e"))
expect_error(levenshtein_distance(NA_character_,"a"))
cat("R Levenshtein tests passed\n")
