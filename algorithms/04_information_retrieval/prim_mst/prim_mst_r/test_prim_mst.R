file_arg <- grep("^--file=", commandArgs(FALSE), value=TRUE)
if (length(file_arg)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=", "", file_arg[[1L]])))
source(file.path(folder, "prim_mst.R"))
expect_error <- function(expr) {
  failed <- tryCatch({force(expr);FALSE}, error=function(e) TRUE)
  stopifnot(failed)
}
graph <- matrix(c(0,1,4,0,1,0,2,5,4,2,0,3,0,5,3,0), nrow=4, byrow=TRUE)
stopifnot(identical(prim_mst(graph),6.0))
ties <- matrix(c(0,1,1,1,0,1,1,1,0), nrow=3, byrow=TRUE)
stopifnot(identical(prim_mst(ties),2.0))
stopifnot(identical(prim_mst(matrix(0,nrow=1,ncol=1)),0.0))
expect_error(prim_mst(matrix(numeric(),nrow=0,ncol=0)))
expect_error(prim_mst(matrix(c(0,0,0,0),nrow=2)))
expect_error(prim_mst(matrix(c(0,2,1,0),nrow=2,byrow=TRUE)))
expect_error(prim_mst(matrix(c(1,1,1,0),nrow=2,byrow=TRUE)))
expect_error(prim_mst(matrix(c(0,-1,-1,0),nrow=2)))
expect_error(prim_mst(matrix(c(0,NaN,NaN,0),nrow=2)))
expect_error(prim_mst(matrix(c(0,Inf,Inf,0),nrow=2)))
expect_error(prim_mst(matrix(c(0,1000001,1000001,0),nrow=2)))
expect_error(prim_mst(matrix(0,nrow=2,ncol=3)))
cat("R Prim MST tests passed\n")
