args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"maximal_marginal_relevance.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
r<-c(.9,.8,.7)
s<-matrix(c(1,.9,-.5,.9,1,0,-.5,0,1),nrow=3,byrow=TRUE)
stopifnot(identical(maximal_marginal_relevance(r,s,.5,3),c(0L,2L,1L)))
stopifnot(identical(maximal_marginal_relevance(r,s,1,3),c(0L,1L,2L)))
stopifnot(identical(maximal_marginal_relevance(r,s,0,3),c(0L,2L,1L)))
stopifnot(identical(maximal_marginal_relevance(c(1,1,1),diag(3),.5,3),c(0L,1L,2L)))
stopifnot(identical(maximal_marginal_relevance(c(1),matrix(1,nrow=1),.5,1),c(0L)))
expect_error(maximal_marginal_relevance(numeric(),matrix(numeric(),nrow=0),.5,1))
expect_error(maximal_marginal_relevance(r,s,.5,0))
expect_error(maximal_marginal_relevance(r,s,.5,4))
expect_error(maximal_marginal_relevance(r,s,NaN,1))
expect_error(maximal_marginal_relevance(r,s,1.1,1))
expect_error(maximal_marginal_relevance(r,matrix(1,nrow=2,ncol=2),.5,1))
expect_error(maximal_marginal_relevance(c(.9,.8,-.1),s,.5,1))
cat("R maximal marginal relevance tests passed\n")
