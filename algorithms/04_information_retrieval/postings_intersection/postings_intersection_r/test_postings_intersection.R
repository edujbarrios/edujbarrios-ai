args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
folder <- dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"postings_intersection.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e) TRUE))
stopifnot(identical(postings_intersection(c(0,2,4,9),c(1,2,4,8)), c(2L,4L)))
stopifnot(identical(postings_intersection(c(0,2,4,9),c(0,2,4,9)), c(0L,2L,4L,9L)))
stopifnot(identical(postings_intersection(numeric(),c(1,2)), integer()))
stopifnot(identical(postings_intersection(numeric(),numeric()), integer()))
expect_error(postings_intersection(c(1,1,2),c(1)))
expect_error(postings_intersection(c(5,2),c(2)))
expect_error(postings_intersection(c(-1),c(1)))
expect_error(postings_intersection(c(2147483648),c(1)))
expect_error(postings_intersection(numeric(),c(3,3)))
cat("R postings intersection tests passed\n")
