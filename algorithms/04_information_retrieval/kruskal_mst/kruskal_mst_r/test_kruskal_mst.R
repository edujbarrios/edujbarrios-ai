args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"kruskal_mst.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
g<-matrix(c(0,1,4,Inf,1,0,2,5,4,2,0,3,Inf,5,3,0),nrow=4,byrow=TRUE)
x<-kruskal_mst(g)
stopifnot(identical(x$edges,matrix(c(0L,1L,1L,2L,2L,3L),ncol=2,byrow=TRUE)))
stopifnot(identical(x$total,6.0))
x<-kruskal_mst(matrix(c(0,1,1,1,0,1,1,1,0),nrow=3,byrow=TRUE))
stopifnot(identical(x$edges,matrix(c(0L,1L,0L,2L),ncol=2,byrow=TRUE)))
stopifnot(identical(x$total,2.0))
x<-kruskal_mst(matrix(c(0,0,2,0,0,1,2,1,0),nrow=3,byrow=TRUE))
stopifnot(identical(x$total,1.0))
x<-kruskal_mst(matrix(0,nrow=1))
stopifnot(nrow(x$edges)==0L,identical(x$total,0.0))
expect_error(kruskal_mst(matrix(numeric(),nrow=0,ncol=0)))
expect_error(kruskal_mst(matrix(c(0,1),nrow=1)))
expect_error(kruskal_mst(matrix(c(0,Inf,Inf,0),nrow=2)))
expect_error(kruskal_mst(matrix(c(0,1,2,0),nrow=2)))
expect_error(kruskal_mst(matrix(c(0,-1,-1,0),nrow=2)))
expect_error(kruskal_mst(matrix(c(0,NaN,NaN,0),nrow=2)))
cat("R Kruskal MST tests passed\n")
