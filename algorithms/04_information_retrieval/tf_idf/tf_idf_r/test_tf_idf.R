args <- grep("^--file=", commandArgs(FALSE), value = TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "tf_idf.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr); FALSE}, error = function(e) TRUE))
stopifnot(abs(tf_idf(3, 100, 10) - 3 * log(10)) < 1e-12)
stopifnot(identical(tf_idf(0, 100, 10), 0.0))
stopifnot(identical(tf_idf(12, 100, 100), 0.0))
expect_error(tf_idf(1, 0, 0))
expect_error(tf_idf(1, 100, 0))
expect_error(tf_idf(1, 100, 101))
expect_error(tf_idf(-1, 100, 10))
cat("R TF-IDF tests passed\n")
