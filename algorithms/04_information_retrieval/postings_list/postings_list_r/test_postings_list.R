args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
folder <- dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"postings_list.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr); FALSE},error=function(e) TRUE))
corpus <- list(c(1,2,1),numeric(),c(2,1),c(3))
p <- postings_list(corpus,1)
stopifnot(identical(p$doc_ids,c(0L,2L)))
stopifnot(identical(p$frequencies,c(2L,1L)))
stopifnot(identical(postings_list(corpus,4)$doc_ids,integer()))
stopifnot(identical(postings_list(list(),-4)$doc_ids,integer()))
p <- postings_list(list(c(-5,-5)),-5)
stopifnot(identical(p$doc_ids,c(0L)),identical(p$frequencies,c(2L)))
expect_error(postings_list(list(c(NaN)),1))
expect_error(postings_list(list(c(2147483648)),1))
expect_error(postings_list(list(c(1)),1.5))
expect_error(postings_list(c(1,2),1))
cat("R postings list tests passed\n")
