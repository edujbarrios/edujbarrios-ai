args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "damerau_levenshtein_distance.R"))
error <- function(expr) stopifnot(tryCatch({force(expr); FALSE}, error=function(e) TRUE))
dl <- damerau_levenshtein_distance
stopifnot(dl(c(67, 65), c(65, 66, 67)) == 2)
stopifnot(dl(c(65, 66, 67), c(67, 65)) == 2)
stopifnot(dl(c(1, 2), c(2, 1)) == 1)
stopifnot(dl(c(1, 1, 2), c(1, 2, 1)) == 1)
stopifnot(dl(c(0, 255), c(255, 0)) == 1)
stopifnot(dl(c(1, 2, 3), c(1, 4, 3)) == 1)
stopifnot(dl(c(1, 2, 3), c(1, 2, 3)) == 0)
stopifnot(dl(numeric(), c(0, 255)) == 2)
stopifnot(dl(c(0, 255), numeric()) == 2)
stopifnot(dl(numeric(), numeric()) == 0)
stopifnot(dl(rep(0, 256), rep(0, 256)) == 0)
stopifnot(dl(rep(0, 256), rep(1, 256)) == 256)
error(dl(TRUE, numeric()))
error(dl(-1, numeric()))
error(dl(256, numeric()))
error(dl(1.5, numeric()))
error(dl(Inf, numeric()))
error(dl(matrix(c(1, 2), nrow=1), numeric()))
error(dl(rep(1, 257), numeric()))
cat("R unrestricted Damerau-Levenshtein tests passed\n")
