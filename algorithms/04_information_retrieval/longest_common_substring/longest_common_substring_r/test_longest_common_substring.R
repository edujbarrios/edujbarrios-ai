args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "longest_common_substring.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr); FALSE}, error=function(e) TRUE))
check <- function(a,b,n,i,j) {
  stopifnot(identical(longest_common_substring(a,b),
                     list(length=as.integer(n),start_a=as.integer(i),start_b=as.integer(j))))
}
check("banana","ananas",5,1,0)
check("abcdef","zabcf",3,0,1)
check("ababa","babab",4,0,1)
check("abcabc","abc",3,0,0)
check("aa","baaa",2,0,1)
check("ABC","abc",0,0,0)
check("","",0,0,0)
check("abc","",0,0,0)
check("","abc",0,0,0)
check("A","A",1,0,0)
check(paste(rep("a",512),collapse=""),paste(rep("a",512),collapse=""),512,0,0)
expect_error(longest_common_substring(paste(rep("a",513),collapse=""),"a"))
expect_error(longest_common_substring("a",paste(rep("a",513),collapse="")))
expect_error(longest_common_substring("é","e"))
expect_error(longest_common_substring("a\tb","a"))
expect_error(longest_common_substring(NA_character_,"a"))
expect_error(longest_common_substring(1,"a"))
cat("R longest common substring tests passed\n")
