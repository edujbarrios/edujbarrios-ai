args <- grep("^--file=", commandArgs(FALSE), value = TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "dice_similarity.R"))
expect_error <- function(expr) {
  stopifnot(tryCatch({ force(expr); FALSE }, error = function(e) TRUE))
}
stopifnot(abs(dice_similarity(c(1, 1, 2, 3), c(2, 3, 4)) - 2 / 3) < 1e-12)
stopifnot(dice_similarity(numeric(), numeric()) == 1)
stopifnot(dice_similarity(numeric(), 7) == 0)
stopifnot(dice_similarity(7, numeric()) == 0)
stopifnot(dice_similarity(c(-5, 3), c(3, -5)) == 1)
stopifnot(dice_similarity(-2147483648, -2147483648) == 1)
stopifnot(dice_similarity(-2147483648, 2147483647) == 0)
expect_error(dice_similarity(TRUE, numeric()))
expect_error(dice_similarity(1.5, numeric()))
expect_error(dice_similarity(2147483648, numeric()))
expect_error(dice_similarity(NaN, numeric()))
expect_error(dice_similarity(numeric(), "7"))
cat("R Dice similarity tests passed\n")
