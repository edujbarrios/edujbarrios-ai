args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"hits_hubs_authorities.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
star<-matrix(c(0,1,1,0,0,0,0,0,0),nrow=3,byrow=TRUE)
v<-hits_hubs_authorities(star)
stopifnot(v$authorities[[1]]==0)
stopifnot(abs(v$authorities[[2]]-1/sqrt(2))<1e-12)
stopifnot(abs(v$authorities[[3]]-1/sqrt(2))<1e-12)
stopifnot(identical(v$hubs,c(1,0,0)))
cycle<-matrix(c(0,1,0,0,0,1,1,0,0),nrow=3,byrow=TRUE)
v<-hits_hubs_authorities(cycle)
stopifnot(all(abs(v$authorities-1/sqrt(3))<1e-12))
stopifnot(all(abs(v$hubs-1/sqrt(3))<1e-12))
v<-hits_hubs_authorities(matrix(0,nrow=2,ncol=2))
stopifnot(identical(v$authorities,c(0,0)),identical(v$hubs,c(0,0)))
v<-hits_hubs_authorities(matrix(1,nrow=1))
stopifnot(identical(v$authorities,c(1)),identical(v$hubs,c(1)))
expect_error(hits_hubs_authorities(matrix(numeric(),nrow=0,ncol=0)))
expect_error(hits_hubs_authorities(matrix(c(0,1),nrow=1)))
expect_error(hits_hubs_authorities(matrix(c(0,-1,0,0),nrow=2)))
expect_error(hits_hubs_authorities(matrix(c(0,NaN,0,0),nrow=2)))
expect_error(hits_hubs_authorities(matrix(c(0,2,0,0),nrow=2)))
cat("R HITS tests passed\n")
