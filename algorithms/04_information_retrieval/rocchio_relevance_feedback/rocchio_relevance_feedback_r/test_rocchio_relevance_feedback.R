args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"rocchio_relevance_feedback.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
rel<-matrix(c(2,0,4,2),nrow=2,byrow=TRUE)
irr<-matrix(c(0,2,2,2),nrow=2,byrow=TRUE)
empty<-matrix(numeric(),nrow=0,ncol=2)
out<-rocchio_relevance_feedback(c(1,1),rel,irr)
stopifnot(abs(out[[1]]-3.1)<1e-12,abs(out[[2]]-1.45)<1e-12)
out<-rocchio_relevance_feedback(c(1,1),rel,empty)
stopifnot(abs(out[[1]]-3.25)<1e-12,abs(out[[2]]-1.75)<1e-12)
stopifnot(identical(rocchio_relevance_feedback(c(0,0),empty,
                                                matrix(c(1,1),nrow=1)),c(0,0)))
expect_error(rocchio_relevance_feedback(c(1,1),empty,empty))
expect_error(rocchio_relevance_feedback(c(1,1),matrix(c(1),nrow=1),empty))
expect_error(rocchio_relevance_feedback(c(1,1),matrix(c(NaN,1),nrow=1),empty))
expect_error(rocchio_relevance_feedback(c(1,1),matrix(c(-1,1),nrow=1),empty))
expect_error(rocchio_relevance_feedback(numeric(),rel,irr))
cat("R Rocchio tests passed\n")
