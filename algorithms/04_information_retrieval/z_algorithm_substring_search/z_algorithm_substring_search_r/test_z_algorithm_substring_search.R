args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
folder <- dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"z_algorithm_substring_search.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
check <- function(t,p,want) {
  stopifnot(identical(z_algorithm_substring_search(t,p),as.integer(want)))
}
check("banana","ana",c(1,3))
check("aaaa","aa",0:2)
check("abcabc","abc",c(0,3))
check("abc","xyz",integer(0))
check("abc","ABC",integer(0))
check("ab","abc",integer(0))
check("mississippi","issi",c(1,4))
check("a a a","a ",c(0,2))
check("~!~!","~!",c(0,2))
check("aba","aba",0)
check("abc","",0:3)
check("","",0)
check("","a",integer(0))
long <- paste(rep("a",512),collapse="")
check(long,"aa",0:510)
check(long,long,0)
check(long,"",0:512)
expect_error(z_algorithm_substring_search(paste(rep("a",513),collapse=""),"a"))
expect_error(z_algorithm_substring_search("a",paste(rep("b",513),collapse="")))
expect_error(z_algorithm_substring_search("é","e"))
expect_error(z_algorithm_substring_search("a\tb","a"))
expect_error(z_algorithm_substring_search(NA_character_,"a"))
expect_error(z_algorithm_substring_search(1,"a"))
cat("R Z-algorithm search tests passed\n")
