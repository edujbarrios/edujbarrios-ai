file_arg <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(file_arg)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",file_arg[[1L]])))
source(file.path(folder,"transitive_closure.R"))
expect_error <- function(expr) {
  failed <- tryCatch({force(expr);FALSE},error=function(e) TRUE)
  stopifnot(failed)
}
chain <- matrix(c(0,1,0,0,0,1,0,0,0),nrow=3,byrow=TRUE)
expected <- matrix(c(1L,1L,1L,0L,1L,1L,0L,0L,1L),nrow=3,byrow=TRUE)
stopifnot(identical(transitive_closure(chain),expected))
cycle <- matrix(c(0,1,1,0),nrow=2,byrow=TRUE)
stopifnot(identical(transitive_closure(cycle),matrix(1L,nrow=2,ncol=2)))
empty <- matrix(0,nrow=2,ncol=2)
stopifnot(identical(transitive_closure(empty),diag(1L,2L)))
stopifnot(identical(transitive_closure(matrix(1,nrow=1)),matrix(1L,nrow=1)))
stopifnot(identical(transitive_closure(matrix(0,nrow=1)),matrix(1L,nrow=1)))
expect_error(transitive_closure(matrix(numeric(),nrow=0,ncol=0)))
expect_error(transitive_closure(matrix(0,nrow=2,ncol=3)))
expect_error(transitive_closure(matrix(c(0,2,0,0),nrow=2)))
expect_error(transitive_closure(matrix(c(0,-1,0,0),nrow=2)))
expect_error(transitive_closure(matrix(c(0,NaN,0,0),nrow=2)))
expect_error(transitive_closure(matrix(c(0,0.5,0,0),nrow=2)))
expect_error(transitive_closure(matrix("1",nrow=1)))
cat("R transitive closure tests passed\n")
