args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"positional_phrase_search.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
a<-matrix(c(1,0,1,5,2,1,4,2),ncol=2,byrow=TRUE)
b<-matrix(c(1,1,1,8,2,3,4,3),ncol=2,byrow=TRUE)
empty<-matrix(numeric(),nrow=0,ncol=2)
stopifnot(identical(positional_phrase_search(a,b),c(1L,4L)))
stopifnot(identical(positional_phrase_search(empty,b),integer()))
stopifnot(identical(positional_phrase_search(a,empty),integer()))
stopifnot(identical(positional_phrase_search(matrix(c(5,2),ncol=2),
                                               matrix(c(5,1),ncol=2)),integer()))
stopifnot(identical(positional_phrase_search(matrix(c(1,0,1,4),ncol=2,byrow=TRUE),
                                               matrix(c(1,1,1,5),ncol=2,byrow=TRUE)),c(1L)))
expect_error(positional_phrase_search(matrix(c(1,5,1,0),ncol=2,byrow=TRUE),b))
expect_error(positional_phrase_search(matrix(c(1,0,1,0),ncol=2,byrow=TRUE),b))
expect_error(positional_phrase_search(matrix(c(1,-1),ncol=2),b))
expect_error(positional_phrase_search(matrix(c(1,1.5),ncol=2),b))
expect_error(positional_phrase_search(a,matrix(c(1,1,1,0),ncol=2,byrow=TRUE)))
cat("R positional phrase search tests passed\n")
