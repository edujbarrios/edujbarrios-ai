args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "minhash_signature.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr); FALSE},
                                                 error=function(e) TRUE))
stopifnot(identical(minhash_signature(c(1,2,3), c(1,3), c(0,7)), c(1,10)))
stopifnot(identical(minhash_signature(c(3,1,2,1), c(1,3), c(0,7)), c(1,10)))
stopifnot(identical(minhash_signature(numeric(), c(1,3), c(0,7)),
                    c(65521,65521)))
stopifnot(identical(minhash_signature(65520, 65520, 65520), 0))
stopifnot(identical(minhash_signature(0, 1, 13), 13))
expect_error(minhash_signature(1, numeric(), numeric()))
expect_error(minhash_signature(1, 1, numeric()))
expect_error(minhash_signature(-1, 1, 0))
expect_error(minhash_signature(65521, 1, 0))
expect_error(minhash_signature(1, 0, 0))
expect_error(minhash_signature(1, 65521, 0))
expect_error(minhash_signature(1, 1, 65521))
expect_error(minhash_signature(1.5, 1, 0))
expect_error(minhash_signature(1, 1.5, 0))
cat("R MinHash signature tests passed\n")
