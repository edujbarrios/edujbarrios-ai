args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
folder <- dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"boyer_moore_horspool_search.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
check <- function(t,p,want) stopifnot(identical(boyer_moore_horspool_search(t,p),as.integer(want)))
check("ABAAABCD","ABC",4L)
check("aaaa","aa",0:2)
check("abababa","aba",c(0,2,4))
check("ABCABCABC","ABC",c(0,3,6))
check("mississippi","issi",c(1,4))
check("abc","XYZ",integer(0))
check("abc","ABC",integer(0))
check("ab","abc",integer(0))
check("~a~a","~a",c(0,2))
check("a a a","a ",c(0,2))
check("abc","",0:3)
check("","",0L)
check("","a",integer(0))
check("a","a",0L)
long <- paste(rep("a",512),collapse="")
check(long,"aa",0:510)
check(long,long,0L)
check(long,"",0:512)
expect_error(boyer_moore_horspool_search(paste(rep("a",513),collapse=""),"a"))
expect_error(boyer_moore_horspool_search("a",paste(rep("b",513),collapse="")))
expect_error(boyer_moore_horspool_search("é","e"))
expect_error(boyer_moore_horspool_search("a\tb","a"))
expect_error(boyer_moore_horspool_search(NA_character_,"a"))
expect_error(boyer_moore_horspool_search(1,"a"))
cat("R Horspool search tests passed\n")
