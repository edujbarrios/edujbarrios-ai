args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"astar_shortest_path.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
g<-matrix(c(0,2,5,0,0,0,1,10,0,0,0,2,0,0,0,0),nrow=4,byrow=TRUE)
h<-c(4,3,2,0)
v<-astar_shortest_path(g,h,0,3)
stopifnot(identical(v$distance,5.0),identical(v$path,c(0L,1L,2L,3L)))
v<-astar_shortest_path(g,c(0,0,0,0),0,3)
stopifnot(identical(v$distance,5.0),identical(v$path,c(0L,1L,2L,3L)))
v<-astar_shortest_path(g,h,3,3)
stopifnot(identical(v$distance,0.0),identical(v$path,c(3L)))
unreachable<-matrix(c(0,1,0,0,0,0,0,0,0),nrow=3,byrow=TRUE)
v<-astar_shortest_path(unreachable,c(0,0,0),0,2)
stopifnot(identical(v$distance,-1.0),identical(v$path,integer()))
expect_error(astar_shortest_path(g,c(10,3,2,0),0,3))
expect_error(astar_shortest_path(g,h,0,2))
expect_error(astar_shortest_path(g,h,4,3))
expect_error(astar_shortest_path(matrix(c(0,-1,0,0),nrow=2),c(0,0),0,1))
expect_error(astar_shortest_path(matrix(numeric(),nrow=0,ncol=0),numeric(),0,0))
cat("R A-star shortest-path tests passed\n")
