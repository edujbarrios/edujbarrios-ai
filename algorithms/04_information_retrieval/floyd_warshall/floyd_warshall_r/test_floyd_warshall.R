args<-grep("^--file=",commandArgs(FALSE),value=TRUE)
folder<-dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"floyd_warshall.R"))
expect_error<-function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
w<-matrix(c(0,3,Inf,Inf,0,-2,4,Inf,0),nrow=3,byrow=TRUE)
expected<-matrix(c(0,3,1,2,0,-2,4,7,0),nrow=3,byrow=TRUE)
stopifnot(identical(floyd_warshall(w),expected))
stopifnot(identical(floyd_warshall(matrix(0,nrow=1)),matrix(0,nrow=1)))
disconnected<-matrix(c(0,Inf,Inf,0),nrow=2)
stopifnot(identical(floyd_warshall(disconnected),disconnected))
expect_error(floyd_warshall(matrix(numeric(),nrow=0,ncol=0)))
expect_error(floyd_warshall(matrix(c(0,1),nrow=1)))
expect_error(floyd_warshall(matrix(c(0,-2,-2,0),nrow=2)))
expect_error(floyd_warshall(matrix(c(1,Inf,Inf,0),nrow=2)))
expect_error(floyd_warshall(matrix(c(0,NaN,Inf,0),nrow=2)))
expect_error(floyd_warshall(matrix(c(0,-Inf,Inf,0),nrow=2)))
expect_error(floyd_warshall(matrix(c(0,1000001,Inf,0),nrow=2)))
cat("R Floyd-Warshall tests passed\n")
