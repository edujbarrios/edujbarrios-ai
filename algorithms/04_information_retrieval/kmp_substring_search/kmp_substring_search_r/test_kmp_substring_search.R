args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "kmp_substring_search.R"))
expect_error <- function(expr) stopifnot(tryCatch({ force(expr); FALSE }, error=function(e) TRUE))
stopifnot(identical(kmp_substring_search("aaaa", "aa"), c(0L, 1L, 2L)))
stopifnot(identical(kmp_substring_search("ABABDABACDABABCABAB", "ABABCABAB"), 10L))
stopifnot(identical(kmp_substring_search("abcabc", "abc"), c(0L, 3L)))
stopifnot(identical(kmp_substring_search("abc", "z"), integer(0)))
stopifnot(identical(kmp_substring_search("abc", "ABC"), integer(0)))
stopifnot(identical(kmp_substring_search("abc", ""), 0:3))
stopifnot(identical(kmp_substring_search("", ""), 0L))
stopifnot(identical(kmp_substring_search("", "a"), integer(0)))
stopifnot(identical(kmp_substring_search(paste(rep("a", 512), collapse=""), "aa"), as.integer(0:510)))
expect_error(kmp_substring_search(paste(rep("a", 513), collapse=""), "a"))
expect_error(kmp_substring_search("a", paste(rep("b", 513), collapse="")))
expect_error(kmp_substring_search("a\tb", "a"))
expect_error(kmp_substring_search("é", "e"))
expect_error(kmp_substring_search(NA_character_, "a"))
expect_error(kmp_substring_search(3, "a"))
cat("R KMP tests passed\n")
