args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "character_bigram_jaccard.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
check <- function(a,b,want) {
  stopifnot(abs(character_bigram_jaccard(a,b)-want)<1e-12)
}
check("banana","bandana",0.6)
check("bandana","banana",0.6)
check("aaaa","aa",1)
check("abcd","cdef",0.2)
check("abc","xyz",0)
check("abc","abcd",2/3)
check("AB","ab",0)
check("","",1)
check("a","",1)
check("a","b",1)
check("a","ab",0)
check(paste(rep("a",512),collapse=""),"aa",1)
check(paste(rep("a",512),collapse=""),paste(rep("b",512),collapse=""),0)
check("~!","~!",1)
expect_error(character_bigram_jaccard(paste(rep("a",513),collapse=""),"a"))
expect_error(character_bigram_jaccard("a",paste(rep("b",513),collapse="")))
expect_error(character_bigram_jaccard("é","e"))
expect_error(character_bigram_jaccard("a\tb","a"))
expect_error(character_bigram_jaccard(NA_character_,"a"))
expect_error(character_bigram_jaccard(1,"a"))
cat("R character bigram Jaccard tests passed\n")
