args <- grep("^--file=", commandArgs(FALSE), value = TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "bm25.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr); FALSE}, error = function(e) TRUE))
expected <- log1p(90.5 / 10.5) * 3 * 2.2 / 4.2
stopifnot(abs(bm25(100, 10, 3, 100, 100, 1.2, 0.75) - expected) < 1e-12)
stopifnot(identical(bm25(100, 10, 0, 0, 100), 0.0))
stopifnot(bm25(100, 10, 3, 50, 100) > bm25(100, 10, 3, 200, 100))
expect_error(bm25(0, 0, 0, 0, 100))
expect_error(bm25(100, 101, 1, 10, 100))
expect_error(bm25(100, 10, 11, 10, 100))
expect_error(bm25(100, 10, 1, 10, 0))
expect_error(bm25(100, 10, 1, 10, 100, 1.2, NaN))
cat("R BM25 tests passed\n")
