args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "longest_palindromic_substring.R"))
expect_error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e)TRUE))
check <- function(s,n,start) {
  stopifnot(identical(longest_palindromic_substring(s),
                     list(length=as.integer(n),start=as.integer(start))))
}
check("babad",3,0)
check("cbbd",2,1)
check("aaaa",4,0)
check("abc",1,0)
check("racecar",7,0)
check("abacdfgdcaba",3,0)
check("a b a",5,0)
check("a!a",3,0)
check("abbaxabba",9,0)
check("",0,0)
check("z",1,0)
check(paste(rep("a",512),collapse=""),512,0)
check(paste0(paste(rep("a",256),collapse=""),paste(rep("b",256),collapse="")),256,0)
expect_error(longest_palindromic_substring(paste(rep("a",513),collapse="")))
expect_error(longest_palindromic_substring("é"))
expect_error(longest_palindromic_substring("a\tb"))
expect_error(longest_palindromic_substring("a\nb"))
expect_error(longest_palindromic_substring(NA_character_))
expect_error(longest_palindromic_substring(1))
cat("R longest palindrome tests passed\n")
