file_arg <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(file_arg)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",file_arg[[1L]])))
source(file.path(folder,"clip_contrastive_loss.R"))
expect_error <- function(expr) {
  failed <- tryCatch({force(expr);FALSE},error=function(e) TRUE)
  stopifnot(failed)
}
close <- function(x,y) stopifnot(abs(x-y)<1e-12)
image <- c(1,0,0,1)
close(clip_contrastive_loss(image,image,2,2,1),log1p(exp(-1)))
close(clip_contrastive_loss(image,c(0,1,1,0),2,2,1),log1p(exp(1)))
close(clip_contrastive_loss(c(1,0,1,0),c(1,0,1,0),2,2,1),log(2))
stopifnot(clip_contrastive_loss(image,image,2,2,100)<1e-12)
close(clip_contrastive_loss(c(2,0,0,3),image,2,2,1),log1p(exp(-1)))
expect_error(clip_contrastive_loss(image,image,1,2,1))
expect_error(clip_contrastive_loss(image,image,2,0,1))
expect_error(clip_contrastive_loss(image,image,2,129,1))
expect_error(clip_contrastive_loss(image,image,2,2,0))
expect_error(clip_contrastive_loss(image,image,2,2,101))
expect_error(clip_contrastive_loss(image,c(0,0,0,1),2,2,1))
expect_error(clip_contrastive_loss(image,c(1,0,Inf,1),2,2,1))
expect_error(clip_contrastive_loss(image,c(1,0,1001,1),2,2,1))
expect_error(clip_contrastive_loss(image,c(1,0,1),2,2,1))
cat("R CLIP contrastive loss tests passed\n")
