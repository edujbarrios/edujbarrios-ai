file_arg <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(file_arg)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",file_arg[[1L]])))
source(file.path(folder,"image_text_hard_negatives.R"))
expect_error <- function(expr) {
  failed <- tryCatch({force(expr);FALSE},error=function(e) TRUE)
  stopifnot(failed)
}
id <- c(1,0,0,1)
same <- c(1,0,1,0,1,0)
triple <- c(1,0,0,1,0.6,0.8)
stopifnot(identical(image_text_hard_negatives(id,id,2,2),c(1L,0L,1L,0L)))
stopifnot(identical(image_text_hard_negatives(same,same,3,2),c(1L,0L,0L,1L,0L,0L)))
stopifnot(identical(image_text_hard_negatives(triple,triple,3,2),c(2L,2L,1L,2L,2L,1L)))
stopifnot(identical(image_text_hard_negatives(c(2,0,0,3),id,2,2),c(1L,0L,1L,0L)))
expect_error(image_text_hard_negatives(id,id,1,2))
expect_error(image_text_hard_negatives(id,id,65,2))
expect_error(image_text_hard_negatives(id,id,2,0))
expect_error(image_text_hard_negatives(id,id,2,129))
expect_error(image_text_hard_negatives(id,c(1,0,0,0),2,2))
expect_error(image_text_hard_negatives(id,c(1,0,Inf,1),2,2))
expect_error(image_text_hard_negatives(id,c(1,0,1001,1),2,2))
expect_error(image_text_hard_negatives(id,c(1,0,1),2,2))
cat("R image-text hard negative tests passed\n")
