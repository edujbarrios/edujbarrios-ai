file_arg <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(file_arg)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",file_arg[[1L]])))
source(file.path(folder,"min_p_logit_filter.R"))
expect_error <- function(expr) {
  failed <- tryCatch({force(expr);FALSE},error=function(e) TRUE)
  stopifnot(failed)
}
stopifnot(identical(min_p_logit_filter(c(0,-1,-2),0.3),c(TRUE,TRUE,FALSE)))
stopifnot(identical(min_p_logit_filter(c(5,5,0),1),c(TRUE,TRUE,FALSE)))
stopifnot(identical(min_p_logit_filter(c(-1000,1000),0),c(TRUE,TRUE)))
stopifnot(identical(min_p_logit_filter(c(-1000,1000),0.5),c(FALSE,TRUE)))
stopifnot(identical(min_p_logit_filter(-5,1),TRUE))
expect_error(min_p_logit_filter(numeric(),0))
expect_error(min_p_logit_filter(rep(0,4097),0.5))
expect_error(min_p_logit_filter(0,-0.1))
expect_error(min_p_logit_filter(0,1.1))
expect_error(min_p_logit_filter(0,NA))
expect_error(min_p_logit_filter(0,NaN))
expect_error(min_p_logit_filter(Inf,0.5))
expect_error(min_p_logit_filter(1001,0.5))
cat("R min-p filter tests passed\n")
