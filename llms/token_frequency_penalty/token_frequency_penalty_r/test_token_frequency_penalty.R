file_arg <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(file_arg)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",file_arg[[1L]])))
source(file.path(folder,"token_frequency_penalty.R"))
expect_error <- function(expr) {
  failed <- tryCatch({force(expr);FALSE},error=function(e) TRUE)
  stopifnot(failed)
}
stopifnot(identical(token_frequency_penalty(c(1,2,3),c(0,2,2),0.5),c(0.5,2,2)))
stopifnot(identical(token_frequency_penalty(c(-1,0,1),c(0,0),1),c(-3,0,1)))
stopifnot(identical(token_frequency_penalty(c(1,2,3),numeric(),1),c(1,2,3)))
stopifnot(identical(token_frequency_penalty(c(1,2,3),c(0,2,2),0),c(1,2,3)))
expect_error(token_frequency_penalty(numeric(),numeric(),1))
expect_error(token_frequency_penalty(c(1,2,3),3,1))
expect_error(token_frequency_penalty(c(1,2,3),-1,1))
expect_error(token_frequency_penalty(c(1,2,3),0.5,1))
expect_error(token_frequency_penalty(c(1,2,3),rep(0,4097),1))
expect_error(token_frequency_penalty(c(1,2,3),0,-1))
expect_error(token_frequency_penalty(c(1,2,3),0,6))
expect_error(token_frequency_penalty(c(1,2,3),0,NaN))
expect_error(token_frequency_penalty(c(1,NaN,3),0,1))
expect_error(token_frequency_penalty(1001,numeric(),1))
cat("R frequency penalty tests passed\n")
