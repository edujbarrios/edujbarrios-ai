file_arg <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(file_arg)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",file_arg[[1L]])))
source(file.path(folder,"top_p_logit_filter.R"))
expect_error <- function(expr) {
  failed <- tryCatch({force(expr);FALSE},error=function(e) TRUE)
  stopifnot(failed)
}
stopifnot(identical(top_p_logit_filter(c(0,0,0,0),0.6),c(TRUE,TRUE,TRUE,FALSE)))
stopifnot(identical(top_p_logit_filter(c(0,0,0,0),0.1),c(TRUE,FALSE,FALSE,FALSE)))
stopifnot(identical(top_p_logit_filter(c(0,0,0,0),1),rep(TRUE,4)))
stopifnot(identical(top_p_logit_filter(c(2,1,0),0.5),c(TRUE,FALSE,FALSE)))
stopifnot(identical(top_p_logit_filter(c(2,1,0),0.8),c(TRUE,TRUE,FALSE)))
stopifnot(identical(top_p_logit_filter(c(-1000,1000,0),0.9),c(FALSE,TRUE,FALSE)))
stopifnot(identical(top_p_logit_filter(5,0.3),TRUE))
expect_error(top_p_logit_filter(numeric(),0.5))
expect_error(top_p_logit_filter(rep(0,4097),0.5))
expect_error(top_p_logit_filter(0,0))
expect_error(top_p_logit_filter(0,-0.1))
expect_error(top_p_logit_filter(0,1.1))
expect_error(top_p_logit_filter(0,NaN))
expect_error(top_p_logit_filter(c(Inf),0.5))
expect_error(top_p_logit_filter(c(1001),0.5))
cat("R nucleus filtering tests passed\n")
