file_arg <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(file_arg)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",file_arg[[1L]])))
source(file.path(folder,"temperature_softmax.R"))
expect_error <- function(expr) {
  failed <- tryCatch({force(expr);FALSE},error=function(e) TRUE)
  stopifnot(failed)
}
expected <- exp(1)/(1+exp(1))
stopifnot(abs(temperature_softmax(c(0,2),2)[[2L]]-expected)<1e-12)
stopifnot(abs(temperature_softmax(c(998,1000),2)[[2L]]-expected)<1e-12)
stopifnot(all(abs(temperature_softmax(c(3,3,3),100)-rep(1/3,3))<1e-12))
stopifnot(identical(temperature_softmax(c(-1000,1000),0.01),c(0,1)))
stopifnot(identical(temperature_softmax(5,1),1))
expect_error(temperature_softmax(numeric(),1))
expect_error(temperature_softmax(rep(1,4097),1))
expect_error(temperature_softmax(1,0))
expect_error(temperature_softmax(1,0.001))
expect_error(temperature_softmax(1,101))
expect_error(temperature_softmax(1,NaN))
expect_error(temperature_softmax(Inf,1))
expect_error(temperature_softmax(1001,1))
cat("R temperature softmax tests passed\n")
