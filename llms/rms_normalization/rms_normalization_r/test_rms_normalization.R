args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(args)==0L) stop("run with Rscript")
source(file.path(dirname(normalizePath(sub("^--file=","",args[[1L]]))),"rms_normalization.R"))
bad <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e) TRUE))
actual <- rms_normalization(c(1,1),c(1,2),1)
stopifnot(abs(actual[[1]]-1/sqrt(2))<1e-12)
stopifnot(abs(actual[[2]]-2/sqrt(2))<1e-12)
stopifnot(identical(rms_normalization(c(0,0),c(1,2),1e-8),c(0,0)))
stopifnot(abs(rms_normalization(c(3,4),c(1,1),1e-8)[[1]]-
              3/sqrt(12.5+1e-8))<1e-12)
bad(rms_normalization(numeric(),numeric(),1))
bad(rms_normalization(c(1,1),1,1))
bad(rms_normalization(1,1,0))
bad(rms_normalization(1,1,1e-9))
bad(rms_normalization(1,1,2))
bad(rms_normalization(1,1,NaN))
bad(rms_normalization(c(1,NA),c(1,2),1))
bad(rms_normalization(1,1001,1))
cat("R RMSNorm tests passed\n")
