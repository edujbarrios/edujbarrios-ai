args <- grep("^--file=", commandArgs(FALSE), value = TRUE)
if (length(args) == 0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "greedy_token_selection.R"))
errors <- function(expr) stopifnot(tryCatch({force(expr); FALSE}, error = function(e) TRUE))

stopifnot(identical(greedy_token_selection(c(2, 5, 5, -1)), 1L))
stopifnot(identical(greedy_token_selection(c(-4, -2, -3)), 1L))
stopifnot(identical(greedy_token_selection(c(1, 1, 1)), 0L))
stopifnot(identical(greedy_token_selection(-1e308), 0L))
stopifnot(identical(greedy_token_selection(c(-1e308, 1e308)), 1L))
errors(greedy_token_selection(numeric()))
errors(greedy_token_selection(c(1, NaN)))
errors(greedy_token_selection(Inf))
errors(greedy_token_selection(TRUE))
cat("R greedy token selection tests passed\n")
