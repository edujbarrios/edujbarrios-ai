args <- grep("^--file=", commandArgs(FALSE), value=TRUE)
if(length(args)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=", "", args[[1L]])))
source(file.path(folder, "token_presence_penalty.R"))
error <- function(expr) stopifnot(tryCatch({force(expr); FALSE}, error=function(e) TRUE))
stopifnot(identical(token_presence_penalty(c(1,2,3),c(0,2,2),0.5),c(0.5,2,2.5)))
stopifnot(identical(token_presence_penalty(c(-1,0,1),c(0,0),1),c(-2,0,1)))
stopifnot(identical(token_presence_penalty(c(1,2),numeric(),5),c(1,2)))
stopifnot(identical(token_presence_penalty(c(1,2),0,0),c(1,2)))
error(token_presence_penalty(numeric(),numeric(),1))
error(token_presence_penalty(1,1,1))
error(token_presence_penalty(1,-1,1))
error(token_presence_penalty(1,0,-1))
error(token_presence_penalty(1,0,Inf))
error(token_presence_penalty(1001,numeric(),1))
error(token_presence_penalty(TRUE,numeric(),1))
cat("R presence penalty tests passed\n")
