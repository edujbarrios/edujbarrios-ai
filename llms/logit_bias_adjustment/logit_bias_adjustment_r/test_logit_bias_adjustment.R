args <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if(length(args)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",args[[1L]])))
source(file.path(folder,"logit_bias_adjustment.R"))
error <- function(expr) stopifnot(tryCatch({force(expr);FALSE},error=function(e) TRUE))
stopifnot(identical(logit_bias_adjustment(c(1,2,3),c(0,2),c(-1,0.5)),c(0,2,3.5)))
stopifnot(identical(logit_bias_adjustment(c(-1,0),numeric(),numeric()),c(-1,0)))
stopifnot(identical(logit_bias_adjustment(c(1,2),1,0),c(1,2)))
stopifnot(identical(logit_bias_adjustment(c(-1000,1000),c(0,1),c(-100,100)),c(-1100,1100)))
error(logit_bias_adjustment(numeric(),numeric(),numeric()))
error(logit_bias_adjustment(1,c(0,0),c(1,1)))
error(logit_bias_adjustment(1,1,1))
error(logit_bias_adjustment(1,TRUE,1))
error(logit_bias_adjustment(1,0,Inf))
error(logit_bias_adjustment(1,0,101))
error(logit_bias_adjustment(1001,numeric(),numeric()))
cat("R sparse logit bias tests passed\n")
