file_arg <- grep("^--file=",commandArgs(FALSE),value=TRUE)
if (length(file_arg)==0L) stop("run with Rscript")
folder <- dirname(normalizePath(sub("^--file=","",file_arg[[1L]])))
source(file.path(folder,"no_repeat_ngram.R"))
expect_error <- function(expr) {
  failed <- tryCatch({force(expr);FALSE},error=function(e) TRUE)
  stopifnot(failed)
}
stopifnot(identical(no_repeat_ngram(c(1,2,1),4,1),c(FALSE,TRUE,TRUE,FALSE)))
stopifnot(identical(no_repeat_ngram(c(1,2,1,2),5,2),c(FALSE,TRUE,FALSE,FALSE,FALSE)))
stopifnot(identical(no_repeat_ngram(c(1,2,3,1,2),5,3),c(FALSE,FALSE,FALSE,TRUE,FALSE)))
stopifnot(identical(no_repeat_ngram(c(1,1,1),3,2),c(FALSE,TRUE,FALSE)))
stopifnot(identical(no_repeat_ngram(numeric(),3,1),rep(FALSE,3)))
stopifnot(identical(no_repeat_ngram(c(0,1),3,3),rep(FALSE,3)))
expect_error(no_repeat_ngram(2,2,1))
expect_error(no_repeat_ngram(c(-1),3,1))
expect_error(no_repeat_ngram(c(3),3,1))
expect_error(no_repeat_ngram(c(0.5),3,1))
expect_error(no_repeat_ngram(c(1,NA),3,1))
expect_error(no_repeat_ngram(c(1,2),0,1))
expect_error(no_repeat_ngram(c(1,2),3,0))
expect_error(no_repeat_ngram(c(1,2),3,33))
expect_error(no_repeat_ngram(rep(0,16385),3,1))
cat("R no-repeat n-gram tests passed\n")
